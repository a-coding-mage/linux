// Linux/Comedi headers and "amplc_pc236.h" are supplied by the surrounding
// translation unit/dependency set.

unsafe fn pc236_intr_update(dev: *mut comedi_device, enable: bool) {
    let board = (*dev).board_ptr;
    let devpriv = (*dev).private;
    let mut flags: libc::c_ulong = 0;

    spin_lock_irqsave(&mut (*dev).spinlock, &mut flags);
    (*devpriv).enable_irq = enable;
    if !(*board).intr_update_cb.is_null() {
        ((*board).intr_update_cb)(dev, enable);
    }
    spin_unlock_irqrestore(&mut (*dev).spinlock, flags);
}

/*
 * This function is called when an interrupt occurs to check whether
 * the interrupt has been marked as enabled and was generated by the
 * board.  If so, the function prepares the hardware for the next
 * interrupt.
 * Returns false if the interrupt should be ignored.
 */
unsafe fn pc236_intr_check(dev: *mut comedi_device) -> bool {
    let board = (*dev).board_ptr;
    let devpriv = (*dev).private;
    let mut retval = false;
    let mut flags: libc::c_ulong = 0;

    spin_lock_irqsave(&mut (*dev).spinlock, &mut flags);
    if (*devpriv).enable_irq {
        if !(*board).intr_chk_clr_cb.is_null() {
            retval = ((*board).intr_chk_clr_cb)(dev);
        } else {
            retval = true;
        }
    }
    spin_unlock_irqrestore(&mut (*dev).spinlock, flags);

    retval
}

unsafe fn pc236_intr_insn(
    _dev: *mut comedi_device,
    _s: *mut comedi_subdevice,
    insn: *mut comedi_insn,
    data: *mut libc::c_uint,
) -> libc::c_int {
    *data.add(1) = 0;
    (*insn).n as libc::c_int
}

unsafe fn pc236_intr_cmdtest(
    _dev: *mut comedi_device,
    _s: *mut comedi_subdevice,
    cmd: *mut comedi_cmd,
) -> libc::c_int {
    let mut err: libc::c_int = 0;

    /* Step 1 : check if triggers are trivially valid */
    err |= comedi_check_trigger_src(&mut (*cmd).start_src, TRIG_NOW);
    err |= comedi_check_trigger_src(&mut (*cmd).scan_begin_src, TRIG_EXT);
    err |= comedi_check_trigger_src(&mut (*cmd).convert_src, TRIG_FOLLOW);
    err |= comedi_check_trigger_src(&mut (*cmd).scan_end_src, TRIG_COUNT);
    err |= comedi_check_trigger_src(&mut (*cmd).stop_src, TRIG_NONE);

    if err != 0 {
        return 1;
    }

    /* Step 2a : make sure trigger sources are unique */
    /* Step 2b : and mutually compatible */

    /* Step 3: check it arguments are trivially valid */
    err |= comedi_check_trigger_arg_is(&mut (*cmd).start_arg, 0);
    err |= comedi_check_trigger_arg_is(&mut (*cmd).scan_begin_arg, 0);
    err |= comedi_check_trigger_arg_is(&mut (*cmd).convert_arg, 0);
    err |= comedi_check_trigger_arg_is(&mut (*cmd).scan_end_arg, (*cmd).chanlist_len);
    err |= comedi_check_trigger_arg_is(&mut (*cmd).stop_arg, 0);

    if err != 0 {
        return 3;
    }

    /* Step 4: fix up any arguments */
    /* Step 5: check channel list if it exists */
    0
}

unsafe fn pc236_intr_cmd(_dev: *mut comedi_device, _s: *mut comedi_subdevice) -> libc::c_int {
    pc236_intr_update(_dev, true);
    0
}

unsafe fn pc236_intr_cancel(_dev: *mut comedi_device, _s: *mut comedi_subdevice) -> libc::c_int {
    pc236_intr_update(_dev, false);
    0
}

unsafe extern "C" fn pc236_interrupt(irq: libc::c_int, d: *mut libc::c_void) -> irqreturn_t {
    let dev = d as *mut comedi_device;
    let s = (*dev).read_subdev;
    let handled = pc236_intr_check(dev);
    if (*dev).attached && handled {
        let val: libc::c_ushort = 0;
        comedi_buf_write_samples(s, &val as *const _ as *const libc::c_void, 1);
        comedi_handle_events(dev, s);
    }
    IRQ_RETVAL(handled)
}

pub unsafe fn amplc_pc236_common_attach(
    dev: *mut comedi_device,
    iobase: libc::c_ulong,
    irq: libc::c_uint,
    req_irq_flags: libc::c_ulong,
) -> libc::c_int {
    let mut s: *mut comedi_subdevice;
    let ret: libc::c_int;

    (*dev).iobase = iobase;
    ret = comedi_alloc_subdevices(dev, 2);
    if ret != 0 {
        return ret;
    }

    s = (*dev).subdevices;
    /* digital i/o subdevice (8255) */
    ret = subdev_8255_io_init(dev, s, 0x00);
    if ret != 0 {
        return ret;
    }

    s = (*dev).subdevices.add(1);
    (*dev).read_subdev = s;
    (*s).type_ = COMEDI_SUBD_UNUSED;
    pc236_intr_update(dev, false);
    if irq != 0 {
        if request_irq(irq, Some(pc236_interrupt), req_irq_flags, (*dev).board_name, dev) >= 0 {
            (*dev).irq = irq;
            (*s).type_ = COMEDI_SUBD_DI;
            (*s).subdev_flags = SDF_READABLE | SDF_CMD_READ;
            (*s).n_chan = 1;
            (*s).maxdata = 1;
            (*s).range_table = &range_digital;
            (*s).insn_bits = Some(pc236_intr_insn);
            (*s).len_chanlist = 1;
            (*s).do_cmdtest = Some(pc236_intr_cmdtest);
            (*s).do_cmd = Some(pc236_intr_cmd);
            (*s).cancel = Some(pc236_intr_cancel);
        }
    }

    0
}

