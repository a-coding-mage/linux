// Register-list macros and types are supplied by the corresponding hardware
// headers and are intentionally left as external dependencies.

#[allow(non_camel_case_types)]
extern "C" {
    fn dal_hw_ddc_init(ddc: *mut hw_ddc);
    fn dal_hw_generic_init(generic: *mut hw_generic);
    fn dal_hw_hpd_init(hpd: *mut hw_hpd);
    fn dal_hw_ddc_get_pin(factory: *mut hw_factory, id: u32, index: u32) -> *mut hw_gpio_pin;
    fn dal_hw_hpd_get_pin(factory: *mut hw_factory, id: u32, index: u32) -> *mut hw_gpio_pin;
    fn dal_hw_generic_get_pin(factory: *mut hw_factory, id: u32, index: u32) -> *mut hw_gpio_pin;
}

extern "C" {
    type hw_gpio_pin;
    type hw_ddc;
    type hw_hpd;
    type hw_generic;
    type hw_factory;
    type hw_factory_funcs;
    type hpd_registers;
    type hpd_sh_mask;
    type ddc_registers;
    type ddc_sh_mask;
    type generic_registers;
    type generic_sh_mask;
}

// The following register tables are generated by the C preprocessor macros
// HPD_REG_LIST, DDC_*_REG_LIST, and GENERIC_*_REG_LIST in the hardware headers.
extern "C" {
    static hpd_regs: [hpd_registers; 6];
    static hpd_shift: hpd_sh_mask;
    static hpd_mask: hpd_sh_mask;
    static ddc_data_regs_dcn: [ddc_registers; 7];
    static ddc_clk_regs_dcn: [ddc_registers; 7];
    static ddc_shift: [ddc_sh_mask; 7];
    static ddc_mask: [ddc_sh_mask; 7];
    static generic_regs: [generic_registers; 2];
    static generic_shift: [generic_sh_mask; 2];
    static generic_mask: [generic_sh_mask; 2];
}

unsafe fn define_ddc_registers(pin: *mut hw_gpio_pin, en: u32) {
    let ddc = HW_DDC_FROM_BASE(pin);
    match (*pin).id {
        GPIO_ID_DDC_DATA => {
            (*ddc).regs = &ddc_data_regs_dcn[en as usize];
            (*ddc).base.regs = &ddc_data_regs_dcn[en as usize].gpio;
        }
        GPIO_ID_DDC_CLOCK => {
            (*ddc).regs = &ddc_clk_regs_dcn[en as usize];
            (*ddc).base.regs = &ddc_clk_regs_dcn[en as usize].gpio;
        }
        _ => {
            ASSERT_CRITICAL(false);
            return;
        }
    }
    (*ddc).shifts = &ddc_shift[en as usize];
    (*ddc).masks = &ddc_mask[en as usize];
}

unsafe fn define_hpd_registers(pin: *mut hw_gpio_pin, en: u32) {
    let hpd = HW_HPD_FROM_BASE(pin);
    (*hpd).regs = &hpd_regs[en as usize];
    (*hpd).shifts = &hpd_shift;
    (*hpd).masks = &hpd_mask;
    (*hpd).base.regs = &hpd_regs[en as usize].gpio;
}

unsafe fn define_generic_registers(pin: *mut hw_gpio_pin, en: u32) {
    let generic = HW_GENERIC_FROM_BASE(pin);
    (*generic).regs = &generic_regs[en as usize];
    (*generic).shifts = &generic_shift[en as usize];
    (*generic).masks = &generic_mask[en as usize];
    (*generic).base.regs = &generic_regs[en as usize].gpio;
}

// Function table corresponding to the C designated initializer.  Its concrete
// layout is supplied by hw_factory.h.
static funcs: hw_factory_funcs = hw_factory_funcs {
    init_ddc_data: dal_hw_ddc_init,
    init_generic: dal_hw_generic_init,
    init_hpd: dal_hw_hpd_init,
    get_ddc_pin: dal_hw_ddc_get_pin,
    get_hpd_pin: dal_hw_hpd_get_pin,
    get_generic_pin: dal_hw_generic_get_pin,
    define_hpd_registers,
    define_ddc_registers,
    define_generic_registers,
};

#[no_mangle]
pub unsafe extern "C" fn dal_hw_factory_dcn20_init(factory: *mut hw_factory) {
    // TODO: check ASIC CAPs.
    (*factory).number_of_pins[GPIO_ID_DDC_DATA as usize] = 8;
    (*factory).number_of_pins[GPIO_ID_DDC_CLOCK as usize] = 8;
    (*factory).number_of_pins[GPIO_ID_GENERIC as usize] = 4;
    (*factory).number_of_pins[GPIO_ID_HPD as usize] = 6;
    (*factory).number_of_pins[GPIO_ID_GPIO_PAD as usize] = 28;
    (*factory).number_of_pins[GPIO_ID_VIP_PAD as usize] = 0;
    (*factory).number_of_pins[GPIO_ID_SYNC as usize] = 0;
    (*factory).number_of_pins[GPIO_ID_GSL as usize] = 0; // add this
    (*factory).funcs = &funcs;
}

