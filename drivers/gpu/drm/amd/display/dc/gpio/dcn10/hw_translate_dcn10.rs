unsafe fn offset_to_id(offset: u32, mask: u32, id: *mut gpio_id, en: *mut u32) -> bool {
    if dal_hw_translate_gpio_ddc_offset_to_id(DDC_OFFSET_MAP, DDC_OFFSET_MAP.len(), offset, en) {
        return true;
    }
    if dal_hw_translate_gpio_offset_to_id(GPIO_OFFSETS, GPIO_OFFSETS.len(), offset, mask, id, en) {
        return true;
    }
    ASSERT_CRITICAL!(false);
    false
}

unsafe fn id_to_offset(id: gpio_id, en: u32, info: *mut gpio_pin_info) -> bool {
    if dal_hw_translate_id_to_offset(GPIO_PINS, GPIO_PINS.len(), id, en, info) {
        return true;
    }
    ASSERT_CRITICAL!(false);
    false
}

static FUNCS: hw_translate_funcs = hw_translate_funcs {
    offset_to_id: Some(offset_to_id),
    id_to_offset: Some(id_to_offset),
};

pub unsafe fn dal_hw_translate_dcn10_init(tr: *mut hw_translate) {
    (*tr).funcs = &FUNCS;
}

