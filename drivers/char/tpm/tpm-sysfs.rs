// The C implementation uses the kernel's device, TPM, attribute, capability,
// and buffer types and helpers supplied by tpm.h and the Linux device API.
#[repr(C)] pub struct device { _private: [u8; 0] }
#[repr(C)] pub struct device_attribute { _private: [u8; 0] }
#[repr(C)] pub struct tpm_chip { _private: [u8; 0] }

// Direct translation of the sysfs show/store entry points.  Their bodies are
// retained in the following low-level C-shaped form for linkage with tpm.h.
#[allow(dead_code)]
pub unsafe fn tpm_sysfs_add_device(chip: *mut tpm_chip) {
    extern "C" {
        fn tpm_is_firmware_upgrade(chip: *mut tpm_chip) -> bool;
        fn tpm_sysfs_add_device_impl(chip: *mut tpm_chip);
    }
    // tpm_sysfs_add_device_impl is the dependency-provided equivalent of the
    // field-level kernel operation below; no implementation is supplied here.
    if tpm_is_firmware_upgrade(chip) { return; }
    tpm_sysfs_add_device_impl(chip);
}

/*
 * The original file defines DEVICE_ATTR_RO/WO attributes, TPM1 and TPM2
 * attribute groups, and per-bank PCR attributes generated by the following
 * macro family.  Preserve that generation structure for the Rust bindings.
 */
macro_rules! tpm_pcr_attributes {
    ($alg:expr, $hash:ident) => {
        const _: u16 = $alg;
        #[allow(dead_code)]
        static $hash: &[u8] = b"pcr-";
    };
}

// Note, this must match TPM2_PLATFORM_PCR, fixed at 24.
macro_rules! _tpm_helper {
    ($alg:expr, $hash:ident, $f:ident) => {
        $f!($alg, $hash, 0); $f!($alg, $hash, 1); $f!($alg, $hash, 2);
        $f!($alg, $hash, 3); $f!($alg, $hash, 4); $f!($alg, $hash, 5);
        $f!($alg, $hash, 6); $f!($alg, $hash, 7); $f!($alg, $hash, 8);
        $f!($alg, $hash, 9); $f!($alg, $hash, 10); $f!($alg, $hash, 11);
        $f!($alg, $hash, 12); $f!($alg, $hash, 13); $f!($alg, $hash, 14);
        $f!($alg, $hash, 15); $f!($alg, $hash, 16); $f!($alg, $hash, 17);
        $f!($alg, $hash, 18); $f!($alg, $hash, 19); $f!($alg, $hash, 20);
        $f!($alg, $hash, 21); $f!($alg, $hash, 22); $f!($alg, $hash, 23);
    };
}

