const BOOTLOG_POOL_SIZE: usize = 16;
const BOOTLOG_MSG_SIZE: usize = 512;
const QAIC_DBC_DIR_NAME: usize = 9;

#[repr(C)]
struct BootlogMsg {
    /* Buffer for bootlog messages */
    str_: [core::ffi::c_char; BOOTLOG_MSG_SIZE],
    /* Length of bootlog message */
    len: usize,
    /* Root struct of device, used to access device resources */
    qdev: *mut qaic_device,
    /* Work struct to schedule work coming on QAIC_LOGGING channel */
    work: work_struct,
}

#[repr(C)]
struct BootlogPage {
    /* Node in list of bootlog pages maintained by root device struct */
    node: list_head,
    /* Total size of the buffer that holds the bootlogs. It is PAGE_SIZE */
    size: u32,
    /* Offset for the next bootlog */
    offset: u32,
}

unsafe fn bootlog_show(s: *mut seq_file, _unused: *mut core::ffi::c_void) -> i32 {
    let qdev = (*s).private as *mut qaic_device;
    mutex_lock(&mut (*qdev).bootlog_mutex);
    let mut page: *mut BootlogPage = core::ptr::null_mut();
    let mut pos = (*qdev).bootlog.next;
    while pos != &mut (*qdev).bootlog as *mut list_head {
        page = container_of!(pos, BootlogPage, node);
        let log = page.add(1) as *mut core::ffi::c_void;
        let len = ((*page).offset as usize).wrapping_sub(core::mem::size_of::<BootlogPage>());
        seq_write(s, log, len);
        pos = (*pos).next;
    }
    mutex_unlock(&mut (*qdev).bootlog_mutex);
    0
}

unsafe fn fifo_size_show(s: *mut seq_file, _unused: *mut core::ffi::c_void) -> i32 {
    let dbc = (*s).private as *mut dma_bridge_chan;
    seq_printf(s, "%u\n", (*dbc).nelem);
    0
}

unsafe fn queued_show(s: *mut seq_file, _unused: *mut core::ffi::c_void) -> i32 {
    let dbc = (*s).private as *mut dma_bridge_chan;
    let mut tail: u32 = 0;
    let mut head: u32 = 0;
    qaic_data_get_fifo_info(dbc, &mut head, &mut tail);
    if head == u32::MAX || tail == u32::MAX {
        seq_printf(s, "%u\n", 0);
    } else if head > tail {
        seq_printf(s, "%u\n", (*dbc).nelem.wrapping_sub(head).wrapping_add(tail));
    } else {
        seq_printf(s, "%u\n", tail.wrapping_sub(head));
    }
    0
}

// Equivalent to DEFINE_SHOW_ATTRIBUTE() declarations generated by the kernel macro.
extern "C" {
    static bootlog_fops: file_operations;
    static fifo_size_fops: file_operations;
    static queued_fops: file_operations;
}

pub unsafe fn qaic_debugfs_init(qddev: *mut qaic_drm_device) {
    let qdev = (*qddev).qdev;
    let debugfs_root = (*to_drm(qddev)).debugfs_root;
    debugfs_create_file(c"bootlog".as_ptr(), 0o400, debugfs_root, qdev as *mut _, &bootlog_fops);
    let mut i: u32 = 0;
    while i < (*qdev).num_dbc && i < 256 {
        let mut name = [0 as core::ffi::c_char; QAIC_DBC_DIR_NAME];
        snprintf(name.as_mut_ptr(), QAIC_DBC_DIR_NAME, c"dbc%03u".as_ptr(), i);
        let debugfs_dir = debugfs_create_dir(name.as_ptr(), debugfs_root);
        debugfs_create_file(c"fifo_size".as_ptr(), 0o400, debugfs_dir, &mut (*qdev).dbc[i as usize] as *mut _, &fifo_size_fops);
        debugfs_create_file(c"queued".as_ptr(), 0o400, debugfs_dir, &mut (*qdev).dbc[i as usize] as *mut _, &queued_fops);
        i += 1;
    }
}

unsafe fn alloc_bootlog_page(qdev: *mut qaic_device) -> *mut BootlogPage {
    let page = devm_get_free_pages(&mut (*(*qdev).pdev).dev, GFP_KERNEL, 0) as *mut BootlogPage;
    if page.is_null() { return page; }
    (*page).size = PAGE_SIZE as u32;
    (*page).offset = core::mem::size_of::<BootlogPage>() as u32;
    list_add_tail(&mut (*page).node, &mut (*qdev).bootlog);
    page
}

unsafe fn reset_bootlog(qdev: *mut qaic_device) -> i32 {
    mutex_lock(&mut (*qdev).bootlog_mutex);
    let mut page: *mut BootlogPage = core::ptr::null_mut();
    let mut i: *mut BootlogPage = core::ptr::null_mut();
    list_for_each_entry_safe!(page, i, &mut (*qdev).bootlog, node, {
        list_del(&mut (*page).node);
        devm_free_pages(&mut (*(*qdev).pdev).dev, page as usize);
    });
    page = alloc_bootlog_page(qdev);
    mutex_unlock(&mut (*qdev).bootlog_mutex);
    if page.is_null() { return -ENOMEM; }
    0
}

unsafe fn bootlog_get_space(qdev: *mut qaic_device, size: u32) -> *mut core::ffi::c_void {
    let mut page = list_last_entry!(&mut (*qdev).bootlog, BootlogPage, node);
    if size.checked_add(core::mem::size_of::<BootlogPage>() as u32).unwrap_or(u32::MAX) > (*page).size { return core::ptr::null_mut(); }
    if (*page).offset.wrapping_add(size) > (*page).size {
        page = alloc_bootlog_page(qdev);
        if page.is_null() { return core::ptr::null_mut(); }
    }
    (page as *mut u8).add((*page).offset as usize) as *mut core::ffi::c_void
}

unsafe fn bootlog_commit(qdev: *mut qaic_device, size: u32) {
    let page = list_last_entry!(&mut (*qdev).bootlog, BootlogPage, node);
    (*page).offset = (*page).offset.wrapping_add(size);
}

unsafe extern "C" fn bootlog_log(work: *mut work_struct) {
    let msg = container_of!(work, BootlogMsg, work);
    let qdev = (*msg).qdev;
    mutex_lock(&mut (*qdev).bootlog_mutex);
    let log = bootlog_get_space(qdev, (*msg).len as u32);
    if !log.is_null() {
        memcpy(log, msg as *const _, (*msg).len);
        bootlog_commit(qdev, (*msg).len as u32);
    }
    mutex_unlock(&mut (*qdev).bootlog_mutex);
    if mhi_queue_buf((*qdev).bootlog_ch, DMA_FROM_DEVICE, msg as *mut _, BOOTLOG_MSG_SIZE, MHI_EOT) != 0 {
        devm_kfree(&mut (*(*qdev).pdev).dev, msg as *mut _);
    }
}

unsafe extern "C" fn qaic_bootlog_mhi_probe(mhi_dev: *mut mhi_device, _id: *const mhi_device_id) -> i32 {
    let qdev = pci_get_drvdata(to_pci_dev((*(*mhi_dev).mhi_cntrl).cntrl_dev));
    let mut ret;
    (*qdev).bootlog_wq = alloc_ordered_workqueue(c"qaic_bootlog".as_ptr(), 0);
    if (*qdev).bootlog_wq.is_null() { return -ENOMEM; }
    ret = reset_bootlog(qdev);
    if ret != 0 { destroy_workqueue((*qdev).bootlog_wq); return ret; }
    ret = mhi_prepare_for_transfer(mhi_dev);
    if ret != 0 { destroy_workqueue((*qdev).bootlog_wq); return ret; }
    dev_set_drvdata(&mut (*mhi_dev).dev, qdev as *mut _);
    (*qdev).bootlog_ch = mhi_dev;
    for _ in 0..BOOTLOG_POOL_SIZE {
        let msg = devm_kzalloc(&mut (*(*qdev).pdev).dev, core::mem::size_of::<BootlogMsg>(), GFP_KERNEL) as *mut BootlogMsg;
        if msg.is_null() { ret = -ENOMEM; mhi_unprepare_from_transfer(mhi_dev); destroy_workqueue((*qdev).bootlog_wq); return ret; }
        (*msg).qdev = qdev;
        INIT_WORK!(&mut (*msg).work, bootlog_log);
        ret = mhi_queue_buf(mhi_dev, DMA_FROM_DEVICE, msg as *mut _, BOOTLOG_MSG_SIZE, MHI_EOT);
        if ret != 0 { mhi_unprepare_from_transfer(mhi_dev); destroy_workqueue((*qdev).bootlog_wq); return ret; }
    }
    0
}

unsafe extern "C" fn qaic_bootlog_mhi_remove(mhi_dev: *mut mhi_device) {
    let qdev = dev_get_drvdata(&mut (*mhi_dev).dev) as *mut qaic_device;
    mhi_unprepare_from_transfer((*qdev).bootlog_ch);
    destroy_workqueue((*qdev).bootlog_wq);
    (*qdev).bootlog_ch = core::ptr::null_mut();
}

unsafe extern "C" fn qaic_bootlog_mhi_ul_xfer_cb(_mhi_dev: *mut mhi_device, _mhi_result: *mut mhi_result) {}

unsafe extern "C" fn qaic_bootlog_mhi_dl_xfer_cb(mhi_dev: *mut mhi_device, mhi_result: *mut mhi_result) {
    let qdev = dev_get_drvdata(&mut (*mhi_dev).dev) as *mut qaic_device;
    let msg = (*mhi_result).buf_addr as *mut BootlogMsg;
    let status = (*mhi_result).transaction_status;
    if status != 0 && status != -EOVERFLOW { devm_kfree(&mut (*(*qdev).pdev).dev, msg as *mut _); return; }
    (*msg).len = (*mhi_result).bytes_xferd as usize;
    if (*msg).len != 0 && (*msg).str_[(*msg).len - 1] == 0 { (*msg).len -= 1; }
    queue_work((*qdev).bootlog_wq, &mut (*msg).work);
}

