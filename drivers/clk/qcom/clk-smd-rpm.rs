//! Translation unit for the Qualcomm RPM-over-SMD clock controller.
//! External Linux-kernel declarations and constants are supplied by the
//! surrounding kernel bindings.

// The source uses Linux kernel infrastructure extensively.  These declarations
// intentionally remain external and are not reimplemented in this isolated
// translation unit.
extern "C" {
    static mut rpmcc_smd_rpm: *mut qcom_smd_rpm;
}

#[repr(C)]
pub struct qcom_smd_rpm;

#[repr(C)]
pub struct clk_smd_rpm_req {
    pub key: u32,
    pub nbytes: u32,
    pub value: u32,
}

#[repr(C)]
pub struct clk_smd_rpm {
    pub rpm_res_type: i32,
    pub rpm_key: i32,
    pub rpm_clk_id: i32,
    pub active_only: bool,
    pub enabled: bool,
    pub branch: bool,
    pub peer: *mut clk_smd_rpm,
    pub hw: *mut core::ffi::c_void,
    pub rate: usize,
}

pub unsafe fn to_active_sleep(
    r: *const clk_smd_rpm,
    rate: usize,
    active: *mut usize,
    sleep: *mut usize,
) {
    *active = rate;
    *sleep = if (*r).active_only { 0 } else { *active };
}

