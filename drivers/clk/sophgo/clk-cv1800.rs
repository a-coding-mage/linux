unsafe fn cv18xx_clk_disable_auto_pd(base: *mut u8) {
    let clocks: [u16; 5] = [
        REG_MIPIMPLL_CLK_CSR, REG_A0PLL_CLK_CSR, REG_DISPPLL_CLK_CSR,
        REG_CAM0PLL_CLK_CSR, REG_CAM1PLL_CLK_CSR,
    ];
    for reg in clocks {
        let p = base.add(reg as usize) as *mut u32;
        let mut val = core::ptr::read_volatile(p);
        val |= GENMASK(12, 9);
        val &= !BIT(8);
        core::ptr::write_volatile(p, val);
    }
}

unsafe fn cv18xx_clk_disable_a53(base: *mut u8) {
    let p = base.add(REG_CLK_BYP_0 as usize) as *mut u32;
    let mut val = core::ptr::read_volatile(p);
    val |= BIT(0) | BIT(1) | BIT(2);
    core::ptr::write_volatile(p, val);
}

unsafe extern "C" fn cv1800_pre_init(_dev: *mut c_void, base: *mut c_void,
                                       _ctrl: *mut cv1800_clk_ctrl,
                                       _desc: *const cv1800_clk_desc) -> i32 {
    let p = (base as *mut u8).add(REG_CLK_EN_2 as usize) as *mut u32;
    let mut val = core::ptr::read_volatile(p);
    val &= !BIT(7);
    core::ptr::write_volatile(p, val);
    cv18xx_clk_disable_a53(base as *mut u8);
    cv18xx_clk_disable_auto_pd(base as *mut u8);
    0
}

