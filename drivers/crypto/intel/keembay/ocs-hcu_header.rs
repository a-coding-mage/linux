// Dependency corresponding to <linux/dma-mapping.h>.

pub const OCS_HCU_DMA_BIT_MASK: u64 = (1u64 << 32) - 1;
pub const OCS_HCU_HW_KEY_LEN: usize = 64;

// Forward declaration: struct ocs_hcu_dma_list;
pub enum ocs_hcu_dma_list {}

#[repr(C)]
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum ocs_hcu_algo {
    OCS_HCU_ALGO_SHA256 = 2,
    OCS_HCU_ALGO_SHA224 = 3,
    OCS_HCU_ALGO_SHA384 = 4,
    OCS_HCU_ALGO_SHA512 = 5,
    OCS_HCU_ALGO_SM3 = 6,
}

/**
 * struct ocs_hcu_dev - OCS HCU device context.
 * @list: List of device contexts.
 * @dev: OCS HCU device.
 * @io_base: Base address of OCS HCU registers.
 * @engine: Crypto engine for the device.
 * @irq: IRQ number.
 * @irq_done: Completion for IRQ.
 * @irq_err: Flag indicating an IRQ error has happened.
 */
#[repr(C)]
pub struct ocs_hcu_dev {
    pub list: crate::list_head,
    pub dev: *mut crate::device,
    pub io_base: *mut core::ffi::c_void,
    pub engine: *mut crate::crypto_engine,
    pub irq: core::ffi::c_int,
    pub irq_done: crate::completion,
    pub irq_err: bool,
}

/**
 * struct ocs_hcu_idata - Intermediate data generated by the HCU.
 * @msg_len_lo: Length of data the HCU has operated on in bits, low 32b.
 * @msg_len_hi: Length of data the HCU has operated on in bits, high 32b.
 * @digest: The digest read from the HCU. If the HCU is terminated, it will
 *          contain the actual hash digest. Otherwise it is the intermediate
 *          state.
 */
#[repr(C)]
pub struct ocs_hcu_idata {
    pub msg_len_lo: u32,
    pub msg_len_hi: u32,
    pub digest: [u8; 64],
}

/**
 * struct ocs_hcu_hash_ctx - Context for OCS HCU hashing operation.
 * @algo: The hashing algorithm being used.
 * @idata: The current intermediate data.
 */
#[repr(C)]
pub struct ocs_hcu_hash_ctx {
    pub algo: ocs_hcu_algo,
    pub idata: ocs_hcu_idata,
}

extern "C" {
    pub fn ocs_hcu_irq_handler(
        irq: core::ffi::c_int,
        dev_id: *mut core::ffi::c_void,
    ) -> crate::irqreturn_t;

    pub fn ocs_hcu_dma_list_alloc(
        hcu_dev: *mut ocs_hcu_dev,
        max_nents: core::ffi::c_int,
    ) -> *mut ocs_hcu_dma_list;

    pub fn ocs_hcu_dma_list_free(
        hcu_dev: *mut ocs_hcu_dev,
        dma_list: *mut ocs_hcu_dma_list,
    );

    pub fn ocs_hcu_dma_list_add_tail(
        hcu_dev: *mut ocs_hcu_dev,
        dma_list: *mut ocs_hcu_dma_list,
        addr: crate::dma_addr_t,
        len: u32,
    ) -> core::ffi::c_int;

    pub fn ocs_hcu_hash_init(
        ctx: *mut ocs_hcu_hash_ctx,
        algo: ocs_hcu_algo,
    ) -> core::ffi::c_int;

    pub fn ocs_hcu_hash_update(
        hcu_dev: *mut ocs_hcu_dev,
        ctx: *mut ocs_hcu_hash_ctx,
        dma_list: *const ocs_hcu_dma_list,
    ) -> core::ffi::c_int;

    pub fn ocs_hcu_hash_finup(
        hcu_dev: *mut ocs_hcu_dev,
        ctx: *const ocs_hcu_hash_ctx,
        dma_list: *const ocs_hcu_dma_list,
        dgst: *mut u8,
        dgst_len: usize,
    ) -> core::ffi::c_int;

    pub fn ocs_hcu_hash_final(
        hcu_dev: *mut ocs_hcu_dev,
        ctx: *const ocs_hcu_hash_ctx,
        dgst: *mut u8,
        dgst_len: usize,
    ) -> core::ffi::c_int;

    pub fn ocs_hcu_digest(
        hcu_dev: *mut ocs_hcu_dev,
        algo: ocs_hcu_algo,
        data: *mut core::ffi::c_void,
        data_len: usize,
        dgst: *mut u8,
        dgst_len: usize,
    ) -> core::ffi::c_int;

    pub fn ocs_hcu_hmac(
        hcu_dev: *mut ocs_hcu_dev,
        algo: ocs_hcu_algo,
        key: *const u8,
        key_len: usize,
        dma_list: *const ocs_hcu_dma_list,
        dgst: *mut u8,
        dgst_len: usize,
    ) -> core::ffi::c_int;
}

