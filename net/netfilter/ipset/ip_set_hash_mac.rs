/* Kernel module implementing an IP set type: the hash:mac type */

// Kernel headers and symbols supplied by the surrounding repository are intentionally
// left as external dependencies.

pub const IPSET_TYPE_REV_MIN: u32 = 0;
pub const IPSET_TYPE_REV_MAX: u32 = 1; // bucketsize, initval support

/* Type specific function prefix */

/* Member elements */
#[repr(C)]
pub union HashMac4ElemData {
    pub ether: [u8; ETH_ALEN as usize],
    pub foo: [__be32; 2],
}

#[repr(C)]
pub struct hash_mac4_elem {
    pub data: HashMac4ElemData,
}

/* Common functions */

unsafe fn hash_mac4_data_equal(
    e1: *const hash_mac4_elem,
    e2: *const hash_mac4_elem,
    _multi: *mut u32,
) -> bool {
    ether_addr_equal((*e1).data.ether.as_ptr(), (*e2).data.ether.as_ptr())
}

unsafe fn hash_mac4_data_list(
    skb: *mut sk_buff,
    e: *const hash_mac4_elem,
) -> bool {
    if nla_put(skb, IPSET_ATTR_ETHER, ETH_ALEN, (*e).data.ether.as_ptr()) != 0 {
        return true;
    }
    false
}

unsafe fn hash_mac4_data_next(
    _next: *mut hash_mac4_elem,
    _e: *const hash_mac4_elem,
) {
}

// The following declarations are generated by the C include "ip_set_hash_gen.h".
// Their definitions and dependent types are supplied by the surrounding repository.

unsafe fn hash_mac4_kadt(
    set: *mut ip_set,
    skb: *const sk_buff,
    par: *const xt_action_param,
    adt: ipset_adt,
    opt: *mut ip_set_adt_opt,
) -> i32 {
    let adtfn = (*(*set).variant).adt[adt as usize];
    let mut e = hash_mac4_elem {
        data: HashMac4ElemData { foo: [0, 0] },
    };
    let mut ext = IP_SET_INIT_KEXT(skb, opt, set);

    if (*skb).dev.is_null()
        || (*(*skb).dev).type_ != ARPHRD_ETHER
        || !skb_mac_header_was_set(skb)
        || skb_mac_header_len(skb) < ETH_HLEN
    {
        return -EINVAL;
    }

    if (*opt).flags & IPSET_DIM_ONE_SRC != 0 {
        ether_addr_copy(
            e.data.ether.as_mut_ptr(),
            (*eth_hdr(skb)).h_source.as_ptr(),
        );
    } else {
        ether_addr_copy(
            e.data.ether.as_mut_ptr(),
            (*eth_hdr(skb)).h_dest.as_ptr(),
        );
    }

    if is_zero_ether_addr(e.data.ether.as_ptr()) {
        return -EINVAL;
    }
    adtfn(set, &e, &mut ext, &(*opt).ext, (*opt).cmdflags)
}

unsafe fn hash_mac4_uadt(
    set: *mut ip_set,
    tb: *mut *mut nlattr,
    adt: ipset_adt,
    lineno: *mut u32,
    flags: u32,
    _retried: bool,
) -> i32 {
    let adtfn = (*(*set).variant).adt[adt as usize];
    let mut e = hash_mac4_elem {
        data: HashMac4ElemData { foo: [0, 0] },
    };
    let mut ext = IP_SET_INIT_UEXT(set);
    let mut ret: i32;

    if !(*tb.add(IPSET_ATTR_LINENO as usize)).is_null() {
        *lineno = nla_get_u32(*tb.add(IPSET_ATTR_LINENO as usize));
    }

    if (*tb.add(IPSET_ATTR_ETHER as usize)).is_null()
        || nla_len(*tb.add(IPSET_ATTR_ETHER as usize)) != ETH_ALEN
    {
        return -IPSET_ERR_PROTOCOL;
    }

    ret = ip_set_get_extensions(set, tb, &mut ext);
    if ret != 0 {
        return ret;
    }
    ether_addr_copy(
        e.data.ether.as_mut_ptr(),
        nla_data(*tb.add(IPSET_ATTR_ETHER as usize)),
    );
    if is_zero_ether_addr(e.data.ether.as_ptr()) {
        return -IPSET_ERR_HASH_ELEM;
    }

    adtfn(set, &e, &mut ext, &ext, flags)
}

// C struct ip_set_type hash_mac_type and its generated hash implementation are
// represented by the surrounding Rust bindings; registration follows below.

unsafe fn hash_mac_init() -> i32 {
    ip_set_type_register(&hash_mac_type)
}

unsafe fn hash_mac_fini() {
    rcu_barrier();
    ip_set_type_unregister(&hash_mac_type);
}

