pub unsafe fn hash_ipmac6_uadt(set: *mut ip_set, tb: *mut *mut nlattr, adt: ipset_adt, lineno: *mut u32, flags: u32, _retried: bool) -> i32 {
    let adtfn = (*(*set).variant).adt[adt as usize]; let mut e: hash_ipmac6_elem = core::mem::zeroed(); let mut ext = IP_SET_INIT_UEXT(set);
    if (*tb.add(IPSET_ATTR_IP as usize)).is_null() || (*tb.add(IPSET_ATTR_ETHER as usize)).is_null() || nla_len(*tb.add(IPSET_ATTR_ETHER as usize)) != ETH_ALEN || !ip_set_optattr_netorder(tb, IPSET_ATTR_TIMEOUT) || !ip_set_optattr_netorder(tb, IPSET_ATTR_PACKETS) || !ip_set_optattr_netorder(tb, IPSET_ATTR_BYTES) || !ip_set_optattr_netorder(tb, IPSET_ATTR_SKBMARK) || !ip_set_optattr_netorder(tb, IPSET_ATTR_SKBPRIO) || !ip_set_optattr_netorder(tb, IPSET_ATTR_SKBQUEUE) { return -IPSET_ERR_PROTOCOL; }
    if !(*tb.add(IPSET_ATTR_LINENO as usize)).is_null() { *lineno = nla_get_u32(*tb.add(IPSET_ATTR_LINENO as usize)); }
    let ret = ip_set_get_ipaddr6(*tb.add(IPSET_ATTR_IP as usize), &mut e.ip) || ip_set_get_extensions(set, tb, &mut ext); if ret != 0 { return ret; }
    memcpy(e.ether.ether.as_mut_ptr(), nla_data(*tb.add(IPSET_ATTR_ETHER as usize)), ETH_ALEN); if is_zero_ether_addr(e.ether.ether.as_ptr()) { return -IPSET_ERR_HASH_ELEM; }
    adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags)
}

