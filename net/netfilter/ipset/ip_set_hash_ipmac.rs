/* Kernel module implementing an IP set type: the hash:ip,mac type */

// C kernel headers and the generated ip_set_hash_gen.h implementations are
// supplied by the surrounding translation environment.

pub const IPSET_TYPE_REV_MIN: u32 = 0;
pub const IPSET_TYPE_REV_MAX: u32 = 1; // bucketsize, initval support

// MODULE_LICENSE!("GPL");
// MODULE_AUTHOR!("Tomasz Chilinski <tomasz.chilinski@chilan.com>");
// IP_SET_MODULE_DESC!("hash:ip,mac", IPSET_TYPE_REV_MIN, IPSET_TYPE_REV_MAX);
