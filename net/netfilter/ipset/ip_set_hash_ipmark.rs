/* Kernel module implementing an IP set type: the hash:ip,mark type */

// Kernel and IP-set headers supplied by the surrounding translation unit.

pub const IPSET_TYPE_REV_MIN: u32 = 0;
pub const IPSET_TYPE_REV_MAX: u32 = 3;

// Type specific function prefix: hash_ipmark
// IP_SET_HASH_WITH_MARKMASK

#[repr(C)]
pub struct hash_ipmark4_elem {
    pub ip: __be32,
    pub mark: __u32,
}

unsafe fn hash_ipmark4_data_equal(
    ip1: *const hash_ipmark4_elem,
    ip2: *const hash_ipmark4_elem,
    _multi: *mut u32,
) -> bool {
    (*ip1).ip == (*ip2).ip && (*ip1).mark == (*ip2).mark
}

unsafe fn hash_ipmark4_data_list(
    skb: *mut sk_buff,
    data: *const hash_ipmark4_elem,
) -> bool {
    if nla_put_ipaddr4(skb, IPSET_ATTR_IP, (*data).ip) != 0
        || nla_put_net32(skb, IPSET_ATTR_MARK, htonl((*data).mark)) != 0
    {
        return true;
    }
    false
}

unsafe fn hash_ipmark4_data_next(
    next: *mut hash_ipmark4_elem,
    d: *const hash_ipmark4_elem,
) {
    (*next).ip = (*d).ip;
}

// MTYPE = hash_ipmark4; HOST_MASK = 32
// The declarations generated by ip_set_hash_gen.h are supplied externally.

unsafe fn hash_ipmark4_kadt(
    set: *mut ip_set,
    skb: *const sk_buff,
    _par: *const xt_action_param,
    adt: ipset_adt,
    opt: *mut ip_set_adt_opt,
) -> i32 {
    let h = (*set).data as *const hash_ipmark4;
    let adtfn = (*(*set).variant).adt[adt as usize];
    let mut e: hash_ipmark4_elem = core::mem::zeroed();
    let mut ext: ip_set_ext = IP_SET_INIT_KEXT(skb, opt, set);

    e.mark = (*skb).mark;
    e.mark &= (*h).markmask;
    ip4addrptr(skb, (*opt).flags & IPSET_DIM_ONE_SRC, &mut e.ip);
    adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut (*opt).ext, (*opt).cmdflags)
}

unsafe fn hash_ipmark4_uadt(
    set: *mut ip_set,
    tb: *mut *mut nlattr,
    adt: ipset_adt,
    lineno: *mut u32,
    flags: u32,
    retried: bool,
) -> i32 {
    let h = (*set).data as *mut hash_ipmark4;
    let adtfn = (*(*set).variant).adt[adt as usize];
    let mut e: hash_ipmark4_elem = core::mem::zeroed();
    let mut ext: ip_set_ext = IP_SET_INIT_UEXT(set);
    let mut ip_to: u32 = 0;
    let mut i: u32 = 0;
    let mut ret: i32;

    if !(*tb.add(IPSET_ATTR_LINENO as usize)).is_null() {
        *lineno = nla_get_u32(*tb.add(IPSET_ATTR_LINENO as usize));
    }
    if (*tb.add(IPSET_ATTR_IP as usize)).is_null()
        || !ip_set_attr_netorder(tb, IPSET_ATTR_MARK)
    { return -IPSET_ERR_PROTOCOL; }
    ret = ip_set_get_ipaddr4(*tb.add(IPSET_ATTR_IP as usize), &mut e.ip);
    if ret != 0 { return ret; }
    ret = ip_set_get_extensions(set, tb, &mut ext);
    if ret != 0 { return ret; }
    e.mark = ntohl(nla_get_be32(*tb.add(IPSET_ATTR_MARK as usize)));
    e.mark &= (*h).markmask;
    if e.mark == 0 && e.ip == 0 { return -IPSET_ERR_HASH_ELEM; }
    if adt == IPSET_TEST || ((*tb.add(IPSET_ATTR_IP_TO as usize)).is_null() && (*tb.add(IPSET_ATTR_CIDR as usize)).is_null()) {
        ret = adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags);
        return if ip_set_eexist(ret, flags) { 0 } else { ret };
    }
    let mut ip = ntohl(e.ip); ip_to = ip;
    if !(*tb.add(IPSET_ATTR_IP_TO as usize)).is_null() {
        ret = ip_set_get_hostipaddr4(*tb.add(IPSET_ATTR_IP_TO as usize), &mut ip_to);
        if ret != 0 { return ret; }
        if ip > ip_to { if e.mark == 0 && ip_to == 0 { return -IPSET_ERR_HASH_ELEM; } core::mem::swap(&mut ip, &mut ip_to); }
    } else {
        let cidr = nla_get_u8(*tb.add(IPSET_ATTR_CIDR as usize));
        if cidr == 0 || cidr > 32 { return -IPSET_ERR_INVALID_CIDR; }
        ip_set_mask_from_to(ip, &mut ip_to, cidr);
    }
    if retried { ip = ntohl((*h).next.ip); }
    while ip <= ip_to {
        e.ip = htonl(ip);
        if i > IPSET_MAX_RANGE { hash_ipmark4_data_next(&mut (*h).next, &e); return -ERANGE; }
        ret = adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags);
        if ret != 0 && !ip_set_eexist(ret, flags) { return ret; }
        ret = 0; if ip == ip_to { break; } ip = ip.wrapping_add(1); i = i.wrapping_add(1);
    }
    ret
}

#[repr(C)]
pub struct hash_ipmark6_elem { pub ip: nf_inet_addr, pub mark: __u32 }

unsafe fn hash_ipmark6_data_equal(ip1: *const hash_ipmark6_elem, ip2: *const hash_ipmark6_elem, _multi: *mut u32) -> bool {
    ipv6_addr_equal(&(*ip1).ip.in6, &(*ip2).ip.in6) && (*ip1).mark == (*ip2).mark
}
unsafe fn hash_ipmark6_data_list(skb: *mut sk_buff, data: *const hash_ipmark6_elem) -> bool {
    if nla_put_ipaddr6(skb, IPSET_ATTR_IP, &(*data).ip.in6) != 0 || nla_put_net32(skb, IPSET_ATTR_MARK, htonl((*data).mark)) != 0 { return true; } false
}
unsafe fn hash_ipmark6_data_next(_next: *mut hash_ipmark6_elem, _d: *const hash_ipmark6_elem) {}

// MTYPE = hash_ipmark6; HOST_MASK = 128; IP_SET_EMIT_CREATE
// The declarations generated by ip_set_hash_gen.h are supplied externally.

unsafe fn hash_ipmark6_kadt(set: *mut ip_set, skb: *const sk_buff, _par: *const xt_action_param, adt: ipset_adt, opt: *mut ip_set_adt_opt) -> i32 {
    let h = (*set).data as *const hash_ipmark6; let adtfn = (*(*set).variant).adt[adt as usize]; let mut e: hash_ipmark6_elem = core::mem::zeroed(); let mut ext: ip_set_ext = IP_SET_INIT_KEXT(skb, opt, set);
    e.mark = (*skb).mark & (*h).markmask; ip6addrptr(skb, (*opt).flags & IPSET_DIM_ONE_SRC, &mut e.ip.in6); adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut (*opt).ext, (*opt).cmdflags)
}

unsafe fn hash_ipmark6_uadt(set: *mut ip_set, tb: *mut *mut nlattr, adt: ipset_adt, lineno: *mut u32, flags: u32, _retried: bool) -> i32 {
    let h = (*set).data as *mut hash_ipmark6; let adtfn = (*(*set).variant).adt[adt as usize]; let mut e: hash_ipmark6_elem = core::mem::zeroed(); let mut ext: ip_set_ext = IP_SET_INIT_UEXT(set); let mut ret: i32;
    if !(*tb.add(IPSET_ATTR_LINENO as usize)).is_null() { *lineno = nla_get_u32(*tb.add(IPSET_ATTR_LINENO as usize)); }
    if (*tb.add(IPSET_ATTR_IP as usize)).is_null() || !ip_set_attr_netorder(tb, IPSET_ATTR_MARK) { return -IPSET_ERR_PROTOCOL; }
    if !(*tb.add(IPSET_ATTR_IP_TO as usize)).is_null() { return -IPSET_ERR_HASH_RANGE_UNSUPPORTED; }
    if !(*tb.add(IPSET_ATTR_CIDR as usize)).is_null() && nla_get_u8(*tb.add(IPSET_ATTR_CIDR as usize)) != 128 { return -IPSET_ERR_INVALID_CIDR; }
    ret = ip_set_get_ipaddr6(*tb.add(IPSET_ATTR_IP as usize), &mut e.ip); if ret != 0 { return ret; }
    ret = ip_set_get_extensions(set, tb, &mut ext); if ret != 0 { return ret; }
    e.mark = ntohl(nla_get_be32(*tb.add(IPSET_ATTR_MARK as usize))) & (*h).markmask;
    if adt == IPSET_TEST { ret = adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags); return if ip_set_eexist(ret, flags) { 0 } else { ret }; }
    ret = adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags); if ret != 0 && !ip_set_eexist(ret, flags) { return ret; } 0
}

// struct ip_set_type hash_ipmark_type and module_init/module_exit registration
// retain the source fields and are provided through the surrounding kernel ABI.

unsafe fn hash_ipmark_init() -> i32 { ip_set_type_register(&mut hash_ipmark_type) }
unsafe fn hash_ipmark_fini() { rcu_barrier(); ip_set_type_unregister(&mut hash_ipmark_type); }

