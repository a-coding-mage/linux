/* Kernel module implementing an IP set type: the hash:ip,port,ip type */

// C dependencies supplied by the surrounding kernel/ipset translation.

pub const IPSET_TYPE_REV_MIN: i32 = 0;
pub const IPSET_TYPE_REV_MAX: i32 = 6; // bucketsize, initval support added

/* IPv4 variant */

#[repr(C)]
pub struct hash_ipportip4_elem {
    pub ip: __be32,
    pub ip2: __be32,
    pub port: __be16,
    pub proto: u8,
    pub padding: u8,
}

pub unsafe fn hash_ipportip4_data_equal(
    ip1: *const hash_ipportip4_elem,
    ip2: *const hash_ipportip4_elem,
    _multi: *mut u32,
) -> bool {
    (*ip1).ip == (*ip2).ip
        && (*ip1).ip2 == (*ip2).ip2
        && (*ip1).port == (*ip2).port
        && (*ip1).proto == (*ip2).proto
}

pub unsafe fn hash_ipportip4_data_list(
    skb: *mut sk_buff,
    data: *const hash_ipportip4_elem,
) -> bool {
    if nla_put_ipaddr4(skb, IPSET_ATTR_IP, (*data).ip) != 0
        || nla_put_ipaddr4(skb, IPSET_ATTR_IP2, (*data).ip2) != 0
        || nla_put_net16(skb, IPSET_ATTR_PORT, (*data).port) != 0
        || nla_put_u8(skb, IPSET_ATTR_PROTO, (*data).proto) != 0
    {
        return true;
    }
    false
}

pub unsafe fn hash_ipportip4_data_next(
    next: *mut hash_ipportip4_elem,
    d: *const hash_ipportip4_elem,
) {
    (*next).ip = (*d).ip;
    (*next).port = (*d).port;
}

// Common functions: generated by including ip_set_hash_gen.h with MTYPE=hash_ipportip4 and HOST_MASK=32.

pub unsafe fn hash_ipportip4_kadt(
    set: *mut ip_set,
    skb: *const sk_buff,
    _par: *const xt_action_param,
    adt: ipset_adt,
    opt: *mut ip_set_adt_opt,
) -> i32 {
    let adtfn = (*(*set).variant).adt[adt as usize];
    let mut e: hash_ipportip4_elem = core::mem::zeroed();
    let mut ext = IP_SET_INIT_KEXT(skb, opt, set);
    if !ip_set_get_ip4_port(skb, (*opt).flags & IPSET_DIM_TWO_SRC, &mut e.port, &mut e.proto) {
        return -EINVAL;
    }
    ip4addrptr(skb, (*opt).flags & IPSET_DIM_ONE_SRC, &mut e.ip);
    ip4addrptr(skb, (*opt).flags & IPSET_DIM_THREE_SRC, &mut e.ip2);
    adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut (*opt).ext, (*opt).cmdflags)
}

pub unsafe fn hash_ipportip4_uadt(
    set: *mut ip_set, tb: *mut *mut nlattr, adt: ipset_adt, lineno: *mut u32,
    flags: u32, retried: bool,
) -> i32 {
    let h = (*set).data as *mut hash_ipportip4;
    let adtfn = (*(*set).variant).adt[adt as usize];
    let mut e: hash_ipportip4_elem = core::mem::zeroed();
    let mut ext = IP_SET_INIT_UEXT(set);
    let mut ip_to: u32 = 0; let mut p: u32 = 0; let mut i: u32 = 0;
    let mut port: u32; let mut port_to: u32; let mut ip: u32;
    let mut with_ports = false;
    let mut ret: i32;
    if !(*tb.add(IPSET_ATTR_LINENO as usize)).is_null() { *lineno = nla_get_u32(*tb.add(IPSET_ATTR_LINENO as usize)); }
    if (*tb.add(IPSET_ATTR_IP as usize)).is_null() || (*tb.add(IPSET_ATTR_IP2 as usize)).is_null()
        || !ip_set_attr_netorder(tb, IPSET_ATTR_PORT) || !ip_set_optattr_netorder(tb, IPSET_ATTR_PORT_TO) { return -IPSET_ERR_PROTOCOL; }
    ret = ip_set_get_ipaddr4(*tb.add(IPSET_ATTR_IP as usize), &mut e.ip); if ret != 0 { return ret; }
    ret = ip_set_get_extensions(set, tb, &mut ext); if ret != 0 { return ret; }
    ret = ip_set_get_ipaddr4(*tb.add(IPSET_ATTR_IP2 as usize), &mut e.ip2); if ret != 0 { return ret; }
    e.port = nla_get_be16(*tb.add(IPSET_ATTR_PORT as usize));
    if !(*tb.add(IPSET_ATTR_PROTO as usize)).is_null() { e.proto = nla_get_u8(*tb.add(IPSET_ATTR_PROTO as usize)); with_ports = ip_set_proto_with_ports(e.proto); if e.proto == 0 { return -IPSET_ERR_INVALID_PROTO; } }
    else { return -IPSET_ERR_MISSING_PROTO; }
    if !(with_ports || e.proto as i32 == IPPROTO_ICMP) { e.port = 0; }
    if adt == IPSET_TEST || ((*tb.add(IPSET_ATTR_IP_TO as usize)).is_null() && (*tb.add(IPSET_ATTR_CIDR as usize)).is_null() && (*tb.add(IPSET_ATTR_PORT_TO as usize)).is_null()) {
        ret = adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags); return if ip_set_eexist(ret, flags) { 0 } else { ret };
    }
    ip = ntohl(e.ip); ip_to = ip;
    if !(*tb.add(IPSET_ATTR_IP_TO as usize)).is_null() { ret = ip_set_get_hostipaddr4(*tb.add(IPSET_ATTR_IP_TO as usize), &mut ip_to); if ret != 0 { return ret; } if ip > ip_to { core::mem::swap(&mut ip, &mut ip_to); } }
    else if !(*tb.add(IPSET_ATTR_CIDR as usize)).is_null() { let cidr = nla_get_u8(*tb.add(IPSET_ATTR_CIDR as usize)); if cidr == 0 || cidr > 32 { return -IPSET_ERR_INVALID_CIDR; } ip_set_mask_from_to(&mut ip, &mut ip_to, cidr); }
    port = ntohs(e.port) as u32; port_to = port;
    if with_ports && !(*tb.add(IPSET_ATTR_PORT_TO as usize)).is_null() { port_to = ip_set_get_h16(*tb.add(IPSET_ATTR_PORT_TO as usize)) as u32; if port > port_to { core::mem::swap(&mut port, &mut port_to); } }
    if retried { ip = ntohl((*h).next.ip); }
    while ip <= ip_to { p = if retried && ip == ntohl((*h).next.ip) { ntohs((*h).next.port) as u32 } else { port }; while p <= port_to { e.ip = htonl(ip); e.port = htons(p as u16); i += 1; if i > IPSET_MAX_RANGE { hash_ipportip4_data_next(&mut (*h).next, &e); return -ERANGE; } ret = adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags); if ret != 0 && !ip_set_eexist(ret, flags) { return ret; } ret = 0; p += 1; } if ip == ip_to { break; } ip += 1; }
    ret
}

/* IPv6 variant */
#[repr(C)]
pub struct hash_ipportip6_elem { pub ip: nf_inet_addr, pub ip2: nf_inet_addr, pub port: __be16, pub proto: u8, pub padding: u8 }

pub unsafe fn hash_ipportip6_data_equal(ip1: *const hash_ipportip6_elem, ip2: *const hash_ipportip6_elem, _multi: *mut u32) -> bool { ipv6_addr_equal(&(*ip1).ip.in6, &(*ip2).ip.in6) && ipv6_addr_equal(&(*ip1).ip2.in6, &(*ip2).ip2.in6) && (*ip1).port == (*ip2).port && (*ip1).proto == (*ip2).proto }
pub unsafe fn hash_ipportip6_data_list(skb: *mut sk_buff, data: *const hash_ipportip6_elem) -> bool { nla_put_ipaddr6(skb, IPSET_ATTR_IP, &(*data).ip.in6) != 0 || nla_put_ipaddr6(skb, IPSET_ATTR_IP2, &(*data).ip2.in6) != 0 || nla_put_net16(skb, IPSET_ATTR_PORT, (*data).port) != 0 || nla_put_u8(skb, IPSET_ATTR_PROTO, (*data).proto) != 0 }
pub unsafe fn hash_ipportip6_data_next(next: *mut hash_ipportip6_elem, d: *const hash_ipportip6_elem) { (*next).port = (*d).port; }

// Common functions: generated by including ip_set_hash_gen.h with MTYPE=hash_ipportip6 and HOST_MASK=128, IP_SET_EMIT_CREATE.

pub unsafe fn hash_ipportip6_kadt(set: *mut ip_set, skb: *const sk_buff, _par: *const xt_action_param, adt: ipset_adt, opt: *mut ip_set_adt_opt) -> i32 { let adtfn = (*(*set).variant).adt[adt as usize]; let mut e: hash_ipportip6_elem = core::mem::zeroed(); let mut ext = IP_SET_INIT_KEXT(skb, opt, set); if !ip_set_get_ip6_port(skb, (*opt).flags & IPSET_DIM_TWO_SRC, &mut e.port, &mut e.proto) { return -EINVAL; } ip6addrptr(skb, (*opt).flags & IPSET_DIM_ONE_SRC, &mut e.ip.in6); ip6addrptr(skb, (*opt).flags & IPSET_DIM_THREE_SRC, &mut e.ip2.in6); adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut (*opt).ext, (*opt).cmdflags) }

pub unsafe fn hash_ipportip6_uadt(set: *mut ip_set, tb: *mut *mut nlattr, adt: ipset_adt, lineno: *mut u32, flags: u32, retried: bool) -> i32 {
    let h = (*set).data as *const hash_ipportip6; let adtfn = (*(*set).variant).adt[adt as usize]; let mut e: hash_ipportip6_elem = core::mem::zeroed(); let mut ext = IP_SET_INIT_UEXT(set); let mut with_ports = false; let mut ret;
    if !(*tb.add(IPSET_ATTR_LINENO as usize)).is_null() { *lineno = nla_get_u32(*tb.add(IPSET_ATTR_LINENO as usize)); }
    if (*tb.add(IPSET_ATTR_IP as usize)).is_null() || (*tb.add(IPSET_ATTR_IP2 as usize)).is_null() || !ip_set_attr_netorder(tb, IPSET_ATTR_PORT) || !ip_set_optattr_netorder(tb, IPSET_ATTR_PORT_TO) { return -IPSET_ERR_PROTOCOL; }
    if !(*tb.add(IPSET_ATTR_IP_TO as usize)).is_null() { return -IPSET_ERR_HASH_RANGE_UNSUPPORTED; }
    if !(*tb.add(IPSET_ATTR_CIDR as usize)).is_null() && nla_get_u8(*tb.add(IPSET_ATTR_CIDR as usize)) != 128 { return -IPSET_ERR_INVALID_CIDR; }
    ret = ip_set_get_ipaddr6(*tb.add(IPSET_ATTR_IP as usize), &mut e.ip); if ret != 0 { return ret; } ret = ip_set_get_extensions(set, tb, &mut ext); if ret != 0 { return ret; } ret = ip_set_get_ipaddr6(*tb.add(IPSET_ATTR_IP2 as usize), &mut e.ip2); if ret != 0 { return ret; }
    e.port = nla_get_be16(*tb.add(IPSET_ATTR_PORT as usize));
    if !(*tb.add(IPSET_ATTR_PROTO as usize)).is_null() { e.proto = nla_get_u8(*tb.add(IPSET_ATTR_PROTO as usize)); with_ports = ip_set_proto_with_ports(e.proto); if e.proto == 0 { return -IPSET_ERR_INVALID_PROTO; } } else { return -IPSET_ERR_MISSING_PROTO; }
    if !(with_ports || e.proto as i32 == IPPROTO_ICMPV6) { e.port = 0; }
    if adt == IPSET_TEST || !with_ports || (*tb.add(IPSET_ATTR_PORT_TO as usize)).is_null() { ret = adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags); return if ip_set_eexist(ret, flags) { 0 } else { ret }; }
    let mut port = ntohs(e.port) as u32; let mut port_to = ip_set_get_h16(*tb.add(IPSET_ATTR_PORT_TO as usize)) as u32; if port > port_to { core::mem::swap(&mut port, &mut port_to); } if retried { port = ntohs((*h).next.port) as u32; }
    while port <= port_to { e.port = htons(port as u16); ret = adtfn(set, &mut e as *mut _ as *mut _, &mut ext, &mut ext, flags); if ret != 0 && !ip_set_eexist(ret, flags) { return ret; } ret = 0; port += 1; } ret
}

// The generated hash implementation and type registration below depend on the surrounding kernel bindings.
extern "C" { fn hash_ipportip_create(set: *mut ip_set, tb: *mut *mut nlattr, flags: u32) -> i32; fn ip_set_type_register(t: *mut ip_set_type) -> i32; fn ip_set_type_unregister(t: *mut ip_set_type); fn rcu_barrier(); }

#[no_mangle] pub unsafe extern "C" fn hash_ipportip_init() -> i32 { ip_set_type_register(&mut hash_ipportip_type) }
#[no_mangle] pub unsafe extern "C" fn hash_ipportip_fini() { rcu_barrier(); ip_set_type_unregister(&mut hash_ipportip_type); }

