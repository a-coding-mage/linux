/* Kernel module implementing an IP set type: the hash:ip,port,net type */

// C kernel dependencies are supplied by the surrounding translation unit.

pub const IPSET_TYPE_REV_MIN: u32 = 0;
pub const IPSET_TYPE_REV_MAX: u32 = 8;
pub const HOST_MASK4: u8 = 32;
pub const HOST_MASK6: u8 = 128;

#[repr(C)]
pub struct hash_ipportnet4_elem {
    pub ip: u32,
    pub ip2: u32,
    pub port: u16,
    pub cidr: u8,
    pub nomatch: u8,
    pub proto: u8,
}

pub unsafe fn hash_ipportnet4_data_equal(
    ip1: *const hash_ipportnet4_elem, ip2: *const hash_ipportnet4_elem, _multi: *mut u32,
) -> bool {
    (*ip1).ip == (*ip2).ip && (*ip1).ip2 == (*ip2).ip2 && (*ip1).cidr == (*ip2).cidr
        && (*ip1).port == (*ip2).port && (*ip1).proto == (*ip2).proto
}

pub unsafe fn hash_ipportnet4_do_data_match(elem: *const hash_ipportnet4_elem) -> i32 {
    if (*elem).nomatch != 0 { -ENOTEMPTY } else { 1 }
}

pub unsafe fn hash_ipportnet4_data_set_flags(elem: *mut hash_ipportnet4_elem, flags: u32) {
    (*elem).nomatch = (((flags >> 16) & IPSET_FLAG_NOMATCH) != 0) as u8;
}

pub unsafe fn hash_ipportnet4_data_reset_flags(elem: *mut hash_ipportnet4_elem, flags: *mut u8) {
    core::mem::swap(flags.as_mut().unwrap(), &mut (*elem).nomatch);
}

pub unsafe fn hash_ipportnet4_data_netmask(elem: *mut hash_ipportnet4_elem, cidr: u8) {
    (*elem).ip2 &= ip_set_netmask(cidr);
    (*elem).cidr = cidr.wrapping_sub(1);
}

pub unsafe fn hash_ipportnet4_data_list(skb: *mut sk_buff, data: *const hash_ipportnet4_elem) -> bool {
    let flags = if (*data).nomatch != 0 { IPSET_FLAG_NOMATCH } else { 0 };
    if nla_put_ipaddr4(skb, IPSET_ATTR_IP, (*data).ip) != 0
        || nla_put_ipaddr4(skb, IPSET_ATTR_IP2, (*data).ip2) != 0
        || nla_put_net16(skb, IPSET_ATTR_PORT, (*data).port) != 0
        || nla_put_u8(skb, IPSET_ATTR_CIDR2, (*data).cidr.wrapping_add(1)) != 0
        || nla_put_u8(skb, IPSET_ATTR_PROTO, (*data).proto) != 0
        || (flags != 0 && nla_put_net32(skb, IPSET_ATTR_CADT_FLAGS, htonl(flags)) != 0) { true } else { false }
}

pub unsafe fn hash_ipportnet4_data_next(next: *mut hash_ipportnet4_elem, d: *const hash_ipportnet4_elem) {
    (*next).ip = (*d).ip; (*next).port = (*d).port; (*next).ip2 = (*d).ip2;
}

// The following declarations are generated by ip_set_hash_gen.h in the C source.
// Their implementations and dependent types are supplied externally.
extern "C" {
    pub fn hash_ipportnet4_create(set: *mut ip_set, tb: *mut *mut nlattr, flags: u32) -> i32;
    pub fn hash_ipportnet6_create(set: *mut ip_set, tb: *mut *mut nlattr, flags: u32) -> i32;
}

pub unsafe fn hash_ipportnet4_kadt(set: *mut ip_set, skb: *const sk_buff, par: *const xt_action_param, adt: ipset_adt, opt: *mut ip_set_adt_opt) -> i32 {
    let h = (*set).data as *const hash_ipportnet4;
    let adtfn = (*(*set).variant).adt[adt as usize];
    let mut e = hash_ipportnet4_elem { ip: 0, ip2: 0, port: 0, cidr: INIT_CIDR((*h).rnets[0], HOST_MASK4), nomatch: 0, proto: 0 };
    let mut ext = IP_SET_INIT_KEXT(skb, opt, set);
    if adt == IPSET_TEST { e.cidr = HOST_MASK4 - 1; }
    if !ip_set_get_ip4_port(skb, (*opt).flags & IPSET_DIM_TWO_SRC, &mut e.port, &mut e.proto) { return -EINVAL; }
    ip4addrptr(skb, (*opt).flags & IPSET_DIM_ONE_SRC, &mut e.ip);
    ip4addrptr(skb, (*opt).flags & IPSET_DIM_THREE_SRC, &mut e.ip2);
    e.ip2 &= ip_set_netmask(e.cidr + 1);
    adtfn(set, &mut e as *mut _, &mut ext, &mut (*opt).ext, (*opt).cmdflags)
}

// Full range parsing is retained with the same external helper calls and ordering.
pub unsafe fn hash_ipportnet4_uadt(set: *mut ip_set, tb: *mut *mut nlattr, adt: ipset_adt, lineno: *mut u32, mut flags: u32, retried: bool) -> i32 {
    let h = (*set).data as *mut hash_ipportnet4;
    let adtfn = (*(*set).variant).adt[adt as usize];
    let mut e = hash_ipportnet4_elem { ip: 0, ip2: 0, port: 0, cidr: HOST_MASK4 - 1, nomatch: 0, proto: 0 };
    let mut ext = IP_SET_INIT_UEXT(set);
    let mut ip = 0u32; let mut ip_to = 0u32; let mut p = 0u32; let mut port: u32; let mut port_to: u32;
    let mut ip2_from = 0u32; let mut ip2_to: u32; let mut ip2: u32; let mut i = 0u32; let mut cidr: u8; let mut ret: i32;
    let mut with_ports = false;
    if !(*tb.add(IPSET_ATTR_LINENO)).is_null() { *lineno = nla_get_u32(*tb.add(IPSET_ATTR_LINENO)); }
    if (*tb.add(IPSET_ATTR_IP)).is_null() || (*tb.add(IPSET_ATTR_IP2)).is_null() || !ip_set_attr_netorder(tb, IPSET_ATTR_PORT) || !ip_set_optattr_netorder(tb, IPSET_ATTR_PORT_TO) || !ip_set_optattr_netorder(tb, IPSET_ATTR_CADT_FLAGS) { return -IPSET_ERR_PROTOCOL; }
    ret = ip_set_get_hostipaddr4(*tb.add(IPSET_ATTR_IP), &mut ip); if ret != 0 { return ret; }
    ret = ip_set_get_extensions(set, tb, &mut ext); if ret != 0 { return ret; }
    ret = ip_set_get_hostipaddr4(*tb.add(IPSET_ATTR_IP2), &mut ip2_from); if ret != 0 { return ret; }
    if !(*tb.add(IPSET_ATTR_CIDR2)).is_null() { cidr = nla_get_u8(*tb.add(IPSET_ATTR_CIDR2)); if cidr == 0 || cidr > HOST_MASK4 { return -IPSET_ERR_INVALID_CIDR; } e.cidr = cidr - 1; }
    e.port = nla_get_be16(*tb.add(IPSET_ATTR_PORT));
    if !(*tb.add(IPSET_ATTR_PROTO)).is_null() { e.proto = nla_get_u8(*tb.add(IPSET_ATTR_PROTO)); with_ports = ip_set_proto_with_ports(e.proto); if e.proto == 0 { return -IPSET_ERR_INVALID_PROTO; } } else { return -IPSET_ERR_MISSING_PROTO; }
    if !(with_ports || e.proto == IPPROTO_ICMP) { e.port = 0; }
    if !(*tb.add(IPSET_ATTR_CADT_FLAGS)).is_null() && ip_set_get_h32(*tb.add(IPSET_ATTR_CADT_FLAGS)) & IPSET_FLAG_NOMATCH != 0 { flags |= IPSET_FLAG_NOMATCH << 16; }
    with_ports = with_ports && !(*tb.add(IPSET_ATTR_PORT_TO)).is_null();
    if adt == IPSET_TEST || ((*tb.add(IPSET_ATTR_CIDR)).is_null() && (*tb.add(IPSET_ATTR_IP_TO)).is_null() && !with_ports && (*tb.add(IPSET_ATTR_IP2_TO)).is_null()) { e.ip = htonl(ip); e.ip2 = htonl(ip2_from & ip_set_hostmask(e.cidr + 1)); ret = adtfn(set, &mut e as *mut _, &mut ext, &mut ext, flags); return if ip_set_enomatch(ret, flags, adt, set) { -ret } else if ip_set_eexist(ret, flags) { 0 } else { ret }; }
    ip_to = ip; if !(*tb.add(IPSET_ATTR_IP_TO)).is_null() { ret = ip_set_get_hostipaddr4(*tb.add(IPSET_ATTR_IP_TO), &mut ip_to); if ret != 0 { return ret; } if ip > ip_to { core::mem::swap(&mut ip, &mut ip_to); } } else if !(*tb.add(IPSET_ATTR_CIDR)).is_null() { cidr = nla_get_u8(*tb.add(IPSET_ATTR_CIDR)); if cidr == 0 || cidr > HOST_MASK4 { return -IPSET_ERR_INVALID_CIDR; } ip_set_mask_from_to(ip, ip_to, cidr); }
    port_to = ntohs(e.port) as u32; port = port_to; if !(*tb.add(IPSET_ATTR_PORT_TO)).is_null() { port_to = ip_set_get_h16(*tb.add(IPSET_ATTR_PORT_TO)); if port > port_to { core::mem::swap(&mut port, &mut port_to); } }
    ip2_to = ip2_from; if !(*tb.add(IPSET_ATTR_IP2_TO)).is_null() { ret = ip_set_get_hostipaddr4(*tb.add(IPSET_ATTR_IP2_TO), &mut ip2_to); if ret != 0 { return ret; } if ip2_from > ip2_to { core::mem::swap(&mut ip2_from, &mut ip2_to); } if ip2_from.wrapping_add(u32::MAX) == ip2_to { return -IPSET_ERR_HASH_RANGE; } } else { ip_set_mask_from_to(ip2_from, ip2_to, e.cidr + 1); }
    if retried { ip = ntohl((*h).next.ip); port = ntohs((*h).next.port) as u32; ip2 = ntohl((*h).next.ip2); } else { p = port; ip2 = ip2_from; }
    while ip <= ip_to { e.ip = htonl(ip); while p <= port_to { e.port = htons(p as u16); loop { i += 1; e.ip2 = htonl(ip2); ip2 = ip_set_range_to_cidr(ip2, ip2_to, &mut cidr); e.cidr = cidr - 1; if i > IPSET_MAX_RANGE { hash_ipportnet4_data_next(&mut (*h).next, &e); return -ERANGE; } ret = adtfn(set, &mut e as *mut _, &mut ext, &mut ext, flags); if ret != 0 && !ip_set_eexist(ret, flags) { return ret; } ret = 0; if ip2 >= ip2_to { break; } ip2 += 1; } ip2 = ip2_from; p += 1; } p = port; if ip == ip_to { break; } ip += 1; } ret
}

