pub unsafe fn fcrypt_preparekey(key: *mut FcryptKey, raw_key: *const u8) {
    let mut k: u64 = 0;
    for i in 0..8 { k = (k << 7) | ((*raw_key.add(i) as u64) >> 1); }
    for i in 0..16 { (*key).sched[i] = cpu_to_be32(k as u32); k = (k >> 11) | ((k & ((1u64 << 11) - 1)) << 45); }
}

pub unsafe fn fcrypt_pcbc_encrypt(key: *const FcryptKey, iv: *const u8, src: *const u8, dst: *mut u8, mut nblocks: usize) {
    let mut prev = (iv as *const u64).read_unaligned(); let mut s = src as *const u64; let mut d = dst as *mut u64;
    while nblocks != 0 { let p = s.read_unaligned(); let c = fcrypt_encrypt(key, prev ^ p); d.write_unaligned(c); s=s.add(1); d=d.add(1); prev=p^c; nblocks-=1; }
}

