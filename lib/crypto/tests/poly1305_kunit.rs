// C dependencies: <crypto/poly1305.h>, "poly1305-testvecs.h", and
// "hash-test-template.h" supply the declarations and generated test cases.

extern "C" {
    fn poly1305_init(ctx: *mut poly1305_desc_ctx, key: *const u8);
    fn poly1305_update(ctx: *mut poly1305_desc_ctx, data: *const u8, len: usize);
    fn poly1305_final(ctx: *mut poly1305_desc_ctx, out: *mut u8);
    fn rand_bytes_seeded_from_len(dst: *mut u8, len: usize);
    fn alloc_buf(test: *mut kunit, len: usize) -> *mut u8;
    fn memset(dst: *mut u8, value: i32, len: usize) -> *mut core::ffi::c_void;
    fn kunit_assert_memeq(
        test: *mut kunit,
        actual: *const u8,
        expected: *const u8,
        len: usize,
    );
}

#[repr(C)]
pub struct poly1305_desc_ctx {
    _private: [u8; 0],
}

#[repr(C)]
pub struct kunit {
    _private: [u8; 0],
}

const POLY1305_KEY_SIZE: usize = 32;
const POLY1305_DIGEST_SIZE: usize = 16;
const POLY1305_BLOCK_SIZE: usize = 16;

extern "C" {
    static poly1305_allones_macofmacs: [u8; POLY1305_DIGEST_SIZE];
}

/* A fixed key used when presenting Poly1305 as an unkeyed hash function. */
static mut test_key: [u8; POLY1305_KEY_SIZE] = [0; POLY1305_KEY_SIZE];

/* This probably should be in the actual API, but just define it here for now */
unsafe fn poly1305(
    key: *const u8,
    data: *const u8,
    len: usize,
    out: *mut u8,
) {
    let mut ctx = core::mem::MaybeUninit::<poly1305_desc_ctx>::uninit();
    poly1305_init(ctx.as_mut_ptr(), key);
    poly1305_update(ctx.as_mut_ptr(), data, len);
    poly1305_final(ctx.as_mut_ptr(), out);
}

unsafe fn poly1305_init_withtestkey(ctx: *mut poly1305_desc_ctx) {
    poly1305_init(ctx, test_key.as_ptr());
}

unsafe fn poly1305_withtestkey(data: *const u8, len: usize, out: *mut u8) {
    poly1305(test_key.as_ptr(), data, len, out);
}

// The following declarations are generated by hash-test-template.h in C:
// HASH_KUNIT_CASES, benchmark_hash, and the hash test cases.

unsafe fn poly1305_suite_init(_suite: *mut core::ffi::c_void) -> i32 {
    rand_bytes_seeded_from_len(test_key.as_mut_ptr(), POLY1305_KEY_SIZE);
    0
}

/*
 * Poly1305 test case which uses a key and message consisting only of one bits:
 *
 * - Using an all-one-bits r_key tests the key clamping.
 * - Using an all-one-bits s_key tests carries in implementations of the
 *   addition mod 2**128 during finalization.
 * - Using all-one-bits message, and to a lesser extent r_key, tends to maximize
 *   any intermediate accumulator values.  This increases the chance of
 *   detecting bugs that occur only in rare cases where the accumulator values
 *   get very large, for example the bug fixed by commit 678cce4019d746da
 *   ("crypto: x86/poly1305 - fix overflow during partial reduction").
 *
 * Accumulator overflow bugs may be specific to particular update lengths (in
 * blocks) and/or particular values of the previous acculumator.  Note that
 * the accumulator starts at 0 which gives the lowest chance of an overflow.
 * Thus, a single all-one-bits test vector may be insufficient.
 *
 * Considering that, do the following test: continuously update a single
 * Poly1305 context with all-one-bits data of varying lengths (0, 16, 32, ...,
 * 4096 bytes).  After each update, generate the MAC from the current context,
 * and feed that MAC into a separate Poly1305 context.  Repeat that entire
 * sequence of updates 32 times without re-initializing either context,
 * resulting in a total of 8224 MAC computations from a long-running,
 * cumulative context.  Finally, generate and verify the MAC of all the MACs.
 */
unsafe fn test_poly1305_allones_keys_and_message(test: *mut kunit) {
    let max_len: usize = 4096;
    let data = alloc_buf(test, max_len);
    let mut mac_ctx = core::mem::MaybeUninit::<poly1305_desc_ctx>::uninit();
    let mut macofmacs_ctx = core::mem::MaybeUninit::<poly1305_desc_ctx>::uninit();
    let mut mac = [0u8; POLY1305_DIGEST_SIZE];

    memset(data, 0xff, max_len);
    poly1305_init(mac_ctx.as_mut_ptr(), data);
    poly1305_init(macofmacs_ctx.as_mut_ptr(), data);
    for _i in 0..32 {
        let mut len = 0usize;
        while len <= max_len {
            let mut tmp_ctx = core::mem::MaybeUninit::<poly1305_desc_ctx>::uninit();
            poly1305_update(mac_ctx.as_mut_ptr(), data, len);
            core::ptr::copy_nonoverlapping(
                mac_ctx.as_ptr() as *const u8,
                tmp_ctx.as_mut_ptr() as *mut u8,
                core::mem::size_of::<poly1305_desc_ctx>(),
            );
            poly1305_final(tmp_ctx.as_mut_ptr(), mac.as_mut_ptr());
            poly1305_update(macofmacs_ctx.as_mut_ptr(), mac.as_ptr(), POLY1305_DIGEST_SIZE);
            len += 16;
        }
    }
    poly1305_final(macofmacs_ctx.as_mut_ptr(), mac.as_mut_ptr());
    kunit_assert_memeq(test, mac.as_ptr(), poly1305_allones_macofmacs.as_ptr(), POLY1305_DIGEST_SIZE);
}

/* Poly1305 test case which uses r_key=1, s_key=0, and a 48-byte message. */
unsafe fn test_poly1305_reduction_edge_cases(test: *mut kunit) {
    let key = [1u8; POLY1305_KEY_SIZE];
    let mut data = [0u8; 3 * POLY1305_BLOCK_SIZE];
    let mut expected_mac = [0u8; POLY1305_DIGEST_SIZE];
    let mut actual_mac = [0u8; POLY1305_DIGEST_SIZE];

    for i in 1u8..=10 {
        data[0] = 0u8.wrapping_sub(i);
        memset(data.as_mut_ptr().add(1), 0xff, POLY1305_BLOCK_SIZE - 1);
        if i <= 5 {
            expected_mac[0] = 5 - i;
            memset(expected_mac.as_mut_ptr().add(1), 0, POLY1305_DIGEST_SIZE - 1);
        } else {
            expected_mac[0] = 0u8.wrapping_sub(i);
            memset(expected_mac.as_mut_ptr().add(1), 0xff, POLY1305_DIGEST_SIZE - 1);
        }
        poly1305(key.as_ptr(), data.as_ptr(), data.len(), actual_mac.as_mut_ptr());
        kunit_assert_memeq(test, actual_mac.as_ptr(), expected_mac.as_ptr(), POLY1305_DIGEST_SIZE);
    }
}

