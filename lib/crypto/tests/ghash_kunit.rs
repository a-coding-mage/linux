// Dependencies supplied by the surrounding kernel test environment:
// crypto::gf128hash, ghash-testvecs, and hash-test-template.

static mut TEST_KEY: ghash_key = unsafe { core::mem::zeroed() };

unsafe fn ghash_init_withtestkey(ctx: *mut ghash_ctx) {
    ghash_init(ctx, &raw const TEST_KEY);
}

unsafe fn ghash_withtestkey(data: *const u8, len: usize, out: *mut u8) {
    ghash(&raw const TEST_KEY, data, len, out);
}

// Generate the HASH_KUNIT_CASES using hash-test-template.h.
// HASH = ghash_withtestkey
// HASH_CTX = ghash_ctx
// HASH_SIZE = GHASH_BLOCK_SIZE
// HASH_INIT = ghash_init_withtestkey
// HASH_UPDATE = ghash_update
// HASH_FINAL = ghash_final
// The contents generated by hash-test-template.h are supplied by the build.

unsafe fn test_ghash_allones_key_and_message(test: *mut kunit) {
    let max_len: usize = 4096;
    let data = alloc_buf(test, max_len);
    let mut key: ghash_key = core::mem::zeroed();
    let mut hashofhashes_ctx: ghash_ctx = core::mem::zeroed();
    let mut hash = [0u8; GHASH_BLOCK_SIZE];

    core::ptr::write_bytes(data, 0xff, max_len);

    ghash_preparekey(&raw mut key, data);
    ghash_init(&raw mut hashofhashes_ctx, &raw const key);
    let mut len = 0usize;
    while len <= max_len {
        ghash(&raw const key, data, len, hash.as_mut_ptr());
        ghash_update(
            &raw mut hashofhashes_ctx,
            hash.as_ptr(),
            core::mem::size_of_val(&hash),
        );
        len += 16;
    }
    ghash_final(&raw mut hashofhashes_ctx, hash.as_mut_ptr());
    KUNIT_ASSERT_MEMEQ(
        test,
        hash.as_ptr(),
        ghash_allones_hashofhashes,
        core::mem::size_of_val(&hash),
    );
}

const MAX_LEN_FOR_KEY_CHECK: usize = 1024;

unsafe fn check_key_consistency(
    test: *mut kunit,
    key1: *const ghash_key,
    key2: *const ghash_key,
) {
    let data = alloc_buf(test, MAX_LEN_FOR_KEY_CHECK);
    let mut hash1 = [0u8; GHASH_BLOCK_SIZE];
    let mut hash2 = [0u8; GHASH_BLOCK_SIZE];

    rand_bytes(data, MAX_LEN_FOR_KEY_CHECK);
    KUNIT_ASSERT_MEMEQ(test, key1, key2, core::mem::size_of::<ghash_key>());

    for _ in 0..100 {
        let len = rand_length(MAX_LEN_FOR_KEY_CHECK);
        ghash(key1, data, len, hash1.as_mut_ptr());
        ghash(key2, data, len, hash2.as_mut_ptr());
        KUNIT_ASSERT_MEMEQ(
            test,
            hash1.as_ptr(),
            hash2.as_ptr(),
            core::mem::size_of_val(&hash1),
        );
    }
}

/* Test that ghash_key only needs to be aligned to __alignof__(struct ghash_key). */
unsafe fn test_ghash_with_guarded_key(test: *mut kunit) {
    let mut raw_key = [0u8; GHASH_BLOCK_SIZE];
    let guarded_raw_key = alloc_guarded_buf(test, core::mem::size_of_val(&raw_key));
    let mut key1: ghash_key = core::mem::zeroed();
    let mut key2: ghash_key = core::mem::zeroed();
    let guarded_key = alloc_guarded_buf(test, core::mem::size_of::<ghash_key>()) as *mut ghash_key;

    rand_bytes(raw_key.as_mut_ptr(), core::mem::size_of_val(&raw_key));
    ghash_preparekey(&raw mut key1, raw_key.as_ptr());
    core::ptr::copy_nonoverlapping(raw_key.as_ptr(), guarded_raw_key, raw_key.len());
    ghash_preparekey(&raw mut key2, guarded_raw_key);
    check_key_consistency(test, &raw const key1, &raw const key2);
    ghash_preparekey(guarded_key, raw_key.as_ptr());
    check_key_consistency(test, &raw const key1, guarded_key);
}

unsafe fn test_ghash_with_minimally_aligned_key(test: *mut kunit) {
    let mut raw_key = [0u8; GHASH_BLOCK_SIZE];
    let mut key: ghash_key = core::mem::zeroed();
    let align = core::mem::align_of::<ghash_key>();
    let key_buf = alloc_buf(test, core::mem::size_of::<ghash_key>() + 3 * align) as usize;
    let minaligned_key = (((key_buf + 2 * align - 1) / (2 * align)) * (2 * align) + align)
        as *mut ghash_key;
    KUNIT_ASSERT_TRUE(test, (minaligned_key as usize) % align == 0);
    KUNIT_ASSERT_TRUE(test, (minaligned_key as usize) % (2 * align) != 0);
    rand_bytes(raw_key.as_mut_ptr(), core::mem::size_of_val(&raw_key));
    ghash_preparekey(&raw mut key, raw_key.as_ptr());
    ghash_preparekey(minaligned_key, raw_key.as_ptr());
    check_key_consistency(test, &raw const key, minaligned_key);
}

#[repr(C)]
struct ghash_irq_test_state {
    expected_key: ghash_key,
    raw_key: [u8; GHASH_BLOCK_SIZE],
}

unsafe fn ghash_irq_test_func(state_: *mut core::ffi::c_void) -> bool {
    let state = state_ as *mut ghash_irq_test_state;
    let mut key: ghash_key = core::mem::zeroed();
    ghash_preparekey(&raw mut key, (*state).raw_key.as_ptr());
    core::slice::from_raw_parts((&raw const key) as *const u8, core::mem::size_of::<ghash_key>())
        == core::slice::from_raw_parts((&raw const (*state).expected_key) as *const u8, core::mem::size_of::<ghash_key>())
}

unsafe fn test_ghash_preparekey_in_irqs(test: *mut kunit) {
    let mut state: ghash_irq_test_state = core::mem::zeroed();
    rand_bytes(state.raw_key.as_mut_ptr(), core::mem::size_of_val(&state.raw_key));
    ghash_preparekey(&raw mut state.expected_key, state.raw_key.as_ptr());
    kunit_run_irq_test(test, ghash_irq_test_func, 200000, &raw mut state as *mut _ as *mut core::ffi::c_void);
}

unsafe fn ghash_suite_init(_suite: *mut kunit_suite) -> i32 {
    let mut raw_key = [0u8; GHASH_BLOCK_SIZE];
    rand_bytes_seeded_from_len(raw_key.as_mut_ptr(), core::mem::size_of_val(&raw_key));
    ghash_preparekey(&raw mut TEST_KEY, raw_key.as_ptr());
    0
}

