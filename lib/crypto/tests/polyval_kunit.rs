// C dependencies supplied by the surrounding kernel test environment.
use core::ffi::c_void;

extern "C" {
    static mut test_key: polyval_key;
    fn polyval_init(ctx: *mut polyval_ctx, key: *const polyval_key);
    fn polyval(key: *const polyval_key, data: *const u8, len: usize, out: *mut u8);
    fn polyval_preparekey(key: *mut polyval_key, raw_key: *const u8);
    fn polyval_update(ctx: *mut polyval_ctx, data: *const u8, len: usize);
    fn polyval_final(ctx: *mut polyval_ctx, out: *mut u8);
    fn alloc_buf(test: *mut kunit, len: usize) -> *mut u8;
    fn alloc_guarded_buf(test: *mut kunit, len: usize) -> *mut u8;
    fn rand_bytes(data: *mut u8, len: usize);
    fn rand_length(max_len: usize) -> usize;
    fn rand_bytes_seeded_from_len(data: *mut u8, len: usize);
    fn kunit_run_irq_test(
        test: *mut kunit,
        func: unsafe extern "C" fn(*mut c_void) -> bool,
        iterations: u32,
        state: *mut c_void,
    );
    static polyval_allones_hashofhashes: [u8; POLYVAL_BLOCK_SIZE];
}

#[repr(C)]
pub struct polyval_key { _private: [u8; 0] }
#[repr(C)]
pub struct polyval_ctx { _private: [u8; 0] }
#[repr(C)]
pub struct kunit { _private: [u8; 0] }
#[repr(C)]
pub struct kunit_suite { pub name: *const u8, pub test_cases: *mut kunit_case, pub suite_init: Option<unsafe extern "C" fn(*mut kunit_suite) -> i32> }
#[repr(C)]
pub struct kunit_case { _private: [u8; 0] }

pub const POLYVAL_BLOCK_SIZE: usize = 16;
const MAX_LEN_FOR_KEY_CHECK: usize = 1024;

unsafe extern "C" fn polyval_init_withtestkey(ctx: *mut polyval_ctx) {
    polyval_init(ctx, &raw const test_key);
}

unsafe extern "C" fn polyval_withtestkey(data: *const u8, len: usize, out: *mut u8) {
    polyval(&raw const test_key, data, len, out);
}

// The HASH_KUNIT_CASES are generated by hash-test-template.h in the C source.

unsafe extern "C" fn test_polyval_rfc8452_testvec(test: *mut kunit) {
    let raw_key: [u8; POLYVAL_BLOCK_SIZE] = *b"\x31\x07\x28\xd9\x91\x1f\x1f\x38\x37\xb2\x43\x16\xc3\xfa\xb9\xa0";
    let data: [u8; 48] = *b"example\0\0\0\0\0\0\0\0Hello world\0\0\0\0\0\x38\0\0\0\0\0\0\0\x58\0\0\0\0\0\0\0";
    let expected_hash: [u8; POLYVAL_BLOCK_SIZE] = *b"\xad\x7f\xcf\x0b\x51\x69\x85\x16\x62\x67\x2f\x3c\x5f\x95\x13\x8f";
    let mut hash = [0u8; POLYVAL_BLOCK_SIZE];
    let mut key = polyval_key { _private: [] };
    polyval_preparekey(&mut key, raw_key.as_ptr());
    polyval(&key, data.as_ptr(), data.len(), hash.as_mut_ptr());
    assert_eq!(&hash[..], &expected_hash[..]);
    let _ = test;
}

unsafe extern "C" fn test_polyval_allones_key_and_message(test: *mut kunit) {
    let max_len = 4096usize;
    let data = alloc_buf(test, max_len);
    let mut key = polyval_key { _private: [] };
    let mut ctx = polyval_ctx { _private: [] };
    let mut hash = [0u8; POLYVAL_BLOCK_SIZE];
    core::ptr::write_bytes(data, 0xff, max_len);
    polyval_preparekey(&mut key, data);
    polyval_init(&mut ctx, &key);
    let mut len = 0;
    while len <= max_len {
        polyval(&key, data, len, hash.as_mut_ptr());
        polyval_update(&mut ctx, hash.as_ptr(), hash.len());
        len += 16;
    }
    polyval_final(&mut ctx, hash.as_mut_ptr());
    assert_eq!(&hash[..], &polyval_allones_hashofhashes[..]);
}

unsafe extern "C" fn check_key_consistency(test: *mut kunit, key1: *const polyval_key, key2: *const polyval_key) {
    let data = alloc_buf(test, MAX_LEN_FOR_KEY_CHECK);
    let mut hash1 = [0u8; POLYVAL_BLOCK_SIZE];
    let mut hash2 = [0u8; POLYVAL_BLOCK_SIZE];
    rand_bytes(data, MAX_LEN_FOR_KEY_CHECK);
    assert_eq!(core::slice::from_raw_parts(key1 as *const u8, core::mem::size_of::<polyval_key>()), core::slice::from_raw_parts(key2 as *const u8, core::mem::size_of::<polyval_key>()));
    for _ in 0..100 { let len = rand_length(MAX_LEN_FOR_KEY_CHECK); polyval(key1, data, len, hash1.as_mut_ptr()); polyval(key2, data, len, hash2.as_mut_ptr()); assert_eq!(hash1, hash2); }
}

unsafe extern "C" fn test_polyval_with_guarded_key(test: *mut kunit) {
    let mut raw_key = [0u8; POLYVAL_BLOCK_SIZE];
    let guarded_raw_key = alloc_guarded_buf(test, raw_key.len());
    let mut key1 = polyval_key { _private: [] }; let mut key2 = polyval_key { _private: [] };
    let guarded_key = alloc_guarded_buf(test, core::mem::size_of::<polyval_key>()) as *mut polyval_key;
    rand_bytes(raw_key.as_mut_ptr(), raw_key.len()); polyval_preparekey(&mut key1, raw_key.as_ptr());
    core::ptr::copy_nonoverlapping(raw_key.as_ptr(), guarded_raw_key, raw_key.len()); polyval_preparekey(&mut key2, guarded_raw_key); check_key_consistency(test, &key1, &key2);
    polyval_preparekey(guarded_key, raw_key.as_ptr()); check_key_consistency(test, &key1, guarded_key);
}

// The remaining KUnit registration and alignment/IRQ helpers retain their C ABI intent.
// They depend on kernel-provided allocation, alignment, assertion, and registration macros.

unsafe extern "C" fn test_polyval_with_minimally_aligned_key(test: *mut kunit) {
    let mut raw_key = [0u8; POLYVAL_BLOCK_SIZE];
    let mut key = polyval_key { _private: [] };
    let align = core::mem::align_of::<polyval_key>();
    let key_buf = alloc_buf(test, core::mem::size_of::<polyval_key>() + 3 * align);
    let minaligned_key = (((key_buf as usize) & !(2 * align - 1)) + align) as *mut polyval_key;
    assert_eq!((minaligned_key as usize) % align, 0);
    assert_ne!((minaligned_key as usize) % (2 * align), 0);
    rand_bytes(raw_key.as_mut_ptr(), raw_key.len());
    polyval_preparekey(&mut key, raw_key.as_ptr());
    polyval_preparekey(minaligned_key, raw_key.as_ptr());
    check_key_consistency(test, &key, minaligned_key);
}

#[repr(C)]
pub struct polyval_irq_test_state { pub expected_key: polyval_key, pub raw_key: [u8; POLYVAL_BLOCK_SIZE] }

unsafe extern "C" fn polyval_irq_test_func(state_: *mut c_void) -> bool {
    let state = state_ as *mut polyval_irq_test_state;
    let mut key = polyval_key { _private: [] };
    polyval_preparekey(&mut key, (*state).raw_key.as_ptr());
    core::slice::from_raw_parts(&key as *const _ as *const u8, core::mem::size_of::<polyval_key>()) ==
        core::slice::from_raw_parts(&(*state).expected_key as *const _ as *const u8, core::mem::size_of::<polyval_key>())
}

unsafe extern "C" fn test_polyval_preparekey_in_irqs(test: *mut kunit) {
    let mut state = polyval_irq_test_state { expected_key: polyval_key { _private: [] }, raw_key: [0; POLYVAL_BLOCK_SIZE] };
    rand_bytes(state.raw_key.as_mut_ptr(), state.raw_key.len());
    polyval_preparekey(&mut state.expected_key, state.raw_key.as_ptr());
    kunit_run_irq_test(test, polyval_irq_test_func, 200000, &mut state as *mut _ as *mut c_void);
}

unsafe extern "C" fn polyval_suite_init(_suite: *mut kunit_suite) -> i32 {
    let mut raw_key = [0u8; POLYVAL_BLOCK_SIZE];
    rand_bytes_seeded_from_len(raw_key.as_mut_ptr(), raw_key.len());
    polyval_preparekey(&raw mut test_key, raw_key.as_ptr());
    0
}

