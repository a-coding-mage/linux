/*
 * Process one cache line (64 bytes) per loop. This is assuming all future
 * popular LoongArch cores are similar performance-characteristics-wise to the
 * current models.
 */
const LINE_WIDTH: usize = 64;

// The C source conditionally includes xor_template.c after defining the
// architecture-specific load, store, xor, and function-name macros. The
// template is an external dependency and is intentionally not reproduced
// here.

#[cfg(CONFIG_CPU_HAS_LSX)]
mod lsx {
    // C macros:
    // LD(reg, base, offset)  -> vld $vr{reg}, %[base], {offset}
    // ST(reg, base, offset)  -> vst $vr{reg}, %[base], {offset}
    // XOR(dj, k)             -> vxor.v $vr{dj}, $vr{dj}, $vr{k}
    //
    // LD_INOUT_LINE(base):
    //   LD(0, base, 0), LD(1, base, 16), LD(2, base, 32), LD(3, base, 48)
    // LD_AND_XOR_LINE(base):
    //   LD(4, base, 0), LD(5, base, 16), LD(6, base, 32), LD(7, base, 48),
    //   XOR(0, 4), XOR(1, 5), XOR(2, 6), XOR(3, 7)
    // ST_LINE(base):
    //   ST(0, base, 0), ST(1, base, 16), ST(2, base, 32), ST(3, base, 48)
    // XOR_FUNC_NAME(nr) -> __xor_lsx_##nr
    //
    // Equivalent code is generated by the external xor_template.c dependency.
}

#[cfg(CONFIG_CPU_HAS_LASX)]
mod lasx {
    // C macros:
    // LD(reg, base, offset)  -> xvld $xr{reg}, %[base], {offset}
    // ST(reg, base, offset)  -> xvst $xr{reg}, %[base], {offset}
    // XOR(dj, k)             -> xvxor.v $xr{dj}, $xr{dj}, $xr{k}
    //
    // LD_INOUT_LINE(base):
    //   LD(0, base, 0), LD(1, base, 32)
    // LD_AND_XOR_LINE(base):
    //   LD(2, base, 0), LD(3, base, 32), XOR(0, 2), XOR(1, 3)
    // ST_LINE(base):
    //   ST(0, base, 0), ST(1, base, 32)
    // XOR_FUNC_NAME(nr) -> __xor_lasx_##nr
    //
    // Equivalent code is generated by the external xor_template.c dependency.
}

