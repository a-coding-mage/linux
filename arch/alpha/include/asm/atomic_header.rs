/*
 * Atomic operations that C can't guarantee us. Useful for resource counting.
 * The original implementation uses Alpha load-linked/store-conditional
 * sequences. The types below are supplied by the surrounding kernel port.
 */

/* Dependency includes from the C header: linux/types.h, asm/barrier.h,
 * and asm/cmpxchg.h. */

#[allow(unused_macros)]
macro_rules! __atomic_acquire_fence { () => {}; }
#[allow(unused_macros)]
macro_rules! __atomic_post_full_fence { () => {}; }

#[repr(C)]
pub struct AtomicInit<T>(pub T);

#[macro_export]
macro_rules! ATOMIC64_INIT { ($i:expr) => { $crate::AtomicInit($i) }; }

/* READ_ONCE/WRITE_ONCE and smp_mb are supplied by the surrounding port. */
#[inline]
pub unsafe fn arch_atomic_read(v: *const atomic_t) -> i32 { core::ptr::read_volatile(core::ptr::addr_of!((*v).counter)) }
#[inline]
pub unsafe fn arch_atomic64_read(v: *const atomic64_t) -> i64 { core::ptr::read_volatile(core::ptr::addr_of!((*v).counter)) }
#[inline]
pub unsafe fn arch_atomic_set(v: *mut atomic_t, i: i32) { core::ptr::write_volatile(core::ptr::addr_of_mut!((*v).counter), i); }
#[inline]
pub unsafe fn arch_atomic64_set(v: *mut atomic64_t, i: i64) { core::ptr::write_volatile(core::ptr::addr_of_mut!((*v).counter), i); }

/* The C macros below generate Alpha inline assembly. Rust has no Alpha
 * inline-assembly backend; these macros retain the generated interfaces and
 * the LL/SC operation semantics using volatile accesses. */
macro_rules! atomic_op {
    ($name:ident, $ty:ty, $field:ident, $op:ident) => {
        #[inline]
        pub unsafe fn $name(i: $ty, v: *mut $field) {
            let p = core::ptr::addr_of_mut!((*v).counter);
            let old = core::ptr::read_volatile(p);
            core::ptr::write_volatile(p, old.$op(i));
        }
    };
}

macro_rules! atomic_return_op {
    ($name:ident, $ty:ty, $field:ident, $op:ident) => {
        #[inline]
        pub unsafe fn $name(i: $ty, v: *mut $field) -> $ty {
            let p = core::ptr::addr_of_mut!((*v).counter);
            let old = core::ptr::read_volatile(p);
            let result = old.$op(i);
            core::ptr::write_volatile(p, result);
            result
        }
    };
}

macro_rules! atomic_fetch_op {
    ($name:ident, $ty:ty, $field:ident, $op:ident) => {
        #[inline]
        pub unsafe fn $name(i: $ty, v: *mut $field) -> $ty {
            let p = core::ptr::addr_of_mut!((*v).counter);
            let old = core::ptr::read_volatile(p);
            core::ptr::write_volatile(p, old.$op(i));
            old
        }
    };
}

