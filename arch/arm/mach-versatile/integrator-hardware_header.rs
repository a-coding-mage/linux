pub const IO_BASE: u32 = 0xF000_0000;
pub const IO_SIZE: u32 = 0x0B00_0000;
pub const IO_START: u32 = INTEGRATOR_HDR_BASE;

#[inline]
pub const fn IO_ADDRESS(x: u32) -> u32 {
    (x & 0x000F_FFFF) | ((x >> 4) & 0x0FF0_0000) | IO_BASE
}
#[inline]
pub fn __io_address(n: u32) -> *mut core::ffi::c_void {
    IO_ADDRESS(n) as usize as *mut core::ffi::c_void
}

