// Kernel and architecture declarations supplied by the surrounding translation unit.

#[repr(C)]
pub struct pt_regs {
    pub ecr: ecr,
}

#[repr(C)]
pub struct ecr {
    pub param: u8,
}

#[repr(C)]
pub struct callee_regs {
    _private: [u8; 0],
}

#[repr(C)]
pub struct task_struct {
    pub thread: thread_struct,
}

#[repr(C)]
pub struct thread_struct {
    pub fault_address: u32,
}

extern "C" {
    fn show_kernel_fault_diag(str_: *const core::ffi::c_char, regs: *mut pt_regs, address: usize);
    fn user_mode(regs: *mut pt_regs) -> bool;
    static mut current: *mut task_struct;
    fn force_sig_fault(signo: i32, si_code: i32, addr: *mut core::ffi::c_void);
    fn fixup_exception(regs: *mut pt_regs) -> i32;
    fn misaligned_fixup(address: usize, regs: *mut pt_regs, cregs: *mut callee_regs) -> i32;
    fn trap_is_kprobe(address: usize, regs: *mut pt_regs) -> i32;
    fn kgdb_trap(regs: *mut pt_regs);
    fn notify_die(name: i32, str_: *const core::ffi::c_char, regs: *mut pt_regs,
                  address: usize, trapno: i32, signo: i32) -> i32;
}

pub unsafe fn die(str_: *const core::ffi::c_char, regs: *mut pt_regs, address: usize) {
    show_kernel_fault_diag(str_, regs, address);

    /* DEAD END */
    core::arch::asm!("flag 1");
}

/*
 * Helper called for bulk of exceptions NOT needing specific handling
 *  -for user faults enqueues requested signal
 *  -for kernel, chk if due to copy_(to|from)_user, otherwise die()
 */
#[inline(never)]
unsafe fn unhandled_exception(
    str_: *const core::ffi::c_char,
    regs: *mut pt_regs,
    signo: i32,
    si_code: i32,
    addr: *mut core::ffi::c_void,
) -> i32 {
    if user_mode(regs) {
        let tsk = current;

        (*tsk).thread.fault_address = addr as u32;
        force_sig_fault(signo, si_code, addr);
    } else {
        /* If not due to copy_(to|from)_user, we are doomed */
        if fixup_exception(regs) != 0 {
            return 0;
        }

        die(str_, regs, addr as usize);
    }

    1
}

pub unsafe fn do_privilege_fault(address: usize, regs: *mut pt_regs) -> i32 {
    unhandled_exception(c"Priv Op/Disabled Extn".as_ptr(), regs, 4, 5, address as *mut _)
}

pub unsafe fn do_extension_fault(address: usize, regs: *mut pt_regs) -> i32 {
    unhandled_exception(c"Invalid Extn Insn".as_ptr(), regs, 4, 1, address as *mut _)
}

pub unsafe fn insterror_is_error(address: usize, regs: *mut pt_regs) -> i32 {
    unhandled_exception(c"Illegal Insn (or Seq)".as_ptr(), regs, 4, 1, address as *mut _)
}

pub unsafe fn do_memory_error(address: usize, regs: *mut pt_regs) -> i32 {
    unhandled_exception(c"Invalid Mem Access".as_ptr(), regs, 7, 2, address as *mut _)
}

pub unsafe fn trap_is_brkpt(address: usize, regs: *mut pt_regs) -> i32 {
    unhandled_exception(c"Breakpoint Set".as_ptr(), regs, 5, 1, address as *mut _)
}

pub unsafe fn do_misaligned_error(address: usize, regs: *mut pt_regs) -> i32 {
    unhandled_exception(c"Misaligned Access".as_ptr(), regs, 7, 1, address as *mut _)
}

pub unsafe fn do_trap5_error(address: usize, regs: *mut pt_regs) -> i32 {
    unhandled_exception(c"gcc generated __builtin_trap".as_ptr(), regs, 11, 0, address as *mut _)
}

/*
 * Entry Point for Misaligned Data access Exception, for emulating in software
 */
pub unsafe fn do_misaligned_access(address: usize, regs: *mut pt_regs, cregs: *mut callee_regs) -> i32 {
    /* If emulation not enabled, or failed, kill the task */
    if misaligned_fixup(address, regs, cregs) != 0 {
        return do_misaligned_error(address, regs);
    }

    0
}

/*
 * Entry point for miscll errors such as Nested Exceptions
 *  -Duplicate TLB entry is handled separately though
 */
pub unsafe fn do_machine_check_fault(address: usize, regs: *mut pt_regs) {
    die(c"Unhandled Machine Check Exception".as_ptr(), regs, address);
}

/* Entry point for traps induced by ARCompact TRAP_S <n> insn */
pub unsafe fn do_non_swi_trap(address: usize, regs: *mut pt_regs) {
    match (*regs).ecr.param {
        1 => { trap_is_brkpt(address, regs); }
        2 => { trap_is_kprobe(address, regs); }
        3 | 4 => { kgdb_trap(regs); }
        5 => { do_trap5_error(address, regs); }
        _ => {}
    }
}

pub unsafe fn do_insterror_or_kprobe(address: usize, regs: *mut pt_regs) {
    /* Check if this exception is caused by kprobes */
    let rc = notify_die(1, c"kprobe_ierr".as_ptr(), regs, address, 0, 4);
    if rc == 0 {
        return;
    }

    insterror_is_error(address, regs);
}

/* abort() call generated by older gcc for __builtin_trap() */
pub unsafe fn abort() {
    core::arch::asm!("trap_s  5");
}

