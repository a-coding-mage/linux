#[inline]
pub unsafe fn arch_atomic_fetch_add_relaxed(i: i32, v: *mut atomic_t) -> i32 {
    atomic_fetch_op(i, v, "add") as i32
}

#[inline]
pub unsafe fn arch_atomic_fetch_sub_relaxed(i: i32, v: *mut atomic_t) -> i32 {
    atomic_fetch_op(i, v, "sub") as i32
}

#[inline]
unsafe fn atomic_fetch_op(i: i32, v: *mut atomic_t, op: &str) -> u32 {
    let ctr = core::ptr::addr_of_mut!((*v).counter);
    let mut val: u32;
    let mut orig: u32;
    // The operation string is selected only from the source-level wrappers
    // above; the architecture instruction sequence mirrors ATOMIC_FETCH_OP.
    match op {
        "add" => core::arch::asm!(
            "1:", "llock {orig}, [{ctr}]", "add {val}, {orig}, {i}",
            "scond {val}, [{ctr}]", "bnz 1b",
            val = lateout(reg) val, orig = lateout(reg) orig,
            ctr = in(reg) ctr, i = in(reg) i, options(nostack)),
        "sub" => core::arch::asm!(
            "1:", "llock {orig}, [{ctr}]", "sub {val}, {orig}, {i}",
            "scond {val}, [{ctr}]", "bnz 1b",
            val = lateout(reg) val, orig = lateout(reg) orig,
            ctr = in(reg) ctr, i = in(reg) i, options(nostack)),
        _ => unreachable!(),
    }
    orig
}

