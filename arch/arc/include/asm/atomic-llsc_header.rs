// The C header's include guard and architecture-specific build context are
// intentionally omitted.  `atomic_t` is supplied by the surrounding kernel
// bindings and is expected to expose a `counter` field.

#[inline]
pub unsafe fn arch_atomic_set(v: *mut atomic_t, i: i32) {
    // Equivalent to WRITE_ONCE(((v)->counter), (i)).
    core::ptr::write_volatile(core::ptr::addr_of_mut!((*v).counter), i);
}

#[inline]
pub unsafe fn arch_atomic_add(i: i32, v: *mut atomic_t) {
    let ctr = core::ptr::addr_of_mut!((*v).counter);
    let mut val: u32;
    core::arch::asm!(
        "1:",
        "llock {val}, [{ctr}]",
        "add {val}, {val}, {i}",
        "scond {val}, [{ctr}]",
        "bnz 1b",
        val = lateout(reg) val,
        ctr = in(reg) ctr,
        i = in(reg) i,
        options(nostack),
    );
}

