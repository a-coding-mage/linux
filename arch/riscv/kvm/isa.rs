pub unsafe fn kvm_riscv_base2isa_ext(base_ext: c_ulong) -> c_ulong {
    let mut i: c_ulong = 0;
    while i < KVM_RISCV_ISA_EXT_MAX {
        if KVM_ISA_EXT_ARR[i as usize] == base_ext { return i; }
        i += 1;
    }
    KVM_RISCV_ISA_EXT_MAX
}

pub unsafe fn __kvm_riscv_isa_check_host(kvm_ext: c_ulong, base_ext: *mut c_ulong) -> c_int {
    if kvm_ext >= KVM_RISCV_ISA_EXT_MAX || kvm_ext >= KVM_ISA_EXT_ARR.len() as c_ulong {
        return -ENOENT;
    }
    let index = array_index_nospec(kvm_ext, KVM_ISA_EXT_ARR.len() as c_ulong) as usize;
    let host_ext = if KVM_ISA_EXT_ARR[index] == RISCV_ISA_EXT_SMNPM {
        RISCV_ISA_EXT_SSNPM
    } else {
        KVM_ISA_EXT_ARR[index]
    };
    if !__riscv_isa_extension_available(core::ptr::null_mut(), host_ext) { return -ENOENT; }
    if !base_ext.is_null() { *base_ext = KVM_ISA_EXT_ARR[index]; }
    0
}

pub unsafe fn kvm_riscv_isa_enable_allowed(ext: c_ulong) -> bool {
    match ext {
        KVM_RISCV_ISA_EXT_H => false,
        KVM_RISCV_ISA_EXT_SSCOFPMF => !kvm_riscv_isa_check_host(SSAIA),
        KVM_RISCV_ISA_EXT_SVADU => arch_has_hw_pte_young(),
        KVM_RISCV_ISA_EXT_V => riscv_v_vstate_ctrl_user_allowed(),
        _ => true,
    }
}

