// Kernel dependencies supplied by the surrounding Rust translation unit.

/* The logical cpu number we should resume on, initialised to a non-cpu number. */
static mut sleep_cpu: i32 = -EINVAL;

/* Pointer to the temporary resume page table. */
static mut resume_pg_dir: *mut pgd_t = core::ptr::null_mut();

/* CPU context to be saved. */
#[no_mangle]
pub static mut hibernate_cpu_context: *mut suspend_context = core::ptr::null_mut();

#[no_mangle]
pub static mut relocated_restore_code: usize = 0;

/**
 * struct arch_hibernate_hdr_invariants - container to store kernel build version.
 * @uts_version: to save the build number and date so that we do not resume with
 *	 a different kernel.
 */
#[repr(C)]
struct arch_hibernate_hdr_invariants {
    uts_version: [i8; __NEW_UTS_LEN + 1],
}

/**
 * struct arch_hibernate_hdr - helper parameters that help us to restore the image.
 * @invariants: container to store kernel build version.
 * @hartid: to make sure same boot_cpu executes the hibernate/restore code.
 * @saved_satp: original page table used by the hibernated image.
 * @restore_cpu_addr: the kernel's image address to restore the CPU context.
 */
#[repr(C)]
struct arch_hibernate_hdr {
    invariants: arch_hibernate_hdr_invariants,
    hartid: usize,
    saved_satp: usize,
    restore_cpu_addr: usize,
}

static mut resume_hdr: arch_hibernate_hdr = arch_hibernate_hdr {
    invariants: arch_hibernate_hdr_invariants { uts_version: [0; __NEW_UTS_LEN + 1] },
    hartid: 0,
    saved_satp: 0,
    restore_cpu_addr: 0,
};

unsafe fn arch_hdr_invariants(i: *mut arch_hibernate_hdr_invariants) {
    core::ptr::write_bytes(i as *mut u8, 0, core::mem::size_of::<arch_hibernate_hdr_invariants>());
    memcpy((*i).uts_version.as_mut_ptr() as *mut _, (*init_utsname()).version.as_ptr(), core::mem::size_of_val(&(*i).uts_version));
}

/*
 * Check if the given pfn is in the 'nosave' section.
 */
#[no_mangle]
pub unsafe fn pfn_is_nosave(pfn: usize) -> i32 {
    let nosave_begin_pfn = sym_to_pfn(&__nosave_begin);
    let nosave_end_pfn = sym_to_pfn((&__nosave_end as *const _).offset(-1));
    if pfn >= nosave_begin_pfn && pfn <= nosave_end_pfn { 1 } else { 0 }
}

pub unsafe fn save_processor_state() {}

pub unsafe fn restore_processor_state() {}

/* Helper parameters need to be saved to the hibernation image header. */
#[no_mangle]
pub unsafe fn arch_hibernation_header_save(addr: *mut core::ffi::c_void, max_size: u32) -> i32 {
    let hdr = addr as *mut arch_hibernate_hdr;
    if (max_size as usize) < core::mem::size_of::<arch_hibernate_hdr>() { return -EOVERFLOW; }
    arch_hdr_invariants(&mut (*hdr).invariants);
    (*hdr).hartid = cpuid_to_hartid_map(sleep_cpu);
    (*hdr).saved_satp = csr_read(CSR_SATP);
    (*hdr).restore_cpu_addr = __hibernate_cpu_resume as usize;
    0
}

/* Retrieve the helper parameters from the hibernation image header. */
#[no_mangle]
pub unsafe fn arch_hibernation_header_restore(addr: *mut core::ffi::c_void) -> i32 {
    let mut invariants = arch_hibernate_hdr_invariants { uts_version: [0; __NEW_UTS_LEN + 1] };
    let hdr = addr as *mut arch_hibernate_hdr;
    let mut ret = 0;
    arch_hdr_invariants(&mut invariants);
    if memcmp(&(*hdr).invariants as *const _, &invariants as *const _, core::mem::size_of_val(&invariants)) != 0 {
        pr_crit!("Hibernate image not generated by this kernel!\n");
        return -EINVAL;
    }
    sleep_cpu = riscv_hartid_to_cpuid((*hdr).hartid);
    if sleep_cpu < 0 {
        pr_crit!("Hibernated on a CPU not known to this kernel!\n");
        sleep_cpu = -EINVAL;
        return -EINVAL;
    }
    // CONFIG_SMP
    #[cfg(CONFIG_SMP)]
    { ret = bringup_hibernate_cpu(sleep_cpu); if ret != 0 { sleep_cpu = -EINVAL; return ret; } }
    resume_hdr = *hdr;
    ret
}

pub unsafe fn swsusp_arch_suspend() -> i32 {
    let mut ret = 0;
    if __cpu_suspend_enter(hibernate_cpu_context) != 0 {
        sleep_cpu = smp_processor_id();
        suspend_save_csrs(hibernate_cpu_context);
        ret = swsusp_save();
    } else {
        suspend_restore_csrs(hibernate_cpu_context);
        flush_tlb_all();
        flush_icache_all();
        /* Tell the hibernation core that we've just restored the memory. */
        in_suspend = 0;
        sleep_cpu = -EINVAL;
    }
    ret
}

unsafe fn temp_pgtable_map_pte(dst_pmdp: *mut pmd_t, src_pmdp: *mut pmd_t, mut start: usize, end: usize, prot: pgprot_t) -> i32 {
    let mut dst_ptep: *mut pte_t;
    let src_ptep: *mut pte_t;
    if pmd_none(READ_ONCE!(*dst_pmdp)) {
        dst_ptep = get_safe_page(GFP_ATOMIC) as *mut pte_t;
        if dst_ptep.is_null() { return -ENOMEM; }
        pmd_populate(core::ptr::null_mut(), dst_pmdp, dst_ptep);
    }
    dst_ptep = pte_offset_kernel(dst_pmdp, start);
    src_ptep = pte_offset_kernel(src_pmdp, start);
    loop {
        let pte = READ_ONCE!(*src_ptep);
        if pte_present(pte) { set_pte(dst_ptep, __pte(pte_val(pte) | pgprot_val(prot))); }
        dst_ptep = dst_ptep.add(1); let src_ptep = src_ptep.add(1); start += PAGE_SIZE;
        if start >= end { break; }
        let _ = src_ptep;
    }
    0
}

unsafe fn temp_pgtable_map_pmd(dst_pudp: *mut pud_t, src_pudp: *mut pud_t, mut start: usize, end: usize, prot: pgprot_t) -> i32 {
    let mut dst_pmdp: *mut pmd_t; let mut src_pmdp: *mut pmd_t;
    if pud_none(READ_ONCE!(*dst_pudp)) { dst_pmdp = get_safe_page(GFP_ATOMIC) as *mut pmd_t; if dst_pmdp.is_null() { return -ENOMEM; } pud_populate(core::ptr::null_mut(), dst_pudp, dst_pmdp); }
    dst_pmdp = pmd_offset(dst_pudp, start); src_pmdp = pmd_offset(src_pudp, start);
    loop { let pmd = READ_ONCE!(*src_pmdp); let next = pmd_addr_end(start, end); if !pmd_none(pmd) { if pmd_leaf(pmd) { set_pmd(dst_pmdp, __pmd(pmd_val(pmd) | pgprot_val(prot))); } else if temp_pgtable_map_pte(dst_pmdp, src_pmdp, start, next, prot) != 0 { return -ENOMEM; } } dst_pmdp = dst_pmdp.add(1); src_pmdp = src_pmdp.add(1); start = next; if start == end { break; } } 0
}

unsafe fn temp_pgtable_map_pud(dst_p4dp: *mut p4d_t, src_p4dp: *mut p4d_t, mut start: usize, end: usize, prot: pgprot_t) -> i32 {
    let mut dst_pudp: *mut pud_t; let mut src_pudp: *mut pud_t;
    if p4d_none(READ_ONCE!(*dst_p4dp)) { dst_pudp = get_safe_page(GFP_ATOMIC) as *mut pud_t; if dst_pudp.is_null() { return -ENOMEM; } p4d_populate(core::ptr::null_mut(), dst_p4dp, dst_pudp); }
    dst_pudp = pud_offset(dst_p4dp, start); src_pudp = pud_offset(src_p4dp, start);
    loop { let pud = READ_ONCE!(*src_pudp); let next = pud_addr_end(start, end); if !pud_none(pud) { if pud_leaf(pud) { set_pud(dst_pudp, __pud(pud_val(pud) | pgprot_val(prot))); } else if temp_pgtable_map_pmd(dst_pudp, src_pudp, start, next, prot) != 0 { return -ENOMEM; } } dst_pudp = dst_pudp.add(1); src_pudp = src_pudp.add(1); start = next; if start == end { break; } } 0
}

unsafe fn temp_pgtable_map_p4d(dst_pgdp: *mut pgd_t, src_pgdp: *mut pgd_t, mut start: usize, end: usize, prot: pgprot_t) -> i32 {
    let mut dst_p4dp: *mut p4d_t; let mut src_p4dp: *mut p4d_t;
    if pgd_none(READ_ONCE!(*dst_pgdp)) { dst_p4dp = get_safe_page(GFP_ATOMIC) as *mut p4d_t; if dst_p4dp.is_null() { return -ENOMEM; } pgd_populate(core::ptr::null_mut(), dst_pgdp, dst_p4dp); }
    dst_p4dp = p4d_offset(dst_pgdp, start); src_p4dp = p4d_offset(src_pgdp, start);
    loop { let p4d = READ_ONCE!(*src_p4dp); let next = p4d_addr_end(start, end); if !p4d_none(p4d) { if p4d_leaf(p4d) { set_p4d(dst_p4dp, __p4d(p4d_val(p4d) | pgprot_val(prot))); } else if temp_pgtable_map_pud(dst_p4dp, src_p4dp, start, next, prot) != 0 { return -ENOMEM; } } dst_p4dp = dst_p4dp.add(1); src_p4dp = src_p4dp.add(1); start = next; if start == end { break; } } 0
}

unsafe fn temp_pgtable_mapping(pgdp: *mut pgd_t, mut start: usize, end: usize, prot: pgprot_t) -> i32 {
    let mut dst_pgdp = pgd_offset_pgd(pgdp, start); let mut src_pgdp = pgd_offset_k(start);
    loop { let pgd = READ_ONCE!(*src_pgdp); let next = pgd_addr_end(start, end); if !pgd_none(pgd) { if pgd_leaf(pgd) { set_pgd(dst_pgdp, __pgd(pgd_val(pgd) | pgprot_val(prot))); } else if temp_pgtable_map_p4d(dst_pgdp, src_pgdp, start, next, prot) != 0 { return -ENOMEM; } } dst_pgdp = dst_pgdp.add(1); src_pgdp = src_pgdp.add(1); start = next; if start == end { break; } } 0
}

unsafe fn relocate_restore_code() -> usize {
    let page = get_safe_page(GFP_ATOMIC) as *mut core::ffi::c_void;
    if page.is_null() { return (-ENOMEM) as usize; }
    copy_page(page, hibernate_core_restore_code);
    set_memory_x(page as usize, 1);
    page as usize
}

pub unsafe fn swsusp_arch_resume() -> i32 {
    let end = pfn_to_virt(max_low_pfn); let mut start = PAGE_OFFSET;
    resume_pg_dir = get_safe_page(GFP_ATOMIC) as *mut pgd_t;
    if resume_pg_dir.is_null() { return -ENOMEM; }
    let mut ret = temp_pgtable_mapping(resume_pg_dir, start, end, __pgprot(_PAGE_WRITE | _PAGE_EXEC)); if ret != 0 { return ret; }
    relocated_restore_code = relocate_restore_code(); if relocated_restore_code == (-ENOMEM) as usize { return -ENOMEM; }
    start = resume_hdr.restore_cpu_addr; let end = start + PAGE_SIZE;
    ret = temp_pgtable_mapping(resume_pg_dir, start, end, __pgprot(_PAGE_WRITE)); if ret != 0 { return ret; }
    hibernate_restore_image(resume_hdr.saved_satp, PFN_DOWN(__pa(resume_pg_dir)) | satp_mode, resume_hdr.restore_cpu_addr);
    0
}

#[cfg(CONFIG_PM_SLEEP_SMP)]
pub unsafe fn hibernate_resume_nonboot_cpu_disable() -> i32 {
    if sleep_cpu < 0 { pr_err!("Failing to resume from hibernate on an unknown CPU\n"); return -ENODEV; }
    freeze_secondary_cpus(sleep_cpu)
}

unsafe fn riscv_hibernate_init() -> i32 {
    hibernate_cpu_context = kzalloc_obj!(*hibernate_cpu_context);
    if WARN_ON!(!hibernate_cpu_context.is_null()) { return -ENOMEM; }
    0
}

early_initcall!(riscv_hibernate_init);

