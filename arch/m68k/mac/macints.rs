/*
 *	Macintosh interrupts
 *
 * General design:
 * In contrary to the Amiga and Atari platforms, the Mac hardware seems to
 * exclusively use the autovector interrupts (the 'generic level0-level7'
 * interrupts with exception vectors 0x19-0x1f). The following interrupt levels
 * are used:
 *	1	- VIA1
 *		  - slot 0: one second interrupt (CA2)
 *		  - slot 1: VBlank (CA1)
 *		  - slot 2: ADB data ready (SR full)
 *		  - slot 3: ADB data  (CB2)
 *		  - slot 4: ADB clock (CB1)
 *		  - slot 5: timer 2
 *		  - slot 6: timer 1
 *		  - slot 7: status of IRQ; signals 'any enabled int.'
 *
 *	2	- VIA2 or RBV
 *		  - slot 0: SCSI DRQ (CA2)
 *		  - slot 1: NUBUS IRQ (CA1) need to read port A to find which
 *		  - slot 2: /EXP IRQ (only on IIci)
 *		  - slot 3: SCSI IRQ (CB2)
 *		  - slot 4: ASC IRQ (CB1)
 *		  - slot 5: timer 2 (not on IIci)
 *		  - slot 6: timer 1 (not on IIci)
 *		  - slot 7: status of IRQ; signals 'any enabled int.'
 *
 * Levels 3-6 vary by machine type. For VIA or RBV Macintoshes:
 *
 *	3	- unused (?)
 *
 *	4	- SCC
 *
 *	5	- unused (?)
 *		  [serial errors or special conditions seem to raise level 6
 *		  interrupts on some models (LC4xx?)]
 *
 *	6	- off switch (?)
 *
 * Machines with Quadra-like VIA hardware, except PSC and PMU machines, support
 * an alternate interrupt mapping, as used by A/UX. It spreads ethernet and
 * sound out to their own autovector IRQs and gives VIA1 a higher priority:
 *
 *	1	- unused (?)
 *
 *	3	- on-board SONIC
 *
 *	5	- Apple Sound Chip (ASC)
 *
 *	6	- VIA1
 *
 * For OSS Macintoshes (IIfx only), we apply an interrupt mapping similar to
 * the Quadra (A/UX) mapping:
 *
 *	1	- ISM IOP (ADB)
 *
 *	2	- SCSI
 *
 *	3	- NuBus
 *
 *	4	- SCC IOP
 *
 *	6	- VIA1
 *
 * For PSC Macintoshes (660AV, 840AV):
 *
 *	3	- PSC level 3
 *		  - slot 0: MACE
 *
 *	4	- PSC level 4
 *		  - slot 1: SCC channel A interrupt
 *		  - slot 2: SCC channel B interrupt
 *		  - slot 3: MACE DMA
 *
 *	5	- PSC level 5
 *
 *	6	- PSC level 6
 *
 * Finally we have good 'ole level 7, the non-maskable interrupt:
 *
 *	7	- NMI (programmer's switch on the back of some Macs)
 *		  Also RAM parity error on models which support it (IIc, IIfx?)
 *
 * The current interrupt logic looks something like this:
 *
 * - We install dispatchers for the autovector interrupts (1-7). These
 *   dispatchers are responsible for querying the hardware (the
 *   VIA/RBV/OSS/PSC chips) to determine the actual interrupt source. Using
 *   this information a machspec interrupt number is generated by placing the
 *   index of the interrupt hardware into the low three bits and the original
 *   autovector interrupt number in the upper 5 bits. The handlers for the
 *   resulting machspec interrupt are then called.
 *
 * - Nubus is a special case because its interrupts are hidden behind two
 *   layers of hardware. Nubus interrupts come in as index 1 on VIA #2,
 *   which translates to IRQ number 17. In this spot we install _another_
 *   dispatcher. This dispatcher finds the interrupting slot number (9-F) and
 *   then forms a new machspec interrupt number as above with the slot number
 *   minus 9 in the low three bits and the pseudo-level 7 in the upper five
 *   bits.  The handlers for this new machspec interrupt number are then
 *   called. This puts Nubus interrupts into the range 56-62.
 *
 * - The Baboon interrupts (used on some PowerBooks) are an even more special
 *   case. They're hidden behind the Nubus slot $C interrupt thus adding a
 *   third layer of indirection. Why oh why did the Apple engineers do that?
 */

extern "C" {
    static oss_present: bool;
    static psc: *mut core::ffi::c_void;
    static baboon_present: bool;

    fn mac_irq_enable(irq: i32);
    fn mac_irq_disable(irq: i32);
    fn oss_irq_enable(irq: i32);
    fn oss_irq_disable(irq: i32);
    fn via_irq_enable(irq: i32);
    fn via_irq_disable(irq: i32);
    fn psc_irq_enable(irq: i32);
    fn psc_irq_disable(irq: i32);
    fn baboon_irq_enable(irq: i32);
    fn baboon_irq_disable(irq: i32);
    fn via_nubus_irq_startup(irq: i32);
    fn via_nubus_irq_shutdown(irq: i32);
    fn oss_register_interrupts();
    fn via_register_interrupts();
    fn psc_register_interrupts();
    fn baboon_register_interrupts();
    fn iop_register_interrupts();
    fn m68k_setup_irq_controller(chip: *mut irq_chip, handler: unsafe extern "C" fn(*mut irq_desc), first: i32, count: i32);
    fn request_irq(irq: i32, handler: unsafe extern "C" fn(i32, *mut core::ffi::c_void) -> irqreturn_t, flags: i32, name: *const i8, dev_id: unsafe extern "C" fn(i32, *mut core::ffi::c_void) -> irqreturn_t) -> i32;
    fn pr_info(message: *const i8);
    fn pr_err(message: *const i8);
    fn get_irq_regs() -> *mut core::ffi::c_void;
    fn show_registers(regs: *mut core::ffi::c_void);
}

#[repr(C)]
pub struct irq_data { pub irq: i32 }
#[repr(C)]
pub struct irq_chip {
    pub name: *const i8,
    pub irq_enable: Option<unsafe extern "C" fn(*mut irq_data)>,
    pub irq_disable: Option<unsafe extern "C" fn(*mut irq_data)>,
    pub irq_startup: Option<unsafe extern "C" fn(*mut irq_data) -> u32>,
    pub irq_shutdown: Option<unsafe extern "C" fn(*mut irq_data)>,
}
#[repr(C)] pub struct irq_desc;
pub type irqreturn_t = i32;

const IRQ_HANDLED: irqreturn_t = 1;
const IRQ_AUTO_7: i32 = 7;
const IRQ_USER: i32 = 0;
const NUM_MAC_SOURCES: i32 = 64;

#[inline]
unsafe fn irq_src(irq: i32) -> i32 { (irq >> 3) & 7 }

unsafe extern "C" fn mac_nmi_handler(_irq: i32, _dev_id: *mut core::ffi::c_void) -> irqreturn_t {
    static mut IN_NMI: i32 = 0;

    if IN_NMI != 0 { return IRQ_HANDLED; }
    IN_NMI = 1;
    pr_info(b"Non-Maskable Interrupt\0".as_ptr() as *const i8);
    show_registers(get_irq_regs());
    IN_NMI = 0;
    IRQ_HANDLED
}

#[no_mangle]
pub unsafe extern "C" fn mac_init_IRQ() {
    static mut MAC_IRQ_CHIP: irq_chip = irq_chip {
        name: b"mac\0".as_ptr() as *const i8,
        irq_enable: Some(mac_irq_enable), irq_disable: Some(mac_irq_disable),
        irq_startup: Some(mac_irq_startup), irq_shutdown: Some(mac_irq_shutdown),
    };
    m68k_setup_irq_controller(&mut MAC_IRQ_CHIP, handle_simple_irq, IRQ_USER, NUM_MAC_SOURCES - IRQ_USER);
    if oss_present { oss_register_interrupts(); } else { via_register_interrupts(); }
    if !psc.is_null() { psc_register_interrupts(); }
    if baboon_present { baboon_register_interrupts(); }
    iop_register_interrupts();
    if request_irq(IRQ_AUTO_7, mac_nmi_handler, 0, b"NMI\0".as_ptr() as *const i8, mac_nmi_handler) != 0 {
        pr_err(b"Couldn't register NMI\n\0".as_ptr() as *const i8);
    }
}

unsafe extern "C" fn mac_irq_enable(data: *mut irq_data) {
    let irq = (*data).irq; let irq_src = irq_src(irq);
    match irq_src {
        1 | 2 | 7 => if oss_present { oss_irq_enable(irq); } else { via_irq_enable(irq); },
        3 | 4 | 5 | 6 => if !psc.is_null() { psc_irq_enable(irq); } else if oss_present { oss_irq_enable(irq); },
        8 => if baboon_present { baboon_irq_enable(irq); }, _ => {}
    }
}

unsafe extern "C" fn mac_irq_disable(data: *mut irq_data) {
    let irq = (*data).irq; let irq_src = irq_src(irq);
    match irq_src {
        1 | 2 | 7 => if oss_present { oss_irq_disable(irq); } else { via_irq_disable(irq); },
        3 | 4 | 5 | 6 => if !psc.is_null() { psc_irq_disable(irq); } else if oss_present { oss_irq_disable(irq); },
        8 => if baboon_present { baboon_irq_disable(irq); }, _ => {}
    }
}

unsafe extern "C" fn mac_irq_startup(data: *mut irq_data) -> u32 {
    let irq = (*data).irq;
    if irq_src(irq) == 7 && !oss_present { via_nubus_irq_startup(irq); } else { mac_irq_enable(data); }
    0
}

unsafe extern "C" fn mac_irq_shutdown(data: *mut irq_data) {
    let irq = (*data).irq;
    if irq_src(irq) == 7 && !oss_present { via_nubus_irq_shutdown(irq); } else { mac_irq_disable(data); }
}

