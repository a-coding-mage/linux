#![allow(non_camel_case_types, non_snake_case, dead_code)]

#[inline(always)]
pub const fn CVMX_ADD_IO_SEG(value: u64) -> u64 { value }

macro_rules! reg {
    ($name:ident, $value:expr) => { pub const $name: u64 = CVMX_ADD_IO_SEG($value); };
}
macro_rules! regx {
    ($name:ident, $base:expr, $stride:expr) => {
        #[inline(always)] pub const fn $name(offset: u64) -> u64 {
            CVMX_ADD_IO_SEG($base) + (offset & 1) * $stride
        }
    };
}

