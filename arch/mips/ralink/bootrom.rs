// C dependencies: linux/debugfs.h and linux/seq_file.h.

use core::ffi::c_void;

const BOOTROM_OFFSET: usize = 0x1011_8000;
const BOOTROM_SIZE: usize = 0x8000;

#[repr(C)]
pub struct seq_file {
    _private: [u8; 0],
}

extern "C" {
    fn seq_write(s: *mut seq_file, data: *const c_void, size: usize) -> isize;
    fn debugfs_create_file(
        name: *const u8,
        mode: u16,
        parent: *mut c_void,
        data: *mut c_void,
        fops: *const c_void,
    ) -> *mut c_void;

    // Generated by DEFINE_SHOW_ATTRIBUTE(bootrom).
    static bootrom_fops: c_void;
}

// KSEG1ADDR(BOOTROM_OFFSET) is supplied by the platform headers.
static mut membase: *mut c_void = BOOTROM_OFFSET as *mut c_void;

unsafe fn bootrom_show(s: *mut seq_file, _unused: *mut c_void) -> i32 {
    seq_write(s, membase as *const c_void, BOOTROM_SIZE);

    0
}

unsafe fn bootrom_setup() -> i32 {
    debugfs_create_file(
        b"bootrom\0".as_ptr(),
        0o444,
        core::ptr::null_mut(),
        core::ptr::null_mut(),
        &bootrom_fops as *const c_void,
    );
    0
}

