pub static mut BCM63XX_RESET_BITS: *const u32 = core::ptr::null();
static mut RESET_REG: i32 = 0;

unsafe fn bcm63xx_reset_bits_init() -> i32 {
    if BCMCPU_IS_3368() { RESET_REG = PERF_SOFTRESET_6358_REG; BCM63XX_RESET_BITS = BCM3368_RESET_BITS.as_ptr(); }
    else if BCMCPU_IS_6328() { RESET_REG = PERF_SOFTRESET_6328_REG; BCM63XX_RESET_BITS = BCM6328_RESET_BITS.as_ptr(); }
    else if BCMCPU_IS_6338() { RESET_REG = PERF_SOFTRESET_REG; BCM63XX_RESET_BITS = BCM6338_RESET_BITS.as_ptr(); }
    else if BCMCPU_IS_6348() { RESET_REG = PERF_SOFTRESET_REG; BCM63XX_RESET_BITS = BCM6348_RESET_BITS.as_ptr(); }
    else if BCMCPU_IS_6358() { RESET_REG = PERF_SOFTRESET_6358_REG; BCM63XX_RESET_BITS = BCM6358_RESET_BITS.as_ptr(); }
    else if BCMCPU_IS_6362() { RESET_REG = PERF_SOFTRESET_6362_REG; BCM63XX_RESET_BITS = BCM6362_RESET_BITS.as_ptr(); }
    else if BCMCPU_IS_6368() { RESET_REG = PERF_SOFTRESET_6368_REG; BCM63XX_RESET_BITS = BCM6368_RESET_BITS.as_ptr(); }
    0
}

unsafe fn __bcm63xx_core_set_reset(mask: u32, enable: i32) {
    if mask == 0 { return; }
    let mut val = bcm_perf_readl(RESET_REG);
    if enable != 0 { val &= !mask; } else { val |= mask; }
    bcm_perf_writel(val, RESET_REG);
}

pub unsafe fn bcm63xx_core_set_reset(core: usize, reset: i32) {
    __bcm63xx_core_set_reset(*BCM63XX_RESET_BITS.add(core), reset);
}

