#[inline] pub fn build_rs(arg: u32) -> u32 { (arg & RS_MASK) << RS_SH }
#[inline] pub fn build_rt(arg: u32) -> u32 { (arg & RT_MASK) << RT_SH }
#[inline] pub fn build_rd(arg: u32) -> u32 { (arg & RD_MASK) << RD_SH }
#[inline] pub fn build_re(arg: u32) -> u32 { (arg & RE_MASK) << RE_SH }
#[inline] pub fn build_simm(arg: i32) -> u32 { arg as u32 & 0xffff }
#[inline] pub fn build_uimm(arg: u32) -> u32 { arg & IMM_MASK }
#[inline] pub fn build_scimm(arg: u32) -> u32 { (arg & SCIMM_MASK) << SCIMM_SH }
#[inline] pub fn build_scimm9(arg: i32) -> u32 { (arg as u32 & SIMM9_MASK) << SIMM9_SH }
#[inline] pub fn build_func(arg: u32) -> u32 { arg & FUNC_MASK }
#[inline] pub fn build_set(arg: u32) -> u32 { arg & SET_MASK }

extern "C" { fn build_insn(buf: *mut *mut u32, opc: opcode, ...); }

macro_rules! wrapper {
    ($name:ident, $opc:ident, ($($arg:ident : $ty:ty),*), ($($expr:expr),*)) => {
        pub unsafe fn $name(buf: *mut *mut u32, $($arg: $ty),*) { build_insn(buf, opcode::$opc, $($expr),*); }
    };
}

