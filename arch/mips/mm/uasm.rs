#[repr(C)] pub struct uasm_label { pub addr: *mut u32, pub lab: i32 }
#[repr(C)] pub struct uasm_reloc { pub addr: *mut u32, pub type_: i32, pub lab: i32 }
pub const UASM_LABEL_INVALID: i32 = -1;
pub const R_MIPS_PC16: i32 = 4;

pub unsafe fn uasm_build_label(lab: *mut *mut uasm_label, addr: *mut u32, lid: i32) {
    (**lab).addr = addr; (**lab).lab = lid; *lab = (*lab).add(1);
}
pub unsafe fn uasm_in_compat_space_p(addr: i64) -> i32 { (addr == addr as i32 as i64) as i32 }
pub unsafe fn uasm_rel_hi(val: i64) -> i32 { ((((val + 0x8000) >> 16) & 0xffff) ^ 0x8000) as i32 - 0x8000 }
pub unsafe fn uasm_rel_lo(val: i64) -> i32 { ((val & 0xffff) ^ 0x8000) as i32 - 0x8000 }

pub unsafe fn uasm_r_mips_pc16(rel: *mut *mut uasm_reloc, addr: *mut u32, lid: i32) {
    (**rel).addr = addr; (**rel).type_ = R_MIPS_PC16; (**rel).lab = lid; *rel = (*rel).add(1);
}
pub unsafe fn uasm_resolve_relocs(mut rel: *mut uasm_reloc, lab: *mut uasm_label) {
    while (*rel).lab != UASM_LABEL_INVALID { let mut l = lab; while (*l).lab != UASM_LABEL_INVALID {
        if (*rel).lab == (*l).lab { /* __resolve_relocs is supplied by the assembler backend. */ }
        l = l.add(1);
    } rel = rel.add(1); }
}
pub unsafe fn uasm_move_relocs(mut rel: *mut uasm_reloc, first: *mut u32, end: *mut u32, off: isize) {
    while (*rel).lab != UASM_LABEL_INVALID { if (*rel).addr >= first && (*rel).addr < end { (*rel).addr = (*rel).addr.offset(off); } rel = rel.add(1); }
}
pub unsafe fn uasm_move_labels(mut lab: *mut uasm_label, first: *mut u32, end: *mut u32, off: isize) {
    while (*lab).lab != UASM_LABEL_INVALID { if (*lab).addr >= first && (*lab).addr < end { (*lab).addr = (*lab).addr.offset(off); } lab = lab.add(1); }
}
