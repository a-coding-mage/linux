/*
 * Three types of 8bit P-Unit IPC commands are supported,
 * bit[7:6]: [00]: BIOS; [01]: GTD; [10]: ISPD.
 */
#[repr(C)]
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum IPC_TYPE {
    BIOS_IPC = 0,
    GTDRIVER_IPC,
    ISPDRIVER_IPC,
    RESERVED_IPC,
}

pub const IPC_TYPE_OFFSET: i32 = 6;
pub const IPC_PUNIT_BIOS_CMD_BASE: i32 = (BIOS_IPC as i32) << IPC_TYPE_OFFSET;
/* Preserve the source spelling of GTDDRIVER_IPC. */
pub const IPC_PUNIT_GTD_CMD_BASE: i32 = (GTDDRIVER_IPC as i32) << IPC_TYPE_OFFSET;
pub const IPC_PUNIT_ISPD_CMD_BASE: i32 = (ISPDRIVER_IPC as i32) << IPC_TYPE_OFFSET;
pub const IPC_PUNIT_CMD_TYPE_MASK: i32 = (RESERVED_IPC as i32) << IPC_TYPE_OFFSET;

/* BIOS => Pcode commands */
pub const IPC_PUNIT_BIOS_ZERO: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x00;
pub const IPC_PUNIT_BIOS_VR_INTERFACE: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x01;
pub const IPC_PUNIT_BIOS_READ_PCS: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x02;
pub const IPC_PUNIT_BIOS_WRITE_PCS: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x03;
pub const IPC_PUNIT_BIOS_READ_PCU_CONFIG: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x04;
pub const IPC_PUNIT_BIOS_WRITE_PCU_CONFIG: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x05;
pub const IPC_PUNIT_BIOS_READ_PL1_SETTING: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x06;
pub const IPC_PUNIT_BIOS_WRITE_PL1_SETTING: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x07;
pub const IPC_PUNIT_BIOS_TRIGGER_VDD_RAM: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x08;
pub const IPC_PUNIT_BIOS_READ_TELE_INFO: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x09;
pub const IPC_PUNIT_BIOS_READ_TELE_TRACE_CTRL: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x0a;
pub const IPC_PUNIT_BIOS_WRITE_TELE_TRACE_CTRL: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x0b;
pub const IPC_PUNIT_BIOS_READ_TELE_EVENT_CTRL: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x0c;
pub const IPC_PUNIT_BIOS_WRITE_TELE_EVENT_CTRL: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x0d;
pub const IPC_PUNIT_BIOS_READ_TELE_TRACE: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x0e;
pub const IPC_PUNIT_BIOS_WRITE_TELE_TRACE: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x0f;
pub const IPC_PUNIT_BIOS_READ_TELE_EVENT: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x10;
pub const IPC_PUNIT_BIOS_WRITE_TELE_EVENT: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x11;
pub const IPC_PUNIT_BIOS_READ_MODULE_TEMP: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x12;
pub const IPC_PUNIT_BIOS_RESERVED: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x13;
pub const IPC_PUNIT_BIOS_READ_VOLTAGE_OVER: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x14;
pub const IPC_PUNIT_BIOS_WRITE_VOLTAGE_OVER: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x15;
pub const IPC_PUNIT_BIOS_READ_RATIO_OVER: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x16;
pub const IPC_PUNIT_BIOS_WRITE_RATIO_OVER: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x17;
pub const IPC_PUNIT_BIOS_READ_VF_GL_CTRL: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x18;
pub const IPC_PUNIT_BIOS_WRITE_VF_GL_CTRL: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x19;
pub const IPC_PUNIT_BIOS_READ_FM_SOC_TEMP_THRESH: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x1a;
pub const IPC_PUNIT_BIOS_WRITE_FM_SOC_TEMP_THRESH: i32 = IPC_PUNIT_BIOS_CMD_BASE | 0x1b;

/* GT Driver => Pcode commands */
pub const IPC_PUNIT_GTD_ZERO: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x00;
pub const IPC_PUNIT_GTD_CONFIG: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x01;
pub const IPC_PUNIT_GTD_READ_ICCP_LIC_CDYN_SCAL: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x02;
pub const IPC_PUNIT_GTD_WRITE_ICCP_LIC_CDYN_SCAL: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x03;
pub const IPC_PUNIT_GTD_GET_WM_VAL: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x06;
pub const IPC_PUNIT_GTD_WRITE_CONFIG_WISHREQ: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x07;
pub const IPC_PUNIT_GTD_READ_REQ_DUTY_CYCLE: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x16;
pub const IPC_PUNIT_GTD_DIS_VOL_FREQ_CHG_REQUEST: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x17;
pub const IPC_PUNIT_GTD_DYNA_DUTY_CYCLE_CTRL: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x1a;
pub const IPC_PUNIT_GTD_DYNA_DUTY_CYCLE_TUNING: i32 = IPC_PUNIT_GTD_CMD_BASE | 0x1c;

/* ISP Driver => Pcode commands */
pub const IPC_PUNIT_ISPD_ZERO: i32 = IPC_PUNIT_ISPD_CMD_BASE | 0x00;
pub const IPC_PUNIT_ISPD_CONFIG: i32 = IPC_PUNIT_ISPD_CMD_BASE | 0x01;
pub const IPC_PUNIT_ISPD_GET_ISP_LTR_VAL: i32 = IPC_PUNIT_ISPD_CMD_BASE | 0x02;
pub const IPC_PUNIT_ISPD_ACCESS_IU_FREQ_BOUNDS: i32 = IPC_PUNIT_ISPD_CMD_BASE | 0x03;
pub const IPC_PUNIT_ISPD_READ_CDYN_LEVEL: i32 = IPC_PUNIT_ISPD_CMD_BASE | 0x04;
pub const IPC_PUNIT_ISPD_WRITE_CDYN_LEVEL: i32 = IPC_PUNIT_ISPD_CMD_BASE | 0x05;

/* Error codes */
pub const IPC_PUNIT_ERR_SUCCESS: i32 = 0;
pub const IPC_PUNIT_ERR_INVALID_CMD: i32 = 1;
pub const IPC_PUNIT_ERR_INVALID_PARAMETER: i32 = 2;
pub const IPC_PUNIT_ERR_CMD_TIMEOUT: i32 = 3;
pub const IPC_PUNIT_ERR_CMD_LOCKED: i32 = 4;
pub const IPC_PUNIT_ERR_INVALID_VR_ID: i32 = 5;
pub const IPC_PUNIT_ERR_VR_ERR: i32 = 6;

