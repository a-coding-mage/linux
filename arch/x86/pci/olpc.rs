static mut FF_LOC: u32 = !0;
static mut ZERO_LOC: u32 = 0;
static mut BAR_PROBING: i32 = 0;
static mut IS_LX: i32 = 0;

const NB_SLOT: u32 = 0x1;
const SB_SLOT: u32 = 0xf;

unsafe fn is_simulated(bus: u32, devfn: u32) -> bool {
    bus == 0 && ((((devfn >> 3) & 0x1f) == NB_SLOT) || (((devfn >> 3) & 0x1f) == SB_SLOT))
}

unsafe fn hdr_addr(hdr: *const u32, reg: i32) -> *mut u32 {
    let off = reg + if BAR_PROBING != 0 { -0x10 } else { 0x20 };
    BAR_PROBING = 0;
    (hdr as *mut u8).offset(off as isize) as *mut u32
}

// The bodies below retain the original external Linux PCI operations and logging symbols.
// They are declarations for integration with the surrounding translated kernel.
extern "C" {
    static mut pci_direct_conf1: PciRawOps;
    static mut raw_pci_ops: *const PciRawOps;
    fn is_geode_lx() -> i32;
    fn printk(fmt: *const u8, ...);
    fn WARN_ON(condition: bool);
    fn BUG() -> !;
}

#[repr(C)]
struct PciRawOps {
    read: Option<unsafe extern "C" fn(u32, u32, u32, i32, i32, *mut u32) -> i32>,
    write: Option<unsafe extern "C" fn(u32, u32, u32, i32, i32, u32) -> i32>,
}

#[no_mangle]
pub unsafe extern "C" fn pci_olpc_read(seg: u32, bus: u32, devfn: u32, reg: i32, len: i32, value: *mut u32) -> i32 {
    WARN_ON(seg != 0);
    if !is_simulated(bus, devfn) { return (pci_direct_conf1.read.unwrap())(seg, bus, devfn, reg, len, value); }
    let addr: *mut u32 = if reg >= 0x70 { &raw mut ZERO_LOC } else { match devfn {
        0x8 => hdr_addr(if IS_LX != 0 { LXNB_HDR.as_ptr() } else { GXNB_HDR.as_ptr() }, reg),
        0x9 => hdr_addr(if IS_LX != 0 { LXFB_HDR.as_ptr() } else { GXFB_HDR.as_ptr() }, reg),
        0xa => if IS_LX != 0 { hdr_addr(AES_HDR.as_ptr(), reg) } else { &raw mut FF_LOC },
        0x78 => hdr_addr(ISA_HDR.as_ptr(), reg), 0x7b => hdr_addr(AC97_HDR.as_ptr(), reg),
        0x7c => hdr_addr(OHCI_HDR.as_ptr(), reg), 0x7d => hdr_addr(EHCI_HDR.as_ptr(), reg),
        _ => &raw mut FF_LOC,
    }};
    *value = match len { 1 => *(addr as *const u8) as u32, 2 => *(addr as *const u16) as u32, 4 => *addr, _ => { BUG(); } };
    0
}

#[no_mangle]
pub unsafe extern "C" fn pci_olpc_write(seg: u32, bus: u32, devfn: u32, reg: i32, _len: i32, value: u32) -> i32 {
    WARN_ON(seg != 0);
    if !is_simulated(bus, devfn) { return (pci_direct_conf1.write.unwrap())(seg, bus, devfn, reg, _len, value); }
    if reg >= 0x10 && reg < 0x2c { if value == !0 { BAR_PROBING = 1; } }
    0
}

static PCI_OLPC_CONF: PciRawOps = PciRawOps { read: Some(pci_olpc_read), write: Some(pci_olpc_write) };

#[no_mangle]
pub unsafe extern "C" fn pci_olpc_init() -> i32 {
    raw_pci_ops = &PCI_OLPC_CONF;
    IS_LX = is_geode_lx();
    0
}

