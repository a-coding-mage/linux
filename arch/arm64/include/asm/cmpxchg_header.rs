macro_rules! xchg_gen {
    ($name:ident, $b8:ident, $b16:ident, $b32:ident, $b64:ident) => {
        #[inline]
        pub unsafe fn $name(x: usize, ptr: *mut core::ffi::c_void, size: i32) -> usize {
            match size {
                1 => $b8(x as u8, ptr) as usize,
                2 => $b16(x as u16, ptr) as usize,
                4 => $b32(x as u32, ptr) as usize,
                8 => $b64(x as u64, ptr) as usize,
                _ => core::hint::unreachable_unchecked(),
            }
        }
    };
}
xchg_gen!(__arch_xchg, __xchg_case_8, __xchg_case_16, __xchg_case_32, __xchg_case_64);
