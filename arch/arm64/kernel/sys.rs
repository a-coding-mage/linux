// Dependencies supplied by the Linux kernel headers are intentionally not
// implemented here.

#[allow(non_camel_case_types)]
pub type syscall_fn_t = unsafe extern "C" fn(*const pt_regs) -> c_long;

extern "C" {
    pub fn ksys_mmap_pgoff(
        addr: c_ulong,
        len: c_ulong,
        prot: c_ulong,
        flags: c_ulong,
        fd: c_ulong,
        pgoff: c_ulong,
    ) -> c_long;
    pub fn ksys_personality(personality: c_uint) -> c_long;
    pub fn system_supports_32bit_el0() -> bool;
    pub fn sys_ni_syscall() -> c_long;
}

extern "C" {
    static __NR_syscalls: usize;
}

pub unsafe extern "C" fn __arm64_sys_mmap(
    addr: c_ulong,
    len: c_ulong,
    prot: c_ulong,
    flags: c_ulong,
    fd: c_ulong,
    off: c_ulong,
) -> c_long {
    if offset_in_page(off) != 0 {
        return -EINVAL as c_long;
    }

    ksys_mmap_pgoff(addr, len, prot, flags, fd, off >> PAGE_SHIFT)
}

pub unsafe extern "C" fn __arm64_sys_arm64_personality(personality_arg: c_uint) -> c_long {
    if personality(personality_arg) == PER_LINUX32 && !system_supports_32bit_el0() {
        return -EINVAL as c_long;
    }
    ksys_personality(personality_arg)
}

pub unsafe extern "C" fn __arm64_sys_ni_syscall(_unused: *const pt_regs) -> c_long {
    sys_ni_syscall()
}

/* Wrappers to pass the pt_regs argument. */

// __arm64_sys_personality is an alias generated by the C preprocessor.
pub use __arm64_sys_arm64_personality as __arm64_sys_personality;

// The syscall-table include expands to declarations for each architecture
// syscall.  Those declarations are supplied by the corresponding dependency.

#[allow(non_upper_case_globals)]
pub static sys_call_table: [syscall_fn_t; __NR_syscalls] =
    [__arm64_sys_ni_syscall; __NR_syscalls];


