/* Hibernate support specific for ARM64. */

// C headers and build-time kernel dependencies are supplied by the surrounding
// kernel translation unit.

extern "C" {
    static mut in_suspend: core::ffi::c_int;
    static mut __hyp_stub_vectors: [core::ffi::c_char; 0];
}

const EINVAL: i32 = 22;
const EOVERFLOW: i32 = 75;
const ENODEV: i32 = 19;
const ENOMEM: i32 = 12;
const EBUSY: i32 = 16;

#[repr(C)]
pub struct ArchHibernateHdrInvariants {
    pub uts_version: [core::ffi::c_char; __NEW_UTS_LEN + 1],
}

#[repr(C)]
pub struct ArchHibernateHdr {
    pub invariants: ArchHibernateHdrInvariants,
    pub ttbr1_el1: phys_addr_t,
    pub reenter_kernel: Option<unsafe extern "C" fn()>,
    pub __hyp_stub_vectors: phys_addr_t,
    pub sleep_cpu_mpidr: u64,
}

static mut sleep_cpu: i32 = -EINVAL;
static mut resume_hdr: ArchHibernateHdr = unsafe { core::mem::zeroed() };

#[inline]
unsafe fn arch_hdr_invariants(i: *mut ArchHibernateHdrInvariants) {
    memset(i.cast(), 0, core::mem::size_of::<ArchHibernateHdrInvariants>());
    memcpy((*i).uts_version.as_mut_ptr().cast(),
           init_utsname().cast::<Utsname>().as_ref().unwrap().version.as_ptr().cast(),
           core::mem::size_of_val(&(*i).uts_version));
}

#[no_mangle]
pub unsafe extern "C" fn pfn_is_nosave(pfn: c_ulong) -> c_int {
    let nosave_begin_pfn = sym_to_pfn(&__nosave_begin);
    let nosave_end_pfn = sym_to_pfn(__nosave_end.sub(1));
    (((pfn >= nosave_begin_pfn) && (pfn <= nosave_end_pfn)) || crash_is_nosave(pfn)) as c_int
}

pub unsafe extern "C" fn save_processor_state() {}
pub unsafe extern "C" fn restore_processor_state() {}

#[no_mangle]
pub unsafe extern "C" fn arch_hibernation_header_save(addr: *mut core::ffi::c_void, max_size: c_uint) -> c_int {
    let hdr = addr.cast::<ArchHibernateHdr>();
    if (max_size as usize) < core::mem::size_of::<ArchHibernateHdr>() { return -EOVERFLOW; }
    arch_hdr_invariants(&mut (*hdr).invariants);
    (*hdr).ttbr1_el1 = __pa_symbol(&swapper_pg_dir);
    (*hdr).reenter_kernel = Some(_cpu_resume);
    (*hdr).__hyp_stub_vectors = if el2_reset_needed() { __pa_symbol(__hyp_stub_vectors.as_ptr()) } else { 0 };
    if sleep_cpu < 0 { pr_err!("Failing to hibernate on an unknown CPU.\n"); return -ENODEV; }
    (*hdr).sleep_cpu_mpidr = cpu_logical_map(sleep_cpu);
    pr_info!("Hibernating on CPU {} [mpidr:0x{:x}]\n", sleep_cpu, (*hdr).sleep_cpu_mpidr);
    0
}

#[no_mangle]
pub unsafe extern "C" fn arch_hibernation_header_restore(addr: *mut core::ffi::c_void) -> c_int {
    let mut invariants: ArchHibernateHdrInvariants = core::mem::zeroed();
    let hdr = addr.cast::<ArchHibernateHdr>();
    arch_hdr_invariants(&mut invariants);
    if memcmp(&(*hdr).invariants as *const _ as *const _, &invariants as *const _ as *const _, core::mem::size_of_val(&invariants)) != 0 {
        pr_crit!("Hibernate image not generated by this kernel!\n"); return -EINVAL;
    }
    sleep_cpu = get_logical_index((*hdr).sleep_cpu_mpidr);
    pr_info!("Hibernated on CPU {} [mpidr:0x{:x}]\n", sleep_cpu, (*hdr).sleep_cpu_mpidr);
    if sleep_cpu < 0 { pr_crit!("Hibernated on a CPU not known to this kernel!\n"); sleep_cpu = -EINVAL; return -EINVAL; }
    let ret = bringup_hibernate_cpu(sleep_cpu);
    if ret != 0 { sleep_cpu = -EINVAL; return ret; }
    resume_hdr = *hdr;
    0
}

unsafe extern "C" fn hibernate_page_alloc(arg: *mut core::ffi::c_void) -> *mut core::ffi::c_void {
    get_safe_page(arg as usize as gfp_t) as *mut _
}

unsafe fn create_safe_exec_page(src_start: *mut core::ffi::c_void, length: usize, phys_dst_addr: *mut phys_addr_t) -> c_int {
    let mut trans_info = trans_pgd_info { trans_alloc_page: Some(hibernate_page_alloc), trans_alloc_arg: GFP_ATOMIC as usize as *mut _ };
    let page = get_safe_page(GFP_ATOMIC) as *mut core::ffi::c_void;
    if page.is_null() { return -ENOMEM; }
    memcpy(page, src_start, length);
    caches_clean_inval_pou(page as usize, page as usize + length);
    let mut trans_ttbr0 = 0; let mut t0sz = 0;
    let rc = trans_pgd_idmap_page(&mut trans_info, &mut trans_ttbr0, &mut t0sz, page);
    if rc != 0 { return rc; }
    cpu_install_ttbr0(trans_ttbr0, t0sz);
    *phys_dst_addr = virt_to_phys(page);
    0
}

