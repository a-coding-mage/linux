#[no_mangle]
pub unsafe extern "C" fn swsusp_arch_suspend() -> c_int {
    let mut ret = 0; let mut flags = 0; let mut state: sleep_stack_data = core::mem::zeroed();
    if cpus_are_stuck_in_kernel() { pr_err!("Can't hibernate: no mechanism to offline secondary CPUs.\n"); return -EBUSY; }
    flags = local_daif_save();
    if __cpu_suspend_enter(&mut state) != 0 {
        crash_prepare_suspend(); ret = mte::swsusp_mte_save_tags();
        if ret != 0 { local_daif_restore(flags); return ret; }
        sleep_cpu = smp_processor_id(); ret = swsusp_save();
    } else {
        dcache_clean_inval_poc(__mmuoff_data_start as usize, __mmuoff_data_end as usize);
        dcache_clean_inval_poc(__idmap_text_start as usize, __idmap_text_end as usize);
        if el2_reset_needed() { dcache_clean_inval_poc(__hyp_idmap_text_start as usize, __hyp_idmap_text_end as usize); dcache_clean_inval_poc(__hyp_text_start as usize, __hyp_text_end as usize); }
        mte::swsusp_mte_restore_tags(); crash_post_resume(); in_suspend = 0; sleep_cpu = -EINVAL; __cpu_suspend_exit(); spectre_v4_enable_mitigation(core::ptr::null_mut());
    }
    local_daif_restore(flags); ret
}

#[no_mangle]
pub unsafe extern "C" fn swsusp_arch_resume() -> c_int {
    let mut trans_info = trans_pgd_info { trans_alloc_page: Some(hibernate_page_alloc), trans_alloc_arg: GFP_ATOMIC as usize as *mut _ };
    let mut tmp_pg_dir = core::ptr::null_mut(); let rc = trans_pgd_create_copy(&mut trans_info, &mut tmp_pg_dir, PAGE_OFFSET, PAGE_END); if rc != 0 { return rc; }
    let zero_page = get_safe_page(GFP_ATOMIC) as *mut _; if zero_page.is_null() { pr_err!("Failed to allocate zero page.\n"); return -ENOMEM; }
    let mut el2_vectors = 0; if el2_reset_needed() { let rc = trans_pgd_copy_el2_vectors(&mut trans_info, &mut el2_vectors); if rc != 0 { pr_err!("Failed to setup el2 vectors\n"); return rc; } }
    let exit_size = __hibernate_exit_text_end as usize - __hibernate_exit_text_start as usize;
    let mut hibernate_exit = core::ptr::null_mut(); let rc = create_safe_exec_page(__hibernate_exit_text_start as *mut _, exit_size, &mut hibernate_exit as *mut _ as *mut _); if rc != 0 { pr_err!("Failed to create safe executable page for hibernate_exit code.\n"); return rc; }
    if el2_reset_needed() { __hyp_set_vectors(el2_vectors); }
    local_daif_save();
    core::mem::transmute::<*mut _, unsafe extern "C" fn(phys_addr_t, phys_addr_t, Option<unsafe extern "C" fn()>, *mut core::ffi::c_void, phys_addr_t, phys_addr_t) -> !>(hibernate_exit)(virt_to_phys(tmp_pg_dir), resume_hdr.ttbr1_el1, resume_hdr.reenter_kernel, restore_pblist, resume_hdr.__hyp_stub_vectors, virt_to_phys(zero_page));
}

pub unsafe extern "C" fn hibernate_resume_nonboot_cpu_disable() -> c_int { if sleep_cpu < 0 { pr_err!("Failing to resume from hibernate on an unknown CPU.\n"); return -ENODEV; } freeze_secondary_cpus(sleep_cpu) }

