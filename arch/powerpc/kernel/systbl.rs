// Dependencies supplied by the surrounding kernel translation:
// linux/syscalls.h, linux/compat.h, asm/unistd.h, and asm/syscalls.h.

// The C __SYSCALL_WITH_COMPAT macro is intentionally mapped to the native
// syscall entry in the non-compat table.
macro_rules! __SYSCALL_WITH_COMPAT {
    ($nr:expr, $entry:expr, $compat:expr) => { __SYSCALL!($nr, $entry) };
}

// With CONFIG_ARCH_HAS_SYSCALL_WRAPPER, entries have the syscall_fn type
// directly. Otherwise C coerces arbitrary syscall handlers through void *;
// the surrounding Rust declarations must provide the corresponding type.
#[cfg(CONFIG_ARCH_HAS_SYSCALL_WRAPPER)]
macro_rules! __SYSCALL {
    ($nr:expr, $entry:expr) => { [$nr] = $entry };
}

#[cfg(not(CONFIG_ARCH_HAS_SYSCALL_WRAPPER))]
macro_rules! __SYSCALL {
    ($nr:expr, $entry:expr) => { [$nr] = $entry as *const core::ffi::c_void };
}

// The following architecture-specific syscall table is generated by the
// included kernel table (asm/syscall_table_64.h or asm/syscall_table_32.h).
// Its declarations are an external dependency of this translation.
#[cfg(CONFIG_PPC64)]
pub static sys_call_table: &[syscall_fn] = &[
    // __SYSCALL entries from asm/syscall_table_64.h
];

#[cfg(not(CONFIG_PPC64))]
pub static sys_call_table: &[syscall_fn] = &[
    // __SYSCALL entries from asm/syscall_table_32.h
];

#[cfg(CONFIG_COMPAT)]
macro_rules! __SYSCALL_WITH_COMPAT {
    ($nr:expr, $native:expr, $compat:expr) => { __SYSCALL!($nr, $compat) };
}

#[cfg(CONFIG_COMPAT)]
pub static compat_sys_call_table: &[syscall_fn] = &[
    // __SYSCALL entries from asm/syscall_table_32.h
];

