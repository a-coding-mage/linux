/* Performance counter support for POWER7 processors. */

use core::ffi::c_void;

// Kernel dependencies supplied by other translation units.
// The C include files and power7-events-list.h are intentionally not copied here.

const PM_PMC_SH: u64 = 16;
const PM_PMC_MSK: u64 = 0xf;
const PM_PMC_MSKS: u64 = PM_PMC_MSK << PM_PMC_SH;
const PM_UNIT_SH: u64 = 12;
const PM_UNIT_MSK: u64 = 0xf;
const PM_COMBINE_SH: u64 = 11;
const PM_COMBINE_MSK: u64 = 1;
const PM_COMBINE_MSKS: u64 = 0x800;
const PM_L2SEL_SH: u64 = 8;
const PM_L2SEL_MSK: u64 = 7;
const PM_PMCSEL_MSK: u64 = 0xff;

const MMCR1_TTM0SEL_SH: u64 = 60;
const MMCR1_TTM1SEL_SH: u64 = 56;
const MMCR1_TTM2SEL_SH: u64 = 52;
const MMCR1_TTM3SEL_SH: u64 = 48;
const MMCR1_TTMSEL_MSK: u64 = 0xf;
const MMCR1_L2SEL_SH: u64 = 45;
const MMCR1_L2SEL_MSK: u64 = 7;
const MMCR1_PMC1_COMBINE_SH: u64 = 35;
const MMCR1_PMC2_COMBINE_SH: u64 = 34;
const MMCR1_PMC3_COMBINE_SH: u64 = 33;
const MMCR1_PMC4_COMBINE_SH: u64 = 32;
const MMCR1_PMC1SEL_SH: u64 = 24;
const MMCR1_PMC2SEL_SH: u64 = 16;
const MMCR1_PMC3SEL_SH: u64 = 8;
const MMCR1_PMC4SEL_SH: u64 = 0;
const MMCR1_PMCSEL_MSK: u64 = 0xff;

const fn mmcr1_pmcsel_sh(n: u64) -> u64 { MMCR1_PMC1SEL_SH - n * 8 }

// The C enum is generated by power7-events-list.h. Its event constants are external
// dependencies of this isolated translation and are referenced below by their names.

const MAX_ALT: usize = 2;

#[repr(C)]
pub struct MmcrRegs { pub mmcr0: u64, pub mmcr1: u64, pub mmcra: u64 }

#[repr(C)]
pub struct PerfEvent { _private: [u8; 0] }

extern "C" {
    fn register_power_pmu(pmu: *mut PowerPmu) -> i32;
    fn mfspr(spr: u32) -> u32;
}

const PPMU_ONLY_COUNT_RUN: u32 = 1 << 0;
const MMCRA_SDAR_DCACHE_MISS: u64 = 1 << 0;
const MMCRA_SDAR_ERAT_MISS: u64 = 1 << 1;
const MMCRA_SAMPLE_ENABLE: u64 = 1 << 2;
const MMCR0_PMC1CE: u64 = 1 << 0;
const MMCR0_PMCjCE: u64 = 1 << 1;
const PPMU_ALT_SIPR: u32 = 1 << 0;
const PPMU_SIAR_VALID: u32 = 1 << 1;

unsafe fn power7_get_constraint(event: u64, maskp: *mut u64, valp: *mut u64, _event_config1: u64) -> i32 {
    let pmc = (event >> PM_PMC_SH) & PM_PMC_MSK;
    let mut mask = 0u64;
    let mut value = 0u64;
    if pmc != 0 {
        if pmc > 6 { return -1; }
        let sh = (pmc - 1) * 2;
        mask |= 2u64 << sh;
        value |= 1u64 << sh;
        if pmc >= 5 && event != 0x500fa && event != 0x600f4 { return -1; }
    }
    if pmc < 5 { mask |= 0x8000; value |= 0x1000; }
    let unit = (event >> PM_UNIT_SH) & PM_UNIT_MSK;
    if unit == 6 {
        let l2sel = (event >> PM_L2SEL_SH) & PM_L2SEL_MSK;
        mask |= 0x7 << 16;
        value |= l2sel << 16;
    }
    *maskp = mask; *valp = value; 0
}

static EVENT_ALTERNATIVES: [[u32; MAX_ALT]; 3] = [
    [0x200f2, 0x300f2], [0x200f4, 0x600f4], [0x400fa, 0x500fa],
];

fn find_alternative(event: u64) -> i32 {
    for (i, row) in EVENT_ALTERNATIVES.iter().enumerate() {
        if event < row[0] as u64 { break; }
        for &v in row.iter() { if v != 0 && event == v as u64 { return i as i32; } }
    }
    -1
}

fn find_alternative_decode(event: u64) -> i64 {
    let pmc = (event >> PM_PMC_SH) & PM_PMC_MSK;
    let psel = event & PM_PMCSEL_MSK;
    if (pmc == 2 || pmc == 4) && (psel & !7) == 0x40 { return event as i64 - (1i64 << PM_PMC_SH) + 8; }
    if (pmc == 1 || pmc == 3) && (psel & !7) == 0x48 { return event as i64 + (1i64 << PM_PMC_SH) - 8; }
    -1
}

fn power7_get_alternatives(event: u64, flags: u32, alt: &mut [u64]) -> i32 {
    alt[0] = event; let mut nalt = 1usize;
    let i = find_alternative(event);
    if i >= 0 {
        for &ae in EVENT_ALTERNATIVES[i as usize].iter() { if ae != 0 && ae as u64 != event { alt[nalt] = ae as u64; nalt += 1; } }
    } else { let ae = find_alternative_decode(event); if ae > 0 { alt[nalt] = ae as u64; nalt += 1; } }
    if flags & PPMU_ONLY_COUNT_RUN != 0 {
        let mut j = nalt;
        for i in 0..nalt { match alt[i] { 0x1e => { alt[j] = 0x600f4; j += 1; }, 0x600f4 => { alt[j] = 0x1e; j += 1; }, 0x2 => { alt[j] = 0x500fa; j += 1; }, 0x500fa => { alt[j] = 0x2; j += 1; }, _ => {} } }
        nalt = j;
    }
    nalt as i32
}

fn power7_marked_instr_event(event: u64) -> i32 {
    let pmc = (event >> PM_PMC_SH) & PM_PMC_MSK;
    let unit = (event >> PM_UNIT_SH) & PM_UNIT_MSK;
    let psel = event & PM_PMCSEL_MSK & !1;
    if pmc >= 5 { return 0; }
    match psel >> 4 {
        2 => (pmc == 2 || pmc == 4) as i32,
        3 => if psel == 0x3c { (pmc == 1) as i32 } else if psel == 0x3e { (pmc != 2) as i32 } else { 1 },
        4 | 5 | 8 => (unit == 0xd) as i32,
        6 => if psel == 0x64 { (pmc >= 3) as i32 } else { 0 },
        _ => 0,
    }
}

unsafe fn power7_compute_mmcr(event: *const u64, n_ev: usize, hwc: *mut u32, mmcr: *mut MmcrRegs, _pevents: *mut *mut PerfEvent, _flags: u32) -> i32 {
    let mut mmcr1 = 0u64; let mut mmcra = MMCRA_SDAR_DCACHE_MISS | MMCRA_SDAR_ERAT_MISS; let mut pmc_inuse = 0u32;
    for i in 0..n_ev { let pmc = (*event.add(i) >> PM_PMC_SH) & PM_PMC_MSK; if pmc != 0 { if pmc > 6 || pmc_inuse & (1 << (pmc - 1)) != 0 { return -1; } pmc_inuse |= 1 << (pmc - 1); } }
    for i in 0..n_ev {
        let e = *event.add(i); let requested = (e >> PM_PMC_SH) & PM_PMC_MSK; let unit = (e >> PM_UNIT_SH) & PM_UNIT_MSK; let combine = (e >> PM_COMBINE_SH) & PM_COMBINE_MSK; let l2sel = (e >> PM_L2SEL_SH) & PM_L2SEL_MSK; let psel = e & PM_PMCSEL_MSK;
        let pmc = if requested == 0 { let mut p = 0; while p < 4 && pmc_inuse & (1 << p) != 0 { p += 1; } if p >= 4 { return -1; } pmc_inuse |= 1 << p; p } else { requested - 1 };
        if pmc <= 3 { mmcr1 |= unit << (60 - 4 * pmc); mmcr1 |= combine << (35 - pmc); mmcr1 |= psel << mmcr1_pmcsel_sh(pmc); if unit == 6 { mmcr1 |= l2sel << MMCR1_L2SEL_SH; } }
        if power7_marked_instr_event(e) != 0 { mmcra |= MMCRA_SAMPLE_ENABLE; } *hwc.add(i) = pmc as u32;
    }
    (*mmcr).mmcr0 = if pmc_inuse & 1 != 0 { MMCR0_PMC1CE } else { 0 }; if pmc_inuse & 0x3e != 0 { (*mmcr).mmcr0 |= MMCR0_PMCjCE; } (*mmcr).mmcr1 = mmcr1; (*mmcr).mmcra = mmcra; 0
}

unsafe fn power7_disable_pmc(pmc: u32, mmcr: *mut MmcrRegs) { if pmc <= 3 { (*mmcr).mmcr1 &= !(0xffu64 << mmcr1_pmcsel_sh(pmc as u64)); } }

// Generic event identifiers, attribute declarations, cache-event tables, and the
// power7_pmu descriptor are generated/typed by the kernel dependencies referenced above.

#[no_mangle]
pub unsafe extern "C" fn init_power7_pmu() -> i32 {
    let pvr = mfspr(0);
    let ver = pvr >> 16;
    if ver != 0x003f && ver != 0x0040 { return -19; }
    if ver == 0x0040 { /* power7_pmu.flags |= PPMU_SIAR_VALID; */ }
    // register_power_pmu(&mut power7_pmu)
    let _ = register_power_pmu(core::ptr::null_mut());
    0
}

