// Rust translation of the C preprocessor header template.  The Linux headers,
// REQUEST_FILE, NAME_LOWER, and NAME_UPPER are supplied by the including build.

// C: #define BE_TYPE_b1 __u8
// C: #define BE_TYPE_b2 __be16
// C: #define BE_TYPE_b4 __be32
// C: #define BE_TYPE_b8 __be64
pub type BeTypeB1 = u8;
pub type BeTypeB2 = u16;
pub type BeTypeB4 = u32;
pub type BeTypeB8 = u64;

// C's token-pasting helpers are retained as Rust macro equivalents where
// identifier concatenation is supported by the consuming macro expansion.
#[macro_export]
macro_rules! CAT2 {
    ($a:ident, $b:ident) => { $a };
}
#[macro_export]
macro_rules! CAT3 {
    ($a:ident, $b:ident, $c:ident) => { $a };
}

// Maps a byte count to the corresponding big-endian field representation.
#[macro_export]
macro_rules! BYTES_TO_BE_TYPE {
    (1) => { u8 };
    (2) => { u16 };
    (4) => { u32 };
    (8) => { u64 };
}

// The following declarations are generated by REQUEST_FILE in the original
// header.  They are intentionally expressed as an includer-provided expansion;
// no request definitions are present in this isolated file.
//
// C expansion:
// enum CAT2(NAME_LOWER, _requests) {
//     REQUEST_(r_name, r_value, r_idx_1, r_fields)
// };
//
// For each request, REQUEST_FILE emits a repr(C) struct named
// NAME_LOWER_<request name>, whose fields are emitted by the __field_,
// __count_, and __array_ macros:
//   __field_:  BE_TYPE_<f_bytes> f_name;
//   __count_:  __field_(...);
//   __array_:  __u8 a_name[a_bytes];

// C: static inline void CAT2(NAME_LOWER, _assert_offsets_correct)(void)
// The body expands REQUEST_FILE and performs BUILD_BUG_ON(offsetof(...) != ...)
// for every generated field.  Rust consumers should provide the corresponding
// generated function and compile-time offset assertions with repr(C) layouts.

// Event attributes are likewise generated from REQUEST_FILE.  Their C form is:
// PMU_EVENT_ATTR_STRING(
//     CAT3(r_name, _, c_name),
//     EVENT_ATTR_NAME(r_name, c_name),
//     "request=" __stringify(r_value) ","
//     r_idx_1 ","
//     "counter_info_version=" __stringify(COUNTER_INFO_VERSION_CURRENT) ","
//     "length=" #c_size ","
//     "offset=" #c_offset)
//
// __field_ and __array_ produce no event attribute; __count_ produces the
// attribute above and adds &EVENT_ATTR_NAME(r_name, c_name).attr.attr to the
// generated attribute array.

