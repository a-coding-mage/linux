//! Embed an optional IPE boot policy as a byte-preserving C string.

use std::fs::File;
use std::io::{self, BufWriter, Read, Seek, SeekFrom, Write};
use std::path::Path;

const HEADER: &[u8] = b"/* This file is automatically generated. Do not edit. */\n\
#include <linux/stddef.h>\n\nextern const char *const ipe_boot_policy;\n\n\
const char *const ipe_boot_policy =\n";

struct Failure {
    status: i32,
    error: io::Error,
}

impl From<io::Error> for Failure {
    fn from(error: io::Error) -> Self {
        Self {
            status: error.raw_os_error().unwrap_or(5),
            error,
        }
    }
}

fn allocation_failure() -> Failure {
    io::Error::from_raw_os_error(12).into()
}

fn policy(path: &Path) -> Result<Vec<u8>, Failure> {
    let mut file = File::open(path)?;
    // Match the original snapshot length, including procfs files whose seek
    // to the end fails but whose current position is still zero.
    let _ = file.seek(SeekFrom::End(0));
    let size: usize = file
        .stream_position()
        .map_err(|_| allocation_failure())?
        .try_into()
        .map_err(|_| allocation_failure())?;
    let _ = file.rewind();
    let mut data = Vec::new();
    data.try_reserve_exact(size)
        .map_err(|_| allocation_failure())?;
    data.resize(size, 0);
    file.read_exact(&mut data).map_err(|error| Failure {
        status: 255,
        error: error
            .raw_os_error()
            .map(io::Error::from_raw_os_error)
            .unwrap_or_else(|| io::Error::from_raw_os_error(0)),
    })?;
    Ok(data)
}

fn write_policy(path: &Path, policy: &[u8]) -> io::Result<()> {
    let mut file = BufWriter::new(File::create(path)?);
    file.write_all(HEADER)?;
    if policy.is_empty() {
        file.write_all(b"\tNULL;\n")?;
    } else {
        file.write_all(b"\t\"")?;
        for byte in policy {
            match byte {
                b'"' => file.write_all(b"\\\"")?,
                b'\n' => file.write_all(b"\\n\"\n\t\"")?,
                b'\\' => file.write_all(b"\\\\")?,
                b'\t' => file.write_all(b"\\t")?,
                b'?' => file.write_all(b"\\?")?,
                byte => file.write_all(std::slice::from_ref(byte))?,
            }
        }
        file.write_all(b"\";\n")?;
    }
    // Unlike the C implementation, do not report success after buffered
    // output fails (for example, ENOSPC on the destination filesystem).
    file.flush()
}

fn run(arguments: &[std::ffi::OsString]) -> Result<(), Failure> {
    let data = match arguments.get(2) {
        Some(input) => policy(Path::new(input))?,
        None => Vec::new(),
    };
    write_policy(Path::new(&arguments[1]), &data)?;
    Ok(())
}

fn main() {
    let arguments: Vec<_> = std::env::args_os().collect();
    if arguments.len() < 2 {
        let mut output = io::stdout().lock();
        let _ = output.write_all(b"Usage: ");
        let _ = output.write_all(arguments[0].as_encoded_bytes());
        let _ = output.write_all(b" OutputFile (PolicyFile)\n");
        std::process::exit(22);
    }
    if let Err(failure) = run(&arguments) {
        let message = failure.error.to_string();
        let message = message.split(" (os error ").next().unwrap_or(&message);
        eprintln!("An error occurred during policy conversion: : {message}");
        std::process::exit(failure.status);
    }
}

