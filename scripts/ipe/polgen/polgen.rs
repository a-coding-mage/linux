use std::env;
use std::ffi::CStr;
use std::fs::File;
use std::io::{self, Read, Write};
use std::os::raw::c_char;
use std::process;

unsafe fn usage(name: *const c_char) {
    let name = CStr::from_ptr(name).to_string_lossy();
    println!("Usage: {} OutputFile (PolicyFile)", name);
    process::exit(22);
}

unsafe fn policy_to_buffer(pathname: *const c_char, buffer: *mut *mut c_char, size: *mut usize) -> i32 {
    let pathname = CStr::from_ptr(pathname).to_string_lossy();
    let mut fd = match File::open(pathname.as_ref()) {
        Ok(file) => file,
        Err(error) => return error.raw_os_error().unwrap_or(5),
    };

    let mut bytes = Vec::new();
    if fd.read_to_end(&mut bytes).is_err() {
        return -1;
    }

    let fsize = bytes.len();
    let mut lbuf = bytes.into_boxed_slice();
    let ptr = lbuf.as_mut_ptr();
    std::mem::forget(lbuf);

    *buffer = ptr as *mut c_char;
    *size = fsize;
    0
}

unsafe fn write_boot_policy(pathname: *const c_char, buf: *const c_char, size: usize) -> i32 {
    let pathname = CStr::from_ptr(pathname).to_string_lossy();
    let mut fd = match File::create(pathname.as_ref()) {
        Ok(file) => file,
        Err(error) => return error.raw_os_error().unwrap_or(5),
    };

    let _ = write!(fd, "/* This file is automatically generated.");
    let _ = write!(fd, " Do not edit. */\n");
    let _ = write!(fd, "#include <linux/stddef.h>\n");
    let _ = write!(fd, "\nextern const char *const ipe_boot_policy;\n\n");
    let _ = write!(fd, "const char *const ipe_boot_policy =\n");

    if buf.is_null() || size == 0 {
        let _ = write!(fd, "\tNULL;\n");
        return 0;
    }

    let _ = write!(fd, "\t\"");
    for i in 0..size {
        match *buf.add(i) as u8 {
            b'"' => { let _ = write!(fd, "\\\""); }
            b'\'' => { let _ = write!(fd, "'"); }
            b'\n' => { let _ = write!(fd, "\\n\"\n\t\""); }
            b'\\' => { let _ = write!(fd, "\\\\"); }
            b'\t' => { let _ = write!(fd, "\\t"); }
            b'?' => { let _ = write!(fd, "\\?"); }
            value => { let _ = write!(fd, "{}", value as char); }
        }
    }
    let _ = write!(fd, "\";\n");
    0
}

fn main() {
    let args: Vec<_> = env::args_os().collect();
    let mut policy: *mut c_char = std::ptr::null_mut();
    let mut len: usize = 0;
    let mut rc: i32 = 0;

    if args.len() < 2 {
        let name = std::ffi::CString::new(args[0].to_string_lossy().as_bytes()).unwrap();
        unsafe { usage(name.as_ptr()); }
    }

    if args.len() > 2 {
        let pathname = std::ffi::CString::new(args[2].to_string_lossy().as_bytes()).unwrap();
        rc = unsafe { policy_to_buffer(pathname.as_ptr(), &mut policy, &mut len) };
        if rc != 0 {
            if !policy.is_null() { unsafe { drop(Vec::from_raw_parts(policy, len, len)); } }
            eprintln!("An error occurred during policy conversion: {}", io::Error::from_raw_os_error(rc));
            process::exit(rc);
        }
    }

    let pathname = std::ffi::CString::new(args[1].to_string_lossy().as_bytes()).unwrap();
    rc = unsafe { write_boot_policy(pathname.as_ptr(), policy, len) };
    if !policy.is_null() { unsafe { drop(Vec::from_raw_parts(policy, len, len)); } }
    if rc != 0 {
        eprintln!("An error occurred during policy conversion: {}", io::Error::from_raw_os_error(rc));
    }
    process::exit(rc);
}

