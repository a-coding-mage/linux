//! Normalize original per-module metadata fields into actual typed Rust objects.

use crate::c_literal::{fields, identifier, quoted_end, strings, text};
use std::fmt::Write;

const HOOKS: &str = "#ifndef MODULE\n#error Rust per-module metadata requires MODULE\n#endif\n#ifdef __GNUC_EXECUTION_CHARSET_NAME\nLUPOS_MODULE_CHARSET __GNUC_EXECUTION_CHARSET_NAME;\n#elif defined(__clang__)\nLUPOS_MODULE_CHARSET \"UTF-8\";\n#else\n#error Unknown C frontend execution charset\n#endif\nLUPOS_MODULE_INPUT_UTF8 \"é\";\nLUPOS_MODULE_LOGICAL_SOURCE __FILE__, __BASE_FILE__;\n#define LUPOS_STRINGIFY_REF(sym) #sym\n#undef __KSYMTAB\n#define __KSYMTAB(name, sym, ns) LUPOS_MODULE_KSYM #name, LUPOS_STRINGIFY_REF(sym), ns\n#undef SYMBOL_FLAGS\n#define SYMBOL_FLAGS(sym, flags) LUPOS_MODULE_FLAGS #sym, #flags\n#undef SYMBOL_CRC\n#define SYMBOL_CRC(sym, crc) LUPOS_MODULE_CRC #sym, #crc\n#undef __MODULE_INFO_PREFIX\n#define __MODULE_INFO_PREFIX LUPOS_MODULE_INFO\n";

/// Retain the authoritative original C body, adding record-only delimiters.
pub(crate) fn header(original: &str, filename: &str) -> Result<String, String> {
    // Filename is inserted in a #line C literal, not interpreted as Rust.
    let filename = filename.replace('\\', "\\\\").replace('"', "\\\"");
    if filename.contains(['\n', '\r']) {
        return Err(
            "module metadata source filename contains newline; use retained C selection\n".into(),
        );
    }
    let count = original
        .lines()
        .filter(|line| {
            line.starts_with("MODULE_INFO(")
                || line.starts_with("MODULE_ALIAS(")
                || line.starts_with("KSYMTAB_")
                || line.starts_with("SYMBOL_")
                || line.starts_with("__section(\".gnu.linkonce.this_module\") = {")
                || line.starts_with("__used __section(\"__versions\") = {")
                || line.starts_with("__used __section(\"__version_ext_crcs\") = {")
                || line.starts_with("__used __section(\"__version_ext_names\") =")
        })
        .count();
    let mut out = format!("/* Generated by modpost; validate original C, then normalize fields. */\n#line 1 \"{filename}\"\n");
    for (index, line) in original.lines().enumerate() {
        writeln!(out, "{line}").unwrap();
        let marker = if line == "#include <linux/compiler.h>" {
            writeln!(
                out,
                "#ifdef LUPOS_RUST_MODULE_RECORDS\nLUPOS_MODULE_COUNT {count};\n{HOOKS}#endif"
            )
            .unwrap();
            None
        } else if line == "__section(\".gnu.linkonce.this_module\") = {" {
            Some("OWNER")
        } else if line == "__used __section(\"__versions\") = {" {
            Some("BASIC")
        } else if line == "__used __section(\"__version_ext_crcs\") = {" {
            Some("EXT_CRCS")
        } else if line == "__used __section(\"__version_ext_names\") =" {
            Some("EXT_NAMES")
        } else {
            continue;
        };
        if let Some(marker) = marker {
            writeln!(
                out,
                "#ifdef LUPOS_RUST_MODULE_RECORDS\nLUPOS_MODULE_{marker}\n#endif"
            )
            .unwrap();
        }
        writeln!(out, "#line {} \"{filename}\"", index + 2).unwrap();
    }
    out.push_str("#ifdef LUPOS_RUST_MODULE_RECORDS\nLUPOS_MODULE_END;\n#endif\n");
    Ok(out)
}

fn comma_list(input: &[u8]) -> Result<Vec<&[u8]>, String> {
    let mut result = Vec::new();
    let mut begin = 0;
    let mut at = 0;
    let mut depth = 0_usize;
    while at < input.len() {
        match input[at] {
            b'\'' | b'"' => {
                at = quoted_end(input, at)?;
                continue;
            }
            b'{' => depth += 1,
            b'}' => depth = depth.checked_sub(1).ok_or("unbalanced initializer")?,
            b',' if depth == 0 => {
                result.push(input[begin..at].trim_ascii());
                begin = at + 1;
            }
            _ => (),
        }
        at += 1;
    }
    if depth != 0 {
        return Err("unbalanced initializer".into());
    }
    if !input[begin..].trim_ascii().is_empty() {
        result.push(input[begin..].trim_ascii());
    }
    Ok(result)
}

fn body(value: &[u8]) -> Result<&[u8], String> {
    value
        .trim_ascii()
        .strip_suffix(b"}")
        .ok_or_else(|| "missing initializer close".into())
}

fn hexadecimal(value: &[u8]) -> Result<u32, String> {
    let value = std::str::from_utf8(value.trim_ascii())
        .map_err(|_| "invalid generated hexadecimal value")?;
    let value = value
        .strip_prefix("0x")
        .ok_or("expected generated hexadecimal value")?;
    u32::from_str_radix(value, 16).map_err(|_| "invalid generated hexadecimal value".into())
}

fn owner(value: &[u8], out: &mut String) -> Result<(), String> {
    let values = comma_list(body(value)?)?;
    let mut name = None;
    let mut init = false;
    let mut exit = false;
    let mut arch = false;
    let mut previous = 0;
    for value in values {
        let equals = value
            .iter()
            .position(|&b| b == b'=')
            .ok_or("invalid owner field")?;
        let (key, value) = (
            value[..equals].trim_ascii(),
            value[equals + 1..].trim_ascii(),
        );
        let order = match key {
            b".name" if name.is_none() => {
                name = Some(strings(value)?);
                1
            }
            b".init" if !init && value == b"init_module" => {
                init = true;
                2
            }
            b".exit" if !exit && value == b"cleanup_module" => {
                exit = true;
                3
            }
            b".arch" if !arch => {
                if value
                    .iter()
                    .copied()
                    .filter(|b| !b.is_ascii_whitespace())
                    .collect::<Vec<_>>()
                    != b"{}"
                {
                    return Err("nonempty MODULE_ARCH_INIT requires retained C selection".into());
                }
                arch = true;
                4
            }
            _ => return Err("unexpected or duplicate module-owner initializer field".into()),
        };
        if order <= previous {
            return Err("module-owner initializer fields out of order".into());
        }
        previous = order;
    }
    let name = name.ok_or("missing module name")?;
    if !arch {
        return Err("missing MODULE_ARCH_INIT".into());
    }
    let mutable = if init || exit { "mut " } else { "" };
    writeln!(out, "/// Loader-owned module state; this is not the implementation owner.\n#[used]\n#[no_mangle]\n#[link_section = \".gnu.linkonce.this_module\"]\npub static mut __this_module: bindings::module = {{\n    let {mutable}value = module_value(&{name:?});").unwrap();
    if init {
        out.push_str("    value.init = Some(bindings::init_module);\n");
    }
    if exit {
        out.push_str("    value.exit = Some(bindings::cleanup_module);\n");
    }
    out.push_str("    value\n};\n");
    Ok(())
}

pub(crate) fn generate(input: &[u8]) -> Result<String, String> {
    let mut at = 0;
    let mut expected = None;
    let mut count = 0;
    let mut guards = 0_u8;
    let mut ended = false;
    let mut seen_owner = false;
    let mut seen_basic = false;
    let mut seen_crcs = None;
    let mut seen_names = false;
    let mut out = String::from("// Generated from original target-preprocessed module metadata.\n");
    while at < input.len() {
        match input[at] {
            b'\'' | b'"' => {
                at = quoted_end(input, at)?;
                continue;
            }
            byte if identifier(byte) => (),
            _ => {
                at += 1;
                continue;
            }
        }
        let begin = at;
        while at < input.len() && identifier(input[at]) {
            at += 1;
        }
        let name = &input[begin..at];
        if !name.starts_with(b"LUPOS_MODULE_") {
            continue;
        }
        if ended {
            return Err("module record after terminal marker".into());
        }
        let begin = at;
        while at < input.len() && input[at] != b';' {
            if matches!(input[at], b'\'' | b'"') {
                at = quoted_end(input, at)?;
            } else {
                at += 1;
            }
        }
        if at == input.len() {
            return Err("unterminated module metadata record".into());
        }
        let value = input[begin..at].trim_ascii();
        at += 1;
        match name {
            b"LUPOS_MODULE_COUNT" if expected.is_none() && count == 0 => {
                expected = Some(
                    std::str::from_utf8(value)
                        .map_err(|_| "invalid record count")?
                        .parse::<usize>()
                        .map_err(|_| "invalid record count")?,
                );
            }
            b"LUPOS_MODULE_CHARSET" if expected.is_some() && guards & 1 == 0 && count == 0 => {
                let value = text(value)?;
                if !value.eq_ignore_ascii_case("UTF-8") && !value.eq_ignore_ascii_case("UTF8") {
                    return Err("Rust module metadata requires UTF-8 execution encoding; use retained C selection".into());
                }
                guards |= 1;
            }
            b"LUPOS_MODULE_INPUT_UTF8" if expected.is_some() && guards & 2 == 0 && count == 0 => {
                if strings(value)? != b"\xc3\xa9\0" {
                    return Err("Rust module metadata requires UTF-8 input encoding; use retained C selection".into());
                }
                guards |= 2;
            }
            b"LUPOS_MODULE_LOGICAL_SOURCE"
                if expected.is_some() && guards & 4 == 0 && count == 0 =>
            {
                let value = fields(value)?;
                if value.len() != 2 || strings(value[0])? != strings(value[1])? {
                    return Err("module source filename mapping differs for __FILE__ and __BASE_FILE__; use retained C selection".into());
                }
                guards |= 4;
            }
            b"LUPOS_MODULE_END"
                if value.is_empty()
                    && guards == 7
                    && expected == Some(count)
                    && seen_owner
                    && seen_crcs.is_some() == seen_names =>
            {
                ended = true
            }
            _ => {
                if expected.is_none() || guards != 7 {
                    return Err("module record precedes required guards".into());
                }
                match name {
                    b"LUPOS_MODULE_OWNER" if !seen_owner => {
                        owner(value, &mut out)?;
                        seen_owner = true;
                    }
                    b"LUPOS_MODULE_BASIC" if !seen_basic => {
                        let rows = comma_list(body(value)?)?;
                        writeln!(out, "#[used]\n#[link_section = \"__versions\"]\nstatic ____VERSIONS: [bindings::modversion_info; {}] = [", rows.len()).unwrap();
                        for row in rows {
                            let row = row
                                .strip_prefix(b"{")
                                .and_then(|row| row.trim_ascii().strip_suffix(b"}"))
                                .ok_or("invalid basic version entry")?;
                            let row = fields(row)?;
                            if row.len() != 2 {
                                return Err("invalid basic version entry field count".into());
                            }
                            writeln!(
                                out,
                                "    version_value(0x{:08x}, &{:?}),",
                                hexadecimal(row[0])?,
                                strings(row[1])?
                            )
                            .unwrap();
                        }
                        out.push_str("];\n");
                        seen_basic = true;
                    }
                    b"LUPOS_MODULE_EXT_CRCS" if seen_crcs.is_none() => {
                        let values = comma_list(body(value)?)?
                            .into_iter()
                            .map(hexadecimal)
                            .collect::<Result<Vec<_>, _>>()?;
                        writeln!(out, "#[used]\n#[link_section = \"__version_ext_crcs\"]\nstatic ____VERSION_EXT_CRCS: [u32; {}] = {:?};", values.len(), values).unwrap();
                        seen_crcs = Some(values.len());
                    }
                    b"LUPOS_MODULE_EXT_NAMES" if !seen_names => {
                        let values = strings(value)?;
                        // Each name carries its explicit terminator; C adds
                        // one more NUL to the concatenated string initializer.
                        // Counting NULs alone also accepts an unterminated
                        // final name after an earlier embedded terminator.
                        if values != [0] && !values.ends_with(&[0, 0]) {
                            return Err("extended version names lack final explicit NUL".into());
                        }
                        if values[..values.len() - 1]
                            .split_inclusive(|&b| b == 0)
                            .any(|name| name == [0])
                        {
                            return Err("extended version name is empty".into());
                        }
                        if seen_crcs
                            != Some(values.iter().filter(|&&b| b == 0).count().saturating_sub(1))
                        {
                            return Err("extended version names and CRC counts differ".into());
                        }
                        writeln!(out, "#[used]\n#[link_section = \"__version_ext_names\"]\nstatic ____VERSION_EXT_NAMES: [u8; {}] = {:?};", values.len(), values).unwrap();
                        seen_names = true;
                    }
                    b"LUPOS_MODULE_INFO" => {
                        let value = strings(value)?;
                        if value[..value.len() - 1].contains(&0) {
                            return Err("MODULE_INFO rejects embedded NUL".into());
                        }
                        writeln!(out, "#[used]\n#[link_section = \".modinfo\"]\nstatic __MODULE_INFO_{count}: [u8; {}] = {:?};", value.len(), value).unwrap();
                    }
                    b"LUPOS_MODULE_KSYM" | b"LUPOS_MODULE_FLAGS" | b"LUPOS_MODULE_CRC" => {
                        // Reuse the existing normalized export emitter, not an
                        // independent string decoder or assembler implementation.
                        let suffix = std::str::from_utf8(&name[b"LUPOS_MODULE_".len()..]).unwrap();
                        let mut record = "LUPOS_EXPORT_COUNT 1; LUPOS_EXPORT_CHARSET \"UTF-8\"; LUPOS_EXPORT_INPUT_UTF8 \"é\"; LUPOS_EXPORT_LOGICAL_SOURCE \"same\", \"same\"; ".as_bytes().to_vec();
                        record.extend_from_slice(format!("LUPOS_EXPORT_{suffix} ").as_bytes());
                        record.extend_from_slice(value);
                        record.extend_from_slice(b"; LUPOS_EXPORT_END;");
                        out.push_str(&crate::vmlinux_export_data::generate(&record)?);
                    }
                    _ => {
                        return Err(format!(
                            "unknown, duplicate or misplaced module metadata record: {}",
                            String::from_utf8_lossy(name)
                        ))
                    }
                }
                count += 1;
                if count > expected.unwrap() {
                    return Err("too many module metadata records".into());
                }
            }
        }
    }
    if !ended {
        return Err("missing or invalid terminal module metadata marker".into());
    }
    Ok(out)
}
