"""Actual C callback binding identity and protected prime-cache calls.

The original C provider and complete Rust provider use the existing explicit
host allocation/RCU transport; this is not a native synchronization test. The
callback typedef is extracted from production bindings, with the original C
primes/FAM layout generated by bindgen. Every artifact is temporary.
"""

import os
from pathlib import Path
import re
import resource
import shlex
import shutil
import signal
import subprocess
import tempfile
import unittest

from test_ctype_translation import run
from test_int_math_translation import rust_flags
from test_kunit_parameters import panic_handler
from test_prime_numbers import DRIVER, Fixture, PRIVATE


C_KCFI = ("-fsanitize=kcfi", "-fsanitize-cfi-icall-experimental-normalize-integers")
RUST_KCFI = ("-Zsanitizer=kcfi", "-Zsanitizer-cfi-normalize-integers")

CONSUMER = r'''
//! Independent consumer of the actual generated function declaration.
#![no_std]
#[path="@PRIVATE@"] pub mod private;
use kernel::{bindings, ffi};
type Dispatch = unsafe extern "C" fn(*mut ffi::c_void, bindings::primes_fn);
/// Load and invoke the actual binding through a protected volatile pointer.
#[no_mangle]
pub unsafe extern "C" fn rust_call(ctx:*mut ffi::c_void, callback:bindings::primes_fn) {
    let target: Dispatch = bindings::with_primes;
    let target = unsafe { core::ptr::read_volatile(&target) };
    unsafe { target(ctx, callback) };
}
unsafe extern "C" fn inspect(ctx:*mut ffi::c_void, snapshot:*const bindings::primes) {
    let out=ctx.cast::<ffi::c_ulong>();
    unsafe {
        out.write(out.read()+1);
        out.add(1).write(core::ptr::addr_of!((*snapshot).last).read());
        out.add(2).write(core::ptr::addr_of!((*snapshot).sz).read() as ffi::c_ulong);
    }
}
/// Exercise both directions: a Rust caller and its real bare Rust callback.
#[no_mangle]
pub unsafe extern "C" fn rust_own_callback(ctx:*mut ffi::c_void) {
    unsafe { rust_call(ctx, inspect) };
}
'''

CALLS = r'''
static typeof(&with_primes) volatile selected_with_primes=with_primes;
void rust_call(void *,primes_fn);
void rust_own_callback(void *);
static void inspect(void *ctx,const struct primes *p){
 unsigned long *out=ctx;REQUIRE(current_readers&&readers);
 out[0]++;out[1]=p->last;out[2]=p->sz;
}
void cleanup_module(void);
__attribute__((noreturn)) void suite_main(void){
 unsigned long state[3]={0};
 for(unsigned long n=1;n<1024;n=n*4+1){
  REQUIRE(next_prime_number(n)>n);
#if CALLER_MODE==0
  selected_with_primes(state,inspect);
#elif CALLER_MODE==1
  rust_call(state,inspect);
#else
  rust_own_callback(state);
#endif
  REQUIRE(!current_readers&&!readers&&state[1]<state[2]);
  output(state,sizeof(state));
 }
 cleanup_module();REQUIRE(!pending_count&&reclaimed==retired);finish(0);
}
'''


def type_ids(path):
    text = path.read_text()
    values = {index: int(value) & 0xffffffff for index, value in
              re.findall(r"(?m)^!(\d+) = !\{i32 (-?\d+)\}$", text)}
    return {name: values[index] for name, index in re.findall(
        r"(?m)^define [^\n]*?@([A-Za-z_][A-Za-z_0-9]*)\([^\n]*!kcfi_type !(\d+)", text)}


def no_core_dump():
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))


class PrimeCallbackKcfiTests(unittest.TestCase):
    def setUp(self):
        self.clang = shlex.split(os.environ.get("CLANG", "clang"))
        if not self.clang or not shutil.which(self.clang[0]):
            if "CLANG" in os.environ:
                self.fail("explicit CLANG unavailable")
            self.skipTest("Clang required for genuine normalized KCFI proof")
        directory = tempfile.TemporaryDirectory(prefix="prime-callback-kcfi-")
        self.addCleanup(directory.cleanup)
        self.work = Path(directory.name)

    def fixture(self, bits):
        fixture = Fixture(self.work / str(bits), bits)
        fixture.cc = self.clang
        return fixture

    def consumer(self, fixture, optimize, wrong_type=False, protected=True, wrong_callback=False):
        text = CONSUMER.replace("@PRIVATE@", str(PRIVATE))
        if wrong_type:
            # The old Option encoding has the identical machine ABI for Some,
            # but is not the original C function-pointer type under KCFI.
            text = text.replace('type Dispatch = unsafe extern "C" fn(*mut ffi::c_void, bindings::primes_fn);',
                                'type Dispatch = unsafe extern "C" fn(*mut ffi::c_void, Option<bindings::primes_fn>);')
            text = text.replace("let target: Dispatch = bindings::with_primes;",
                "let original: unsafe extern \"C\" fn(*mut ffi::c_void, bindings::primes_fn) = bindings::with_primes;\n"
                "    let target: Dispatch = unsafe { core::mem::transmute(original) };")
            text = text.replace("target(ctx, callback)", "target(ctx, Some(callback))")
        if wrong_callback:
            text = text.replace("snapshot:*const bindings::primes", "snapshot:*mut bindings::primes")
            text = text.replace("rust_call(ctx, inspect)",
                'rust_call(ctx, core::mem::transmute::<unsafe extern "C" fn(*mut ffi::c_void, '
                '*mut bindings::primes), bindings::primes_fn>(inspect))')
        path = fixture.work / "consumer.rs"
        path.write_text(text + panic_handler())
        output = fixture.work / "consumer.a"
        run([*fixture.rustc, *fixture.target, *rust_flags(optimize),
             *(RUST_KCFI if protected else ()), "--crate-name=consumer", "--crate-type=staticlib",
             "--extern", "kernel="+str(fixture.library), "--cfg=CONFIG_PRIME_NUMBERS_KUNIT_TEST",
             "--emit=link="+str(output)+",llvm-ir="+str(output.with_suffix(".ll")), path], env=fixture.env)
        return output

    def executable(self, fixture, owner, consumer, mode, protected=True):
        # Reuse only the explicit boundary transport; no algorithm is replaced.
        transport = DRIVER[:DRIVER.index("static unsigned long cached_last")]
        startup = DRIVER[DRIVER.index("#if __SIZEOF_POINTER__==8\n__asm__"):]
        source = fixture.work / "protected.c"
        calls = CALLS
        if not protected:
            # Only the outer C call is unchecked: callbacks still need their
            # real metadata when invoked by an instrumented provider.
            calls = calls.replace('__attribute__((noreturn)) void suite_main',
                '__attribute__((noreturn,no_sanitize("kcfi"))) void suite_main')
        source.write_text(transport + calls + startup)
        linker = fixture.work / "link.lds"
        linker.write_text("SECTIONS { /DISCARD/ : { *(.eh_frame .eh_frame.* .eh_frame_hdr .gcc_except_table .gcc_except_table.* .data.DW.ref.rust_eh_personality) } } INSERT AFTER .data;\n")
        binary = fixture.work / "protected"
        obj = fixture.work / "protected.o"
        flags = [*self.clang, *fixture.flags, "-O2", "-DCALLER_MODE="+str(mode),
                 "-ffreestanding", "-fno-builtin", "-fno-pic", "-fno-pie", "-fno-stack-protector",
                 *(C_KCFI if fixture.bits==64 else ())]
        run([*flags, "-c", source, "-o", obj])
        run([*self.clang, "-m"+str(fixture.bits), "-static", "-nostdlib", "-no-pie",
             "-Wl,--gc-sections", "-Wl,-e,_start", "-Wl,-T,"+str(linker),
             obj, owner, consumer, "-o", binary])
        self.assertEqual(binary.read_bytes()[:6], b"\x7fELF"+bytes([1 if fixture.bits==32 else 2,1]))
        return binary

    def execute(self, fixture, binary, expected=0):
        runner = shlex.split(os.environ.get("INT_MATH_I686_RUNNER", "")) if fixture.bits==32 else []
        result = subprocess.run([*runner, binary], capture_output=True, timeout=30, preexec_fn=no_core_dump)
        self.assertEqual(result.returncode, expected, result.stderr.decode(errors="replace"))
        return result.stdout

    def test_original_and_native_normalized_type_ids_lp64(self):
        # Rust 1.85 explicitly does not support KCFI on i686. Genuine ELF32
        # ordinary ABI/callback execution remains a separate, mandatory test
        # whenever the matching sysroot is explicitly supplied.
        for bits in (64,):
            fixture = self.fixture(bits)
            for optimize in ("0", "2", "s"):
                with self.subTest(bits=bits,optimize=optimize):
                    c = fixture.owner(False, optimize, object_only=True, kcfi=True)
                    rust = fixture.owner(True, optimize, object_only=True, kcfi=True)
                    expected, actual = type_ids(c.with_suffix(".ll")), type_ids(rust.with_suffix(".ll"))
                    for name in ("with_primes", "is_prime_number", "next_prime_number", "slow_is_prime_number"):
                        self.assertEqual(actual[name], expected[name], name)
                    consumer = self.consumer(fixture, optimize)
                    self.assertEqual(type_ids(consumer.with_suffix(".ll"))["rust_call"], expected["with_primes"])
                    for ir in (c.with_suffix(".ll"), rust.with_suffix(".ll"), consumer.with_suffix(".ll")):
                        self.assertIn('"kcfi"', ir.read_text())

    def behavior(self, bits):
        fixture = self.fixture(bits)
        protected = bits == 64
        expected = None
        for optimize in ("0", "2", "s"):
            for rust in (False, True):
                owner = fixture.owner(rust, optimize, object_only=True, kcfi=protected)
                consumer = self.consumer(fixture, optimize, protected=protected)
                for mode in (0, 1, 2):
                    with self.subTest(bits=bits,optimize=optimize,rust=rust,caller=mode):
                        binary = self.executable(fixture, owner, consumer, mode, protected=protected)
                        result = self.execute(fixture,binary)
                        self.assertTrue(result)
                        if expected is None:
                            expected = result
                        self.assertEqual(result,expected)

    def test_lp64_protected_c_and_rust_calls_original_and_rust_providers(self):
        self.behavior(64)

    def test_ilp32_actual_c_and_rust_indirect_calls_without_unsupported_kcfi(self):
        self.behavior(32)

    def test_nullable_rust_caller_has_same_abi_but_traps_for_both_providers(self):
        fixture = self.fixture(64)
        for rust in (False, True):
            with self.subTest(rust=rust):
                owner = fixture.owner(rust,"2",object_only=True,kcfi=True)
                consumer = self.consumer(fixture,"2",wrong_type=True,protected=False)
                self.assertTrue(self.execute(fixture,self.executable(fixture,owner,consumer,1,protected=False)))
                consumer = self.consumer(fixture,"2",wrong_type=True)
                self.execute(fixture,self.executable(fixture,owner,consumer,1),-signal.SIGILL)

    def test_nullable_owner_has_same_abi_but_protected_callers_trap(self):
        fixture = self.fixture(64)
        owner = fixture.owner(True,"2",mutation="nullable-callback",object_only=True,kcfi=True)
        wrong_id = type_ids(owner.with_suffix(".ll"))["with_primes"]
        consumer = self.consumer(fixture,"2",protected=False)
        self.assertTrue(self.execute(fixture,self.executable(fixture,owner,consumer,0,protected=False)))
        consumer = self.consumer(fixture,"2")
        self.assertNotEqual(wrong_id,type_ids(consumer.with_suffix(".ll"))["rust_call"])
        for mode in (0,1,2):
            with self.subTest(caller=mode):
                self.execute(fixture,self.executable(fixture,owner,consumer,mode),-signal.SIGILL)

    def test_wrong_inner_callback_pointee_has_same_abi_but_both_providers_trap(self):
        fixture = self.fixture(64)
        for rust in (False, True):
            with self.subTest(rust=rust):
                owner = fixture.owner(rust,"2",object_only=True)
                consumer = self.consumer(fixture,"2",wrong_callback=True,protected=False)
                self.assertTrue(self.execute(fixture,self.executable(fixture,owner,consumer,2,protected=False)))
                owner = fixture.owner(rust,"2",object_only=True,kcfi=True)
                consumer = self.consumer(fixture,"2",wrong_callback=True)
                self.execute(fixture,self.executable(fixture,owner,consumer,2),-signal.SIGILL)


if __name__ == "__main__":
    unittest.main()
