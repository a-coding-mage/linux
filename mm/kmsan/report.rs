// Linux kernel dependencies are supplied by the surrounding translation unit.

static mut KMSAN_REPORT_LOCK: RawSpinLock = DEFINE_RAW_SPINLOCK!();
const DESCR_SIZE: usize = 128;
/* Protected by kmsan_report_lock */
static mut REPORT_LOCAL_DESCR: [c_char; DESCR_SIZE] = [0; DESCR_SIZE];
pub static mut panic_on_kmsan: c_int = 0;

// MODULE_PARAM_PREFIX is "kmsan." and panic_on_kmsan is exposed as module
// parameter "panic".

/*
 * Skip internal KMSAN frames.
 */
unsafe fn get_stack_skipnr(stack_entries: *const c_ulong, num_entries: c_int) -> c_int {
    let mut buf = [0 as c_char; 64];
    let mut skip: c_int = 0;

    while skip < num_entries {
        let len = scnprintf!(buf.as_mut_ptr(), buf.len(), "%ps", *stack_entries.add(skip as usize) as *mut c_void);

        /* Never show __msan_* or kmsan_* functions. */
        if strnstr!(buf.as_ptr(), "__msan_", len) == buf.as_ptr()
            || strnstr!(buf.as_ptr(), "kmsan_", len) == buf.as_ptr()
        {
            skip += 1;
            continue;
        }

        /*
         * No match for runtime functions -- @skip entries to skip to
         * get to first frame of interest.
         */
        break;
    }

    skip
}

/*
 * Currently the descriptions of locals generated by Clang look as follows:
 *   ----local_name@function_name
 * We want to print only the name of the local, as other information in that
 * description can be confusing.
 * The meaningful part of the description is copied to a global buffer to avoid
 * allocating memory.
 */
unsafe fn pretty_descr(descr: *mut c_char) -> *mut c_char {
    let mut pos: usize = 0;
    let len = strlen!(descr);

    for i in 0..len {
        let ch = *descr.add(i);
        if ch == b'@' as c_char {
            break;
        }
        if ch == b'-' as c_char {
            continue;
        }
        REPORT_LOCAL_DESCR[pos] = ch;
        if pos + 1 == DESCR_SIZE {
            break;
        }
        pos += 1;
    }
    REPORT_LOCAL_DESCR[pos] = 0;
    REPORT_LOCAL_DESCR.as_mut_ptr()
}

pub unsafe fn kmsan_print_origin(mut origin: depot_stack_handle_t) {
    let mut entries: *mut c_ulong = core::ptr::null_mut();
    let mut chained_entries: *mut c_ulong = core::ptr::null_mut();
    let mut nr_entries: c_uint;
    let mut chained_nr_entries: c_uint;
    let mut skipnr: c_uint;
    let mut pc1: *mut c_void = core::ptr::null_mut();
    let mut pc2: *mut c_void = core::ptr::null_mut();
    let mut head: depot_stack_handle_t;
    let mut magic: c_ulong;
    let mut descr: *mut c_char = core::ptr::null_mut();
    let mut depth: c_uint;

    if origin == 0 {
        return;
    }

    loop {
        nr_entries = stack_depot_fetch(origin, &mut entries);
        depth = kmsan_depth_from_eb(stack_depot_get_extra_bits(origin));
        magic = if nr_entries != 0 { *entries } else { 0 };
        if nr_entries == 4 && magic == KMSAN_ALLOCA_MAGIC_ORIGIN {
            descr = *entries.add(1) as *mut c_char;
            pc1 = *entries.add(2) as *mut c_void;
            pc2 = *entries.add(3) as *mut c_void;
            pr_err!("Local variable %s created at:\n", pretty_descr(descr));
            if !pc1.is_null() { pr_err!(" %pSb\n", pc1); }
            if !pc2.is_null() { pr_err!(" %pSb\n", pc2); }
            break;
        }
        if nr_entries == 3 && magic == KMSAN_CHAIN_MAGIC_ORIGIN {
            if depth == KMSAN_MAX_ORIGIN_DEPTH {
                pr_err!("<Zero or more stacks not recorded to save memory>\n\n");
            }
            head = *entries.add(1) as depot_stack_handle_t;
            origin = *entries.add(2) as depot_stack_handle_t;
            pr_err!("Uninit was stored to memory at:\n");
            chained_nr_entries = stack_depot_fetch(head, &mut chained_entries);
            kmsan_internal_unpoison_memory(chained_entries as *mut c_void, chained_nr_entries as usize * core::mem::size_of::<c_ulong>(), false);
            skipnr = get_stack_skipnr(chained_entries, chained_nr_entries as c_int) as c_uint;
            stack_trace_print(chained_entries.add(skipnr as usize), chained_nr_entries - skipnr, 0);
            pr_err!("\n");
            continue;
        }
        pr_err!("Uninit was created at:\n");
        if nr_entries != 0 {
            skipnr = get_stack_skipnr(entries, nr_entries as c_int) as c_uint;
            stack_trace_print(entries.add(skipnr as usize), nr_entries - skipnr, 0);
        } else {
            pr_err!("(stack is not available)\n");
        }
        break;
    }
}

pub unsafe fn kmsan_report(
    origin: depot_stack_handle_t,
    address: *mut c_void,
    size: c_int,
    off_first: c_int,
    off_last: c_int,
    user_addr: *const c_void,
    reason: kmsan_bug_reason,
) {
    let mut stack_entries = [0 as c_ulong; KMSAN_STACK_DEPTH];
    let mut num_stack_entries: c_int;
    let mut skipnr: c_int;
    let mut bug_type: *const c_char = core::ptr::null();
    let mut ua_flags: c_ulong;
    let is_uaf: bool;

    if !kmsan_enabled || kmsan_in_runtime() || (*current).kmsan_ctx.depth != 0 || origin == 0 { return; }

    kmsan_enter_runtime();
    ua_flags = user_access_save();
    raw_spin_lock(&raw mut KMSAN_REPORT_LOCK);
    pr_err!("=====================================================\n");
    is_uaf = kmsan_uaf_from_eb(stack_depot_get_extra_bits(origin));
    bug_type = match reason {
        REASON_ANY => if is_uaf { cstr!("use-after-free") } else { cstr!("uninit-value") },
        REASON_COPY_TO_USER => if is_uaf { cstr!("kernel-infoleak-after-free") } else { cstr!("kernel-infoleak") },
        REASON_SUBMIT_URB => if is_uaf { cstr!("kernel-usb-infoleak-after-free") } else { cstr!("kernel-usb-infoleak") },
    };
    num_stack_entries = stack_trace_save(stack_entries.as_mut_ptr(), KMSAN_STACK_DEPTH, 1);
    skipnr = get_stack_skipnr(stack_entries.as_ptr(), num_stack_entries);
    pr_err!("BUG: KMSAN: %s in %pSb\n", bug_type, stack_entries[skipnr as usize] as *mut c_void);
    stack_trace_print(stack_entries.as_ptr().add(skipnr as usize), (num_stack_entries - skipnr) as c_uint, 0);
    pr_err!("\n");
    kmsan_print_origin(origin);
    if size != 0 {
        pr_err!("\n");
        if off_first == off_last { pr_err!("Byte %d of %d is uninitialized\n", off_first, size); }
        else { pr_err!("Bytes %d-%d of %d are uninitialized\n", off_first, off_last, size); }
    }
    if !address.is_null() { pr_err!("Memory access of size %d starts at %px\n", size, address); }
    if !user_addr.is_null() && reason == REASON_COPY_TO_USER { pr_err!("Data copied to user address %px\n", user_addr); }
    pr_err!("\n");
    dump_stack_print_info(KERN_ERR);
    pr_err!("=====================================================\n");
    add_taint(TAINT_BAD_PAGE, LOCKDEP_NOW_UNRELIABLE);
    raw_spin_unlock(&raw mut KMSAN_REPORT_LOCK);
    if panic_on_kmsan != 0 { panic!("kmsan.panic set ...\n"); }
    user_access_restore(ua_flags);
    kmsan_leave_runtime();
}

