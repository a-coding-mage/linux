/* Every native boundary is a field-address expression, architecture/compiler
 * primitive, callback identity comparison, or one call to an existing header
 * or external subsystem. Header algorithms remain explicit Rust gaps in
 * NATIVE_BOUNDARIES.md; they are not claimed as algorithm-free glue. */
#define MR_FIELD(prefix, type, member) \
 __typeof__(((struct type *)0)->member) *rust_mremap_##prefix##_##member(struct type *p); \
 __typeof__(((struct type *)0)->member) *rust_mremap_##prefix##_##member(struct type *p) { return &p->member; }
