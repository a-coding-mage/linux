// Linux dependencies and INTERVAL_TREE_DEFINE are supplied by other files.

use core::ffi::c_void;

pub type pgoff_t = usize;

#[repr(C)]
pub struct rb_node {
    pub rb_left: *mut rb_node,
    pub rb_right: *mut rb_node,
    pub rb_parent: *mut rb_node,
}

#[repr(C)]
pub struct rb_root {
    pub rb_node: *mut rb_node,
}

#[repr(C)]
pub struct rb_root_cached {
    pub rb_root: rb_root,
}

#[repr(C)]
pub struct vm_area_struct {
    pub shared: vm_area_shared,
}

#[repr(C)]
pub struct vm_area_shared {
    pub rb: rb_node,
    pub rb_subtree_last: pgoff_t,
}

#[repr(C)]
pub struct address_space {
    pub i_mmap: rb_root_cached,
}

#[repr(C)]
pub struct anon_vma_chain {
    pub rb: rb_node,
    pub rb_subtree_last: pgoff_t,
    #[cfg(CONFIG_DEBUG_VM_RB)]
    pub cached_vma_start: pgoff_t,
    #[cfg(CONFIG_DEBUG_VM_RB)]
    pub cached_vma_last: pgoff_t,
    pub vma: *mut vm_area_struct,
}

#[repr(C)]
pub struct anon_vma {
    pub rb_root: rb_root,
}

// The following declarations are generated by INTERVAL_TREE_DEFINE in the
// kernel interval-tree generic header.
