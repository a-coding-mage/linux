pub unsafe fn mapping_rmap_tree_insert(vma: *mut vm_area_struct, mapping: *mut address_space) {
    __mapping_rmap_tree_insert(vma, &mut (*mapping).i_mmap);
}

/* Insert vma immediately after prev in the interval tree */
pub unsafe fn mapping_rmap_tree_insert_after(
    vma: *mut vm_area_struct,
    prev: *mut vm_area_struct,
    mapping: *mut address_space,
) {
    let mut link: *mut *mut rb_node;
    let mut parent: *mut vm_area_struct;
    let pgoff_last = vma_last_pgoff(vma);

    VM_WARN_ON_ONCE_VMA(vma_start_pgoff(vma) != vma_start_pgoff(prev), vma);

    if (*prev).shared.rb.rb_right.is_null() {
        parent = prev;
        link = &mut (*prev).shared.rb.rb_right;
    } else {
        parent = (*((*prev).shared.rb.rb_right as *mut vm_area_struct));
        if (*parent).shared.rb_subtree_last < pgoff_last {
            (*parent).shared.rb_subtree_last = pgoff_last;
        }
        while !(*parent).shared.rb.rb_left.is_null() {
            parent = (*((*parent).shared.rb.rb_left as *mut vm_area_struct));
            if (*parent).shared.rb_subtree_last < pgoff_last {
                (*parent).shared.rb_subtree_last = pgoff_last;
            }
        }
        link = &mut (*parent).shared.rb.rb_left;
    }

    (*vma).shared.rb_subtree_last = pgoff_last;
    rb_link_node(&mut (*vma).shared.rb, &mut (*parent).shared.rb, link);
    rb_insert_augmented(&mut (*vma).shared.rb, &mut (*mapping).i_mmap.rb_root, __mapping_rmap_tree_augment as *const c_void);
}

pub unsafe fn mapping_rmap_tree_remove(vma: *mut vm_area_struct, mapping: *mut address_space) {
    __mapping_rmap_tree_remove(vma, &mut (*mapping).i_mmap);
}

pub unsafe fn mapping_rmap_tree_iter_first(mapping: *mut address_space, start: pgoff_t, last: pgoff_t) -> *mut vm_area_struct {
    __mapping_rmap_tree_iter_first(&mut (*mapping).i_mmap, start, last)
}

pub unsafe fn mapping_rmap_tree_iter_next(vma: *mut vm_area_struct, start: pgoff_t, last: pgoff_t) -> *mut vm_area_struct {
    __mapping_rmap_tree_iter_next(vma, start, last)
}

/* Anonymous interval tree (anon_vma->rb_root) */
unsafe fn avc_start_pgoff(avc: *mut anon_vma_chain) -> pgoff_t { vma_start_anon_pgoff((*avc).vma) }
unsafe fn avc_last_pgoff(avc: *mut anon_vma_chain) -> pgoff_t { vma_last_anon_pgoff((*avc).vma) }

pub unsafe fn anon_rmap_tree_insert(avc: *mut anon_vma_chain, anon_vma: *mut anon_vma) {
    #[cfg(CONFIG_DEBUG_VM_RB)]
    {
        (*avc).cached_vma_start = avc_start_pgoff(avc);
        (*avc).cached_vma_last = avc_last_pgoff(avc);
    }
    __anon_rmap_tree_insert(avc, &mut (*anon_vma).rb_root);
}

pub unsafe fn anon_rmap_tree_remove(avc: *mut anon_vma_chain, anon_vma: *mut anon_vma) { __anon_rmap_tree_remove(avc, &mut (*anon_vma).rb_root); }
pub unsafe fn anon_rmap_tree_iter_first(anon_vma: *mut anon_vma, start: pgoff_t, last: pgoff_t) -> *mut anon_vma_chain { __anon_rmap_tree_iter_first(&mut (*anon_vma).rb_root, start, last) }
pub unsafe fn anon_rmap_tree_iter_next(avc: *mut anon_vma_chain, start: pgoff_t, last: pgoff_t) -> *mut anon_vma_chain { __anon_rmap_tree_iter_next(avc, start, last) }

#[cfg(CONFIG_DEBUG_VM_RB)]
pub unsafe fn anon_rmap_tree_verify(avc: *mut anon_vma_chain) {
    WARN_ON_ONCE((*avc).cached_vma_start != avc_start_pgoff(avc));
    WARN_ON_ONCE((*avc).cached_vma_last != avc_last_pgoff(avc));
}

