    fn __mapping_rmap_tree_remove(vma: *mut vm_area_struct, root: *mut rb_root_cached);
    fn __mapping_rmap_tree_iter_first(root: *mut rb_root_cached, start: pgoff_t, last: pgoff_t) -> *mut vm_area_struct;
    fn __mapping_rmap_tree_iter_next(vma: *mut vm_area_struct, start: pgoff_t, last: pgoff_t) -> *mut vm_area_struct;
    fn __anon_rmap_tree_insert(avc: *mut anon_vma_chain, root: *mut rb_root);
    fn __anon_rmap_tree_remove(avc: *mut anon_vma_chain, root: *mut rb_root);
    fn __anon_rmap_tree_iter_first(root: *mut rb_root, start: pgoff_t, last: pgoff_t) -> *mut anon_vma_chain;
    fn __anon_rmap_tree_iter_next(avc: *mut anon_vma_chain, start: pgoff_t, last: pgoff_t) -> *mut anon_vma_chain;
    fn vma_start_pgoff(vma: *mut vm_area_struct) -> pgoff_t;
    fn vma_last_pgoff(vma: *mut vm_area_struct) -> pgoff_t;
    fn vma_start_anon_pgoff(vma: *mut vm_area_struct) -> pgoff_t;
    fn vma_last_anon_pgoff(vma: *mut vm_area_struct) -> pgoff_t;
    fn rb_link_node(node: *mut rb_node, parent: *mut rb_node, link: *mut *mut rb_node);
    fn rb_insert_augmented(node: *mut rb_node, root: *mut rb_root, augment: *const c_void);
    fn __mapping_rmap_tree_augment();
    fn VM_WARN_ON_ONCE_VMA(condition: bool, vma: *mut vm_area_struct);
    fn WARN_ON_ONCE(condition: bool);
