/* 127.0.0.1 in host byte order */
const SERVER_IP: u32 = 0x7F000001;
/* ::1 in host byte order (last 32-bit word) */
const SERVER_IP6_LO: u32 = 0x00000001;

#[no_mangle]
pub static mut server_port: __u16 = 0;
#[no_mangle]
pub static mut unreach_type: i32 = 0;
#[no_mangle]
pub static mut unreach_code: i32 = 0;
#[no_mangle]
pub static mut kfunc_ret: i32 = -1;
#[no_mangle]
pub static mut target_pid: i32 = -1;

#[no_mangle]
pub static mut rec_count: u32 = 0;
#[no_mangle]
pub static mut rec_kfunc_rets: [i32; 2] = [-1, -1];

extern "C" {
    fn bpf_icmp_send(skb: *mut __sk_buff, type_: i32, code: i32) -> i32;
    fn bpf_get_current_pid_tgid() -> u64;
    fn bpf_htonl(x: u32) -> u32;
    fn bpf_htons(x: __u16) -> __u16;
}

#[no_mangle]
#[link_section = "cgroup_skb/egress"]
pub unsafe extern "C" fn egress(skb: *mut __sk_buff) -> i32 {
    let data = (*skb).data as usize as *mut u8;
    let data_end = (*skb).data_end as usize as *mut u8;
    let mut iph: *mut iphdr;
    let mut ip6h: *mut ipv6hdr;
    let mut tcph: *mut tcphdr;
    let version: __u8;

    if data.add(1) > data_end {
        return SK_PASS;
    }

    version = (*(data as *mut __u8)) >> 4;

    if version == 4 {
        iph = data as *mut iphdr;
        if (iph.add(1) as *mut u8) > data_end
            || (*iph).protocol != IPPROTO_TCP
            || (*iph).daddr != bpf_htonl(SERVER_IP)
        {
            return SK_PASS;
        }

        tcph = (iph as *mut u8).add(((*iph).ihl * 4) as usize) as *mut tcphdr;
        if (tcph.add(1) as *mut u8) > data_end || (*tcph).dest != bpf_htons(server_port) {
            return SK_PASS;
        }
    } else if version == 6 {
        ip6h = data as *mut ipv6hdr;
        if (ip6h.add(1) as *mut u8) > data_end || (*ip6h).nexthdr != IPPROTO_TCP {
            return SK_PASS;
        }

        if (*ip6h).daddr.in6_u.u6_addr32[0] != 0
            || (*ip6h).daddr.in6_u.u6_addr32[1] != 0
            || (*ip6h).daddr.in6_u.u6_addr32[2] != 0
            || (*ip6h).daddr.in6_u.u6_addr32[3] != bpf_htonl(SERVER_IP6_LO)
        {
            return SK_PASS;
        }

        tcph = ip6h.add(1) as *mut tcphdr;
        if (tcph.add(1) as *mut u8) > data_end || (*tcph).dest != bpf_htons(server_port) {
            return SK_PASS;
        }
    } else {
        return SK_PASS;
    }

    kfunc_ret = bpf_icmp_send(skb, unreach_type, unreach_code);

    SK_DROP
}

#[no_mangle]
#[link_section = "cgroup_skb/egress"]
pub unsafe extern "C" fn recursion(skb: *mut __sk_buff) -> i32 {
    let data = (*skb).data as usize as *mut u8;
    let data_end = (*skb).data_end as usize as *mut u8;
    let mut icmph: *mut icmphdr;
    let mut tcph: *mut tcphdr;
    let mut iph: *mut iphdr;
    let ret: i32;

    if (bpf_get_current_pid_tgid() >> 32) != target_pid as u64 {
        return SK_PASS;
    }

    iph = data as *mut iphdr;
    if (iph.add(1) as *mut u8) > data_end || (*iph).version != 4 {
        return SK_PASS;
    }

    if (*iph).daddr != bpf_htonl(SERVER_IP) {
        return SK_PASS;
    }

    if (*iph).protocol == IPPROTO_TCP {
        tcph = (iph as *mut u8).add(((*iph).ihl * 4) as usize) as *mut tcphdr;
        if (tcph.add(1) as *mut u8) > data_end || (*tcph).dest != bpf_htons(server_port) {
            return SK_PASS;
        }
    } else if (*iph).protocol == IPPROTO_ICMP {
        icmph = (iph as *mut u8).add(((*iph).ihl * 4) as usize) as *mut icmphdr;
        if (icmph.add(1) as *mut u8) > data_end
            || (*icmph).type_ != unreach_type as __u8
            || (*icmph).code != unreach_code as __u8
        {
            return SK_PASS;
        }
    } else {
        return SK_PASS;
    }

    /*
     * This call will provoke a recursion: the ICMP packet generated by the
     * kfunc will re-trigger this program since we are in the root cgroup in
     * which the kernel ICMP socket belongs. However when re-entering the
     * kfunc, it should return EBUSY.
     */
    ret = bpf_icmp_send(skb, unreach_type, unreach_code);
    rec_kfunc_rets[(rec_count & 1) as usize] = ret;
    rec_count = rec_count.wrapping_add(1);

    /* Let the first ICMP error message pass */
    if (*iph).protocol == IPPROTO_ICMP {
        return SK_PASS;
    }

    SK_DROP
}

