use core::ffi::{c_char, c_int, c_void};

const MAX_DATA_LEN: usize = 512;
const HASH_LEN: usize = 20;

extern "C" {
    fn strreplace_chars(needle: c_char, haystack: *const c_char, replace: *const c_char) -> *mut c_char;
    fn strcmp(s1: *const c_char, s2: *const c_char) -> c_int;
    fn free(ptr: *mut c_void);

    fn blake2s_init(ctx: *mut blake2s_ctx, outlen: usize);
    fn blake2s_update(ctx: *mut blake2s_ctx, in_: *const u8, inlen: usize);
    fn blake2s_final(ctx: *mut blake2s_ctx, out: *mut u8);
    fn memcmp(s1: *const c_void, s2: *const c_void, n: usize) -> c_int;
}

unsafe fn test_strreplace(
    needle: c_char,
    haystack: *const c_char,
    replace: *const c_char,
    expected: *const c_char,
) -> c_int {
    let new = strreplace_chars(needle, haystack, replace);
    let ret = strcmp(new, expected);

    free(new as *mut c_void);
    (ret == 0) as c_int
}

/* Test the implementation of the BLAKE2s hash algorithm. */
unsafe fn test_blake2s() -> c_int {
    let mut data: [u8; MAX_DATA_LEN] = [0; MAX_DATA_LEN];
    let mut hash: [u8; HASH_LEN] = [0; HASH_LEN];
    let mut hash2: [u8; HASH_LEN] = [0; HASH_LEN];
    let mut main_ctx: blake2s_ctx = core::mem::zeroed();
    /*
     * This value was generated by the following Python code:
     *
     * import hashlib
     *
     * data = bytes(i % 256 for i in range(513))
     * h = hashlib.blake2s(digest_size=20)
     * for i in range(513):
     *     h.update(hashlib.blake2s(data=data[:i], digest_size=20).digest())
     * print(h.hexdigest())
     */
    static EXPECTED_HASH_OF_HASHES: [u8; 20] = [
        0xef, 0x9b, 0x13, 0x98, 0x78, 0x8e, 0x74, 0x59, 0x9c, 0xd5,
        0x0c, 0xf0, 0x33, 0x97, 0x79, 0x3d, 0x3e, 0xd0, 0x95, 0xa6,
    ];
    let mut i: usize;

    /* Generate MAX_DATA_LEN bytes of data. */
    i = 0;
    while i < MAX_DATA_LEN {
        data[i] = i as u8;
        i += 1;
    }

    blake2s_init(&mut main_ctx, core::mem::size_of_val(&hash));
    i = 0;
    while i <= MAX_DATA_LEN {
        let mut ctx: blake2s_ctx = core::mem::zeroed();

        /* Compute the BLAKE2s hash of 'i' data bytes. */
        blake2s_init(&mut ctx, HASH_LEN);
        blake2s_update(&mut ctx, data.as_ptr(), i);
        blake2s_final(&mut ctx, hash.as_mut_ptr());

        /* Verify that multiple updates produce the same result. */
        blake2s_init(&mut ctx, HASH_LEN);
        blake2s_update(&mut ctx, data.as_ptr(), i / 2);
        blake2s_update(&mut ctx, data.as_ptr().add(i / 2), i - (i / 2));
        blake2s_final(&mut ctx, hash2.as_mut_ptr());
        TEST_ASSERT_VAL!(
            c"inconsistent BLAKE2s hashes".as_ptr(),
            memcmp(
                hash.as_ptr() as *const c_void,
                hash2.as_ptr() as *const c_void,
                HASH_LEN,
            ) == 0
        );

        /*
         * Pass the hash to another BLAKE2s context, so that we
         * incrementally compute the hash of all the hashes.
         */
        blake2s_update(&mut main_ctx, hash.as_ptr(), HASH_LEN);
        i += 1;
    }

    /* Verify the hash of all the hashes. */
    blake2s_final(&mut main_ctx, hash.as_mut_ptr());
    TEST_ASSERT_VAL!(
        c"wrong BLAKE2s hashes".as_ptr(),
        memcmp(
            hash.as_ptr() as *const c_void,
            EXPECTED_HASH_OF_HASHES.as_ptr() as *const c_void,
            HASH_LEN,
        ) == 0
    );
    0
}

unsafe extern "C" fn test__blake2s_case(
    _t: *mut test_suite,
    _subtest: c_int,
) -> c_int {
    test_blake2s()
}

unsafe extern "C" fn test__strreplace(
    _t: *mut test_suite,
    _subtest: c_int,
) -> c_int {
    TEST_ASSERT_VAL!(
        c"empty string".as_ptr(),
        test_strreplace(
            b' ' as c_char,
            c"".as_ptr(),
            c"123".as_ptr(),
            c"".as_ptr(),
        ) != 0
    );
    TEST_ASSERT_VAL!(
        c"no match".as_ptr(),
        test_strreplace(
            b'5' as c_char,
            c"123".as_ptr(),
            c"4".as_ptr(),
            c"123".as_ptr(),
        ) != 0
    );
    TEST_ASSERT_VAL!(
        c"replace 1".as_ptr(),
        test_strreplace(
            b'3' as c_char,
            c"123".as_ptr(),
            c"4".as_ptr(),
            c"124".as_ptr(),
        ) != 0
    );
    TEST_ASSERT_VAL!(
        c"replace 2".as_ptr(),
        test_strreplace(
            b'a' as c_char,
            c"abcabc".as_ptr(),
            c"ef".as_ptr(),
            c"efbcefbc".as_ptr(),
        ) != 0
    );
    TEST_ASSERT_VAL!(
        c"replace long".as_ptr(),
        test_strreplace(
            b'a' as c_char,
            c"abcabc".as_ptr(),
            c"longlong".as_ptr(),
            c"longlongbclonglongbc".as_ptr(),
        ) != 0
    );

    0
}

