const fn lower(x: usize) -> u8 {
    match x as u8 {
        0x40..=0x5a => (x as u8) + 0x20,
        0xc0..=0xd6 | 0xd8..=0xde => (x as u8) + 0x20,
        0xa1 => 0xb1, 0xa3 => 0xb3, 0xa5 => 0xb5, 0xa9 => 0xb9,
        0xad => 0xad, 0xbd => 0xbf, 0xd7 => 0xd7, 0xdf => 0xdf,
        _ => x as u8,
    }
}
const fn upper(x: usize) -> u8 {
    match x as u8 {
        0x61..=0x7a => (x as u8) - 0x20,
        0xe0..=0xf6 | 0xf8..=0xfe => (x as u8) - 0x20,
        0xb1 => 0xa1, 0xb3 => 0xa3, 0xb5 => 0xa5, 0xb9 => 0xa9,
        0xbd => 0xbd, 0xbf => 0xbd, 0xf7 => 0xf7, 0xff => 0xff,
        _ => x as u8,
    }
}
const fn make_lower() -> [u8;256] { let mut a=[0u8;256]; let mut i=0; while i<256 { a[i]=lower(i); i+=1; } a }
const fn make_upper() -> [u8;256] { let mut a=[0u8;256]; let mut i=0; while i<256 { a[i]=upper(i); i+=1; } a }
static charset2lower: [u8;256] = make_lower();
static charset2upper: [u8;256] = make_upper();

