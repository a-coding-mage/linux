// Exact Unicode-to-charset pages; null pages are represented by None.
static page_uni2charset: [Option<&'static [u8;256]>;256] = {
    let mut p = [None;256]; p[0] = Some(&page00); p[1] = Some(&page01); p[0x20] = Some(&page20); p
};

#[repr(C)]
struct NlsTable { charset: *const i8, uni2char: Option<unsafe extern "C" fn(u32,*mut u8,i32)->i32>, char2uni: Option<unsafe extern "C" fn(*const u8,i32,*mut u32)->i32>, charset2lower: *const u8, charset2upper: *const u8 }
extern "C" { fn register_nls(t: *mut NlsTable) -> i32; fn unregister_nls(t: *mut NlsTable); }

unsafe extern "C" fn uni2char(uni: u32, out: *mut u8, boundlen: i32) -> i32 {
    if boundlen <= 0 { return -ENAMETOOLONG; }
    let page = page_uni2charset[((uni & 0xff00) >> 8) as usize];
    match page.and_then(|p| { let v=p[(uni & 0xff) as usize]; if v != 0 { Some(v) } else { None } }) { Some(v) => { *out=v; 1 }, None => -EINVAL }
}
unsafe extern "C" fn char2uni(rawstring: *const u8, _boundlen: i32, uni: *mut u32) -> i32 {
    *uni = charset2uni[*rawstring as usize] as u32; if *uni == 0 { -EINVAL } else { 1 }
}

static mut table: NlsTable = NlsTable { charset: b"iso8859-13\0".as_ptr() as *const i8, uni2char: Some(uni2char), char2uni: Some(char2uni), charset2lower: charset2lower.as_ptr(), charset2upper: charset2upper.as_ptr() };
unsafe extern "C" fn init_nls_iso8859_13() -> i32 { register_nls(&raw mut table) }
unsafe extern "C" fn exit_nls_iso8859_13() { unregister_nls(&raw mut table); }

