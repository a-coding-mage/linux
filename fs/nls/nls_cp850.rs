unsafe extern "C" fn uni2char(uni: u32, out: *mut u8, boundlen: c_int) -> c_int {
    if boundlen <= 0 { return -ENAMETOOLONG; }
    let cl = (uni & 0x00ff) as usize;
    let ch = ((uni & 0xff00) >> 8) as usize;
    let value = if ch == 0 && cl < 0x80 { cl as u8 } else {
        let mut found = None;
        let mut i = 0usize;
        while i < CHARSET2UNI.len() { if CHARSET2UNI[i] == uni { found = Some(i as u8); break; } i += 1; }
        match found { Some(v) => v, None => return -EINVAL }
    };
    *out = value;
    1
}

unsafe extern "C" fn char2uni(rawstring: *const u8, _boundlen: c_int, uni: *mut u32) -> c_int {
    *uni = CHARSET2UNI[*rawstring as usize];
    if *uni == 0 { return -EINVAL; }
    1
}

