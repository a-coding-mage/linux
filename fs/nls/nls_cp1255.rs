unsafe fn uni2char(uni: u16, out: *mut u8, boundlen: i32) -> i32 {
    if boundlen <= 0 { return -36; }
    let ch=(uni>>8) as u8; let cl=(uni&0xff) as usize;
    let p: Option<&[u8;256]> = match ch { 0=>Some(&page00),1=>Some(&page01),2=>Some(&page02),5=>Some(&page05),0x20=>Some(&page20),0x21=>Some(&page21),_=>None };
    match p { Some(t) if t[cl]!=0 => { *out=t[cl] as u8; 1 }, _=>-22 }
}
unsafe fn char2uni(rawstring: *const u8, _boundlen: i32, uni: *mut u16) -> i32 { *uni=charset2uni[*rawstring as usize]; if *uni==0 { -22 } else { 1 } }

