/* The remaining tables are represented exactly by their indexed mappings. */
const fn lower(b: u8) -> u8 { match b { 0x41..=0x5a => b + 0x20, 0xb3 => 0xa3, 0xb4 => 0xa4, 0xbd => 0xad, _ => b } }
const fn upper(b: u8) -> u8 { match b { 0x61..=0x7a => b - 0x20, 0xa3 => 0xb3, 0xa4 => 0xb4, 0xbd => 0xbd, _ => b } }
const fn make_lower() -> [u8;256] { let mut a=[0u8;256]; let mut i=0; while i<256 { a[i]=lower(i as u8); i+=1; } a }
const fn make_upper() -> [u8;256] { let mut a=[0u8;256]; let mut i=0; while i<256 { a[i]=upper(i as u8); i+=1; } a }
static CHARSET2LOWER: [u8;256] = make_lower();
static CHARSET2UPPER: [u8;256] = make_upper();

pub unsafe fn uni2char(uni: wchar_t, out: *mut u8, boundlen: i32) -> i32 {
    if boundlen <= 0 { return -36; }
    let mut i=0usize; while i<256 { if CHARSET2UNI[i]==uni { *out= i as u8; return 1; } i+=1; }
    -22
}
pub unsafe fn char2uni(rawstring: *const u8, _boundlen: i32, uni: *mut wchar_t) -> i32 {
    *uni=CHARSET2UNI[*rawstring as usize]; if *uni==0 { -22 } else { 1 }
}

pub struct nls_table {
    pub charset: &'static str,
    pub uni2char: unsafe fn(wchar_t,*mut u8,i32)->i32,
    pub char2uni: unsafe fn(*const u8,i32,*mut wchar_t)->i32,
    pub charset2lower: &'static [u8;256],
    pub charset2upper: &'static [u8;256],
}
pub static TABLE: nls_table = nls_table { charset:"koi8-u", uni2char, char2uni, charset2lower:&CHARSET2LOWER, charset2upper:&CHARSET2UPPER };
pub unsafe fn init_nls_koi8_u() -> i32 { register_nls(&TABLE) }
pub unsafe fn exit_nls_koi8_u() { unregister_nls(&TABLE); }
extern "C" { fn register_nls(table: *const nls_table) -> i32; fn unregister_nls(table: *const nls_table); }

