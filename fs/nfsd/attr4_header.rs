extern "C" {
    pub static nfsd_suppattrs: [[u32; 3]; 3];
}

#[inline]
pub unsafe fn bmval_is_subset(bm1: *const u32, bm2: *const u32) -> bool {
    !((*bm1.add(0) & !*bm2.add(0)) != 0 ||
      (*bm1.add(1) & !*bm2.add(1)) != 0 ||
      (*bm1.add(2) & !*bm2.add(2)) != 0)
}

#[inline]
pub unsafe fn nfsd_attrs_supported(minorversion: u32, bmval: *const u32) -> bool {
    bmval_is_subset(bmval, nfsd_suppattrs[minorversion as usize].as_ptr())
}

