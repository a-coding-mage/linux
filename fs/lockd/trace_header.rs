/// Data captured by `nlmclnt_lock_event`.
#[repr(C)]
pub struct NlmclntLockEventEntry {
    pub oh: u32,
    pub svid: u32,
    pub fh: u32,
    pub status: ::core::ffi::c_ulong,
    pub start: i64,
    pub end: i64,
    // `__sockaddr(addr, addrlen)` is an inline tracepoint sockaddr payload.
    pub addr: [u8; 0],
}

/*
 * DECLARE_EVENT_CLASS(nlmclnt_lock_event,
 *   TP_PROTO(const struct lockd_lock *lock,
 *            const struct sockaddr *addr,
 *            unsigned int addrlen,
 *            __be32 status),
 *   TP_ARGS(lock, addr, addrlen, status),
 *   TP_STRUCT__entry(...),
 *   TP_fast_assign(
 *     oh     = ~crc32_le(0xffffffff, lock->oh.data, lock->oh.len);
 *     svid   = lock->svid;
 *     fh     = nfs_fhandle_hash(&lock->fh);
 *     start  = lock->fl.fl_start;
 *     end    = lock->fl.fl_end;
 *     status = be32_to_cpu(status);
 *     __assign_sockaddr(addr, addr, addrlen);
 *   ),
 *   TP_printk("addr=%pISpc oh=0x%08x svid=0x%08x fh=0x%08x start=%lld
 *              end=%lld status=%s", ...))
 *
 * These are Linux tracepoint registration/declaration macros.  Their Rust
 * equivalents are emitted by the tracepoint implementation around the C
 * compatible entry layout above; the assignments and print format are kept
 * here verbatim in semantic form because they depend on external lockd,
 * sockaddr, CRC, and NFS definitions.
 */

