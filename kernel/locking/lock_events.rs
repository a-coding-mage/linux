/* Collect locking event counts. */

// C dependencies supplied by the surrounding kernel translation unit.

const LOCK_EVENTS_DIR: *const u8 = b"lock_event_counts\0".as_ptr();

/*
 * When CONFIG_LOCK_EVENT_COUNTS is enabled, event counts of different
 * types of locks will be reported under the <debugfs>/lock_event_counts/
 * directory. See lock_events_list.h for the list of available locking
 * events.
 *
 * Writing to the special ".reset_counts" file will reset all the above
 * locking event counts. This is a very slow operation and so should not
 * be done frequently.
 *
 * These event counts are implemented as per-cpu variables which are
 * summed and computed whenever the corresponding debugfs files are read. This
 * minimizes added overhead making the counts usable even in a production
 * environment.
 */
// The entries generated by lock_events_list.h are retained as an external
// dependency; the generated array has one additional reset entry.
extern "C" {
    static lockevent_num: usize;
    static LOCKEVENT_reset_cnts: usize;
    static lockevent_names: *const *const u8;
}

/* Per-cpu counts. */
extern "C" {
    static mut lockevents: *mut usize;
}

/* The lockevent_read() function can be overridden. */
#[no_mangle]
pub unsafe extern "C" fn lockevent_read(
    file: *mut file,
    user_buf: *mut u8,
    count: usize,
    ppos: *mut loff_t,
) -> isize {
    let mut buf = [0u8; 64];
    let mut sum: u64 = 0;

    /* Get the counter ID stored in file->f_inode->i_private. */
    let id = (*file_inode(file)).i_private as isize as usize;

    if id >= lockevent_num {
        return -EBADF;
    }

    for_each_possible_cpu!(cpu => {
        sum = sum.wrapping_add(per_cpu!(lockevents[id], cpu));
    });
    let len = snprintf!(buf.as_mut_ptr(), buf.len() - 1, "%llu\n", sum);

    simple_read_from_buffer(user_buf, count, ppos, buf.as_ptr(), len)
}

/*
 * Function to handle write request.
 *
 * When idx = reset_cnts, reset all the counts.
 */
unsafe fn lockevent_write(
    file: *mut file,
    _user_buf: *const u8,
    count: usize,
    _ppos: *mut loff_t,
) -> isize {
    /* Get the counter ID stored in file->f_inode->i_private. */
    if ((*file_inode(file)).i_private as isize as usize) != LOCKEVENT_reset_cnts {
        return count as isize;
    }

    for_each_possible_cpu!(cpu => {
        let ptr: *mut usize = per_cpu_ptr!(lockevents, cpu);
        for i in 0..lockevent_num {
            core::ptr::write_volatile(ptr.add(i), 0);
        }
    });
    count as isize
}

/* Debugfs data structures. */
static fops_lockevent: file_operations = file_operations {
    read: Some(lockevent_read),
    write: Some(lockevent_write),
    llseek: Some(default_llseek),
};

#[cfg(CONFIG_PARAVIRT_SPINLOCKS)]
unsafe fn skip_lockevent(name: *const u8) -> bool {
    static mut pv_on: i32 = -1;

    if pv_on < 0 {
        pv_on = if pv_is_native_spin_unlock() { 0 } else { 1 };
    }
    /* Skip PV qspinlock events on bare metal. */
    if pv_on == 0 && memcmp(name, b"pv_\0".as_ptr(), 3) == 0 {
        return true;
    }
    false
}

#[cfg(not(CONFIG_PARAVIRT_SPINLOCKS))]
unsafe fn skip_lockevent(_name: *const u8) -> bool {
    false
}

/* Initialize debugfs for the locking event counts. */
unsafe fn init_lockevent_counts() -> i32 {
    let d_counts = debugfs_create_dir(LOCK_EVENTS_DIR, core::ptr::null_mut());

    if IS_ERR!(d_counts) {
        return init_lockevent_counts_out();
    }

    /* Create the debugfs files. */
    for i in 0..lockevent_num {
        if skip_lockevent(*lockevent_names.add(i)) {
            continue;
        }
        if IS_ERR!(debugfs_create_file(
            *lockevent_names.add(i),
            0o400,
            d_counts,
            i as *mut core::ffi::c_void,
            &fops_lockevent,
        )) {
            debugfs_remove_recursive(d_counts);
            return init_lockevent_counts_out();
        }
    }

    if IS_ERR!(debugfs_create_file(
        *lockevent_names.add(LOCKEVENT_reset_cnts),
        0o200,
        d_counts,
        LOCKEVENT_reset_cnts as *mut core::ffi::c_void,
        &fops_lockevent,
    )) {
        debugfs_remove_recursive(d_counts);
        return init_lockevent_counts_out();
    }

    0
}

unsafe fn init_lockevent_counts_out() -> i32 {
    pr_warn!("Could not create '%s' debugfs entries\n", LOCK_EVENTS_DIR);
    -ENOMEM
}

fs_initcall!(init_lockevent_counts);

