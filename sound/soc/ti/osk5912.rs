const CODEC_CLOCK: u32 = 12000000;

extern "C" {
    static mut tlv320aic23_mclk: *mut clk;

    fn clk_prepare_enable(clk: *mut clk) -> core::ffi::c_int;
    fn clk_disable_unprepare(clk: *mut clk);
    fn snd_soc_substream_to_rtd(
        substream: *mut snd_pcm_substream,
    ) -> *mut snd_soc_pcm_runtime;
    fn snd_soc_rtd_to_codec(
        rtd: *mut snd_soc_pcm_runtime,
        num: core::ffi::c_int,
    ) -> *mut snd_soc_dai;
    fn snd_soc_dai_set_sysclk(
        dai: *mut snd_soc_dai,
        clk_id: core::ffi::c_int,
        freq: core::ffi::c_uint,
        dir: core::ffi::c_int,
    ) -> core::ffi::c_int;
    fn printk(fmt: *const core::ffi::c_char, ...) -> core::ffi::c_int;
    fn machine_is_omap_osk() -> core::ffi::c_int;
    fn platform_device_alloc(
        name: *const core::ffi::c_char,
        id: core::ffi::c_int,
    ) -> *mut platform_device;
    fn platform_set_drvdata(pdev: *mut platform_device, data: *mut core::ffi::c_void);
    fn platform_device_add(pdev: *mut platform_device) -> core::ffi::c_int;
    fn clk_get(dev: *mut device, id: *const core::ffi::c_char) -> *mut clk;
    fn IS_ERR(ptr: *const core::ffi::c_void) -> core::ffi::c_int;
    fn PTR_ERR(ptr: *const core::ffi::c_void) -> core::ffi::c_long;
    fn clk_get_rate(clk: *mut clk) -> core::ffi::c_ulong;
    fn clk_set_rate(clk: *mut clk, rate: core::ffi::c_ulong) -> core::ffi::c_int;
    fn clk_put(clk: *mut clk);
    fn platform_device_del(pdev: *mut platform_device);
    fn platform_device_put(pdev: *mut platform_device);
    fn platform_device_unregister(pdev: *mut platform_device);

    static THIS_MODULE: *mut module;
}

