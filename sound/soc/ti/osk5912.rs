const SND_SOC_CLOCK_IN: core::ffi::c_int = 0;
const SND_SOC_DAIFMT_DSP_B: core::ffi::c_uint = 0;
const SND_SOC_DAIFMT_NB_NF: core::ffi::c_uint = 0;
const SND_SOC_DAIFMT_CBP_CFP: core::ffi::c_uint = 0;
const ENODEV: core::ffi::c_int = 19;
const ENOMEM: core::ffi::c_int = 12;
const ECANCELED: core::ffi::c_int = 125;
const KERN_ERR: &[u8] = b"\0";
const KERN_INFO: &[u8] = b"\0";

static mut osk_snd_device: *mut platform_device = core::ptr::null_mut();

unsafe extern "C" fn osk_startup(
    _substream: *mut snd_pcm_substream,
) -> core::ffi::c_int {
    unsafe { clk_prepare_enable(tlv320aic23_mclk) }
}

unsafe extern "C" fn osk_shutdown(_substream: *mut snd_pcm_substream) {
    unsafe {
        clk_disable_unprepare(tlv320aic23_mclk);
    }
}

unsafe extern "C" fn osk_hw_params(
    substream: *mut snd_pcm_substream,
    _params: *mut snd_pcm_hw_params,
) -> core::ffi::c_int {
    let rtd: *mut snd_soc_pcm_runtime = unsafe { snd_soc_substream_to_rtd(substream) };
    let codec_dai: *mut snd_soc_dai = unsafe { snd_soc_rtd_to_codec(rtd, 0) };
    let err: core::ffi::c_int;

    /* Set the codec system clock for DAC and ADC */
    err = unsafe {
        snd_soc_dai_set_sysclk(codec_dai, 0, CODEC_CLOCK as core::ffi::c_uint, SND_SOC_CLOCK_IN)
    };

    if err < 0 {
        unsafe {
            printk(
                concat!("\0", "can't set codec system clock\n\0").as_ptr()
                    as *const core::ffi::c_char,
            );
        }
        return err;
    }

    err
}

