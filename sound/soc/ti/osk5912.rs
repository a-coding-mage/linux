unsafe extern "C" fn osk_soc_init() -> core::ffi::c_int {
    let mut err: core::ffi::c_int;
    let curRate: u32;
    let dev: *mut device;

    unsafe {
        snd_soc_card_osk.owner = THIS_MODULE;
    }

    if unsafe { machine_is_omap_osk() } == 0 {
        return -ENODEV;
    }

    unsafe {
        osk_snd_device =
            platform_device_alloc(b"soc-audio\0".as_ptr() as *const core::ffi::c_char, -1);
    }
    if unsafe { osk_snd_device.is_null() } {
        return -ENOMEM;
    }

    unsafe {
        platform_set_drvdata(
            osk_snd_device,
            &mut snd_soc_card_osk as *mut snd_soc_card as *mut core::ffi::c_void,
        );
        err = platform_device_add(osk_snd_device);
    }
    if err != 0 {
        unsafe {
            platform_device_put(osk_snd_device);
        }
        return err;
    }

    dev = unsafe { &mut (*osk_snd_device).dev as *mut device };

    unsafe {
        tlv320aic23_mclk = clk_get(dev, b"mclk\0".as_ptr() as *const core::ffi::c_char);
    }
    if unsafe { IS_ERR(tlv320aic23_mclk as *const core::ffi::c_void) } != 0 {
        unsafe {
            printk(
                concat!("\0", "Could not get mclk clock\n\0").as_ptr()
                    as *const core::ffi::c_char,
            );
            err = PTR_ERR(tlv320aic23_mclk as *const core::ffi::c_void) as core::ffi::c_int;
            platform_device_del(osk_snd_device);
            platform_device_put(osk_snd_device);
        }
        return err;
    }

    /*
     * Configure 12 MHz output on MCLK.
     */
    curRate = unsafe { clk_get_rate(tlv320aic23_mclk) as core::ffi::c_uint };
    if curRate != CODEC_CLOCK {
        if unsafe { clk_set_rate(tlv320aic23_mclk, CODEC_CLOCK as core::ffi::c_ulong) } != 0 {
            unsafe {
                printk(
                    concat!("\0", "Cannot set MCLK for AIC23 CODEC\n\0").as_ptr()
                        as *const core::ffi::c_char,
                );
                err = -ECANCELED;
                clk_put(tlv320aic23_mclk);
                platform_device_del(osk_snd_device);
                platform_device_put(osk_snd_device);
            }
            return err;
        }
    }

    unsafe {
        printk(
            concat!("\0", "MCLK = %d [%d]\n\0").as_ptr() as *const core::ffi::c_char,
            clk_get_rate(tlv320aic23_mclk) as core::ffi::c_uint,
            CODEC_CLOCK,
        );
    }

    0
}

unsafe extern "C" fn osk_soc_exit() {
    unsafe {
        clk_put(tlv320aic23_mclk);
        platform_device_unregister(osk_snd_device);
    }
}

