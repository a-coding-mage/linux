pub unsafe extern "C" fn cs47l35_component_probe(component: *mut snd_soc_component) -> c_int {
    let dapm = snd_soc_component_to_dapm(component);
    let cs47l35 = snd_soc_component_get_drvdata(component) as *mut cs47l35;
    let madera = (*cs47l35).core.madera;
    let mut i: c_int;
    let mut ret: c_int;

    snd_soc_component_init_regmap(component, (*madera).regmap);

    mutex_lock(&mut (*madera).dapm_ptr_lock);
    (*madera).dapm = snd_soc_component_to_dapm(component);
    mutex_unlock(&mut (*madera).dapm_ptr_lock);

    ret = madera_init_inputs(component);
    if ret != 0 {
        return ret;
    }

    ret = madera_init_outputs(
        component,
        cs47l35_mono_routes.as_ptr(),
        cs47l35_mono_routes.len(),
        CS47L35_MONO_OUTPUTS,
    );
    if ret != 0 {
        return ret;
    }

    snd_soc_dapm_disable_pin(dapm, b"HAPTICS\0".as_ptr() as *const c_char);

    ret = snd_soc_add_component_controls(component, madera_adsp_rate_controls.as_ptr(), CS47L35_NUM_ADSP);
    if ret != 0 {
        return ret;
    }

    i = 0;
    while i < CS47L35_NUM_ADSP as c_int {
        wm_adsp2_component_probe(&mut (*cs47l35).core.adsp[i as usize], component);
        i += 1;
    }

    0
}

