pub unsafe extern "C" fn cs47l35_open(
    component: *mut snd_soc_component,
    stream: *mut snd_compr_stream,
) -> c_int {
    let rtd = (*stream).private_data as *mut snd_soc_pcm_runtime;
    let cs47l35 = snd_soc_component_get_drvdata(component) as *mut cs47l35;
    let priv_ = &mut (*cs47l35).core as *mut madera_priv;
    let madera = (*priv_).madera;
    let n_adsp: c_int;
    let codec = snd_soc_rtd_to_codec(rtd, 0);

    if strcmp((*codec).name, b"cs47l35-dsp-voicectrl\0".as_ptr() as *const c_char) == 0 {
        n_adsp = 2;
    } else if strcmp((*codec).name, b"cs47l35-dsp-trace\0".as_ptr() as *const c_char) == 0 {
        n_adsp = 0;
    } else {
        dev_err(
            (*madera).dev,
            b"No suitable compressed stream for DAI '%s'\n\0".as_ptr() as *const c_char,
            (*codec).name,
        );
        return -EINVAL;
    }

    wm_adsp_compr_open(&mut (*priv_).adsp[n_adsp as usize], stream)
}

pub unsafe extern "C" fn cs47l35_adsp2_irq(irq: c_int, data: *mut c_void) -> irqreturn_t {
    let _ = irq;
    let cs47l35 = data as *mut cs47l35;
    let priv_ = &mut (*cs47l35).core as *mut madera_priv;
    let madera = (*priv_).madera;
    let mut trig_info: madera_voice_trigger_info = core::mem::zeroed();
    let mut serviced: c_int = 0;
    let mut i: c_int = 0;
    let mut ret: c_int;

    while i < CS47L35_NUM_ADSP as c_int {
        ret = wm_adsp_compr_handle_irq(&mut (*priv_).adsp[i as usize]);
        if ret != -ENODEV {
            serviced += 1;
        }
        if ret == WM_ADSP_COMPR_VOICE_TRIGGER {
            trig_info.core_num = i + 1;
            blocking_notifier_call_chain(
                &mut (*madera).notifier,
                MADERA_NOTIFY_VOICE_TRIGGER,
                &mut trig_info as *mut _ as *mut c_void,
            );
        }
        i += 1;
    }

    if serviced == 0 {
        dev_err((*madera).dev, b"Spurious compressed data IRQ\n\0".as_ptr() as *const c_char);
        return IRQ_NONE;
    }

    IRQ_HANDLED
}

