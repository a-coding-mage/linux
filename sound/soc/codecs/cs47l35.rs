pub unsafe extern "C" fn cs47l35_probe(pdev: *mut platform_device) -> c_int {
    let madera = dev_get_drvdata((*(*pdev).dev.parent)) as *mut madera;
    let mut cs47l35: *mut cs47l35;
    let mut i: c_int;
    let mut ret: c_int;

    BUILD_BUG_ON!(ARRAY_SIZE!(cs47l35_dai) > MADERA_MAX_DAI);

    /* quick exit if Madera irqchip driver hasn't completed probe */
    if (*madera).irq_dev.is_null() {
        dev_dbg(&mut (*pdev).dev, b"irqchip driver not ready\n\0".as_ptr() as *const c_char);
        return -EPROBE_DEFER;
    }

    cs47l35 = devm_kzalloc(&mut (*pdev).dev, core::mem::size_of::<cs47l35>(), GFP_KERNEL) as *mut cs47l35;
    if cs47l35.is_null() {
        return -ENOMEM;
    }
    platform_set_drvdata(pdev, cs47l35 as *mut c_void);

    (*cs47l35).core.madera = madera;
    (*cs47l35).core.dev = &mut (*pdev).dev;
    (*cs47l35).core.num_inputs = 4;

    ret = madera_core_init(&mut (*cs47l35).core);
    if ret != 0 {
        return ret;
    }

    ret = madera_init_overheat(&mut (*cs47l35).core);
    if ret != 0 {
        madera_core_free(&mut (*cs47l35).core);
        return ret;
    }

    ret = madera_request_irq(madera, MADERA_IRQ_DSP_IRQ1, b"ADSP2 Compressed IRQ\0".as_ptr() as *const c_char, Some(cs47l35_adsp2_irq), cs47l35 as *mut c_void);
    if ret != 0 {
        dev_err(&mut (*pdev).dev, b"Failed to request DSP IRQ: %d\n\0".as_ptr() as *const c_char, ret);
        madera_free_overheat(&mut (*cs47l35).core);
        madera_core_free(&mut (*cs47l35).core);
        return ret;
    }

    ret = madera_set_irq_wake(madera, MADERA_IRQ_DSP_IRQ1, 1);
    if ret != 0 {
        dev_warn(&mut (*pdev).dev, b"Failed to set DSP IRQ wake: %d\n\0".as_ptr() as *const c_char, ret);
    }

    i = 0;
    while i < CS47L35_NUM_ADSP as c_int {
        (*cs47l35).core.adsp[i as usize].part = b"cs47l35\0".as_ptr() as *const c_char;
        (*cs47l35).core.adsp[i as usize].cs_dsp.num = i + 1;
        (*cs47l35).core.adsp[i as usize].cs_dsp.type_ = WMFW_ADSP2;
        (*cs47l35).core.adsp[i as usize].cs_dsp.rev = 1;
        (*cs47l35).core.adsp[i as usize].cs_dsp.dev = (*madera).dev;
        (*cs47l35).core.adsp[i as usize].cs_dsp.regmap = (*madera).regmap_32bit;
        (*cs47l35).core.adsp[i as usize].cs_dsp.base = wm_adsp2_control_bases[i as usize];
        (*cs47l35).core.adsp[i as usize].cs_dsp.mem = cs47l35_dsp_regions[i as usize];
        (*cs47l35).core.adsp[i as usize].cs_dsp.num_mems = cs47l35_dsp1_regions.len();

        ret = wm_adsp2_init(&mut (*cs47l35).core.adsp[i as usize]);
        if ret != 0 {
            i -= 1;
            while i >= 0 {
                wm_adsp2_remove(&mut (*cs47l35).core.adsp[i as usize]);
                i -= 1;
            }
            madera_set_irq_wake(madera, MADERA_IRQ_DSP_IRQ1, 0);
            madera_free_irq(madera, MADERA_IRQ_DSP_IRQ1, cs47l35 as *mut c_void);
            madera_free_overheat(&mut (*cs47l35).core);
            madera_core_free(&mut (*cs47l35).core);
            return ret;
        }
        i += 1;
    }

    madera_init_fll(madera, 1, MADERA_FLL1_CONTROL_1 - 1, &mut (*cs47l35).fll);

    i = 0;
    while i < ARRAY_SIZE!(cs47l35_dai) as c_int {
        madera_init_dai(&mut (*cs47l35).core, i);
        i += 1;
    }

    /* Latch volume update bits */
    i = 0;
    while i < cs47l35_digital_vu.len() as c_int {
        regmap_update_bits((*madera).regmap, cs47l35_digital_vu[i as usize], CS47L35_DIG_VU, CS47L35_DIG_VU);
        i += 1;
    }

    pm_runtime_enable(&mut (*pdev).dev);
    pm_runtime_idle(&mut (*pdev).dev);

    ret = devm_snd_soc_register_component(
        &mut (*pdev).dev,
        &soc_component_dev_cs47l35,
        cs47l35_dai.as_mut_ptr(),
        ARRAY_SIZE!(cs47l35_dai),
    );
    if ret < 0 {
        dev_err(&mut (*pdev).dev, b"Failed to register component: %d\n\0".as_ptr() as *const c_char, ret);
        pm_runtime_disable(&mut (*pdev).dev);
        i = 0;
        while i < CS47L35_NUM_ADSP as c_int {
            wm_adsp2_remove(&mut (*cs47l35).core.adsp[i as usize]);
            i += 1;
        }
        madera_set_irq_wake(madera, MADERA_IRQ_DSP_IRQ1, 0);
        madera_free_irq(madera, MADERA_IRQ_DSP_IRQ1, cs47l35 as *mut c_void);
        madera_free_overheat(&mut (*cs47l35).core);
        madera_core_free(&mut (*cs47l35).core);
        return ret;
    }

    ret
}

pub unsafe extern "C" fn cs47l35_remove(pdev: *mut platform_device) {
    let cs47l35 = platform_get_drvdata(pdev) as *mut cs47l35;
    let mut i: c_int = 0;

    pm_runtime_disable(&mut (*pdev).dev);

    while i < CS47L35_NUM_ADSP as c_int {
        wm_adsp2_remove(&mut (*cs47l35).core.adsp[i as usize]);
        i += 1;
    }

    madera_set_irq_wake((*cs47l35).core.madera, MADERA_IRQ_DSP_IRQ1, 0);
    madera_free_irq((*cs47l35).core.madera, MADERA_IRQ_DSP_IRQ1, cs47l35 as *mut c_void);
    madera_free_overheat(&mut (*cs47l35).core);
    madera_core_free(&mut (*cs47l35).core);
}

