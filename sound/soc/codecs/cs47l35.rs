pub unsafe extern "C" fn cs47l35_hp_post_enable(w: *mut snd_soc_dapm_widget) {
    let component = snd_soc_dapm_to_component((*w).dapm);
    let mut val: c_uint;

    match (*w).shift {
        MADERA_OUT1L_ENA_SHIFT | MADERA_OUT1R_ENA_SHIFT => {
            val = snd_soc_component_read(component, MADERA_OUTPUT_ENABLES_1);
            val &= MADERA_OUT1L_ENA | MADERA_OUT1R_ENA;

            if val != (MADERA_OUT1L_ENA | MADERA_OUT1R_ENA) {
                return;
            }

            snd_soc_component_update_bits(component, MADERA_EDRE_HP_STEREO_CONTROL, 0x0001, 1);
        }
        _ => {}
    }
}

pub unsafe extern "C" fn cs47l35_hp_post_disable(w: *mut snd_soc_dapm_widget) {
    let component = snd_soc_dapm_to_component((*w).dapm);

    match (*w).shift {
        MADERA_OUT1L_ENA_SHIFT => {
            snd_soc_component_write(component, MADERA_DCS_HP1L_CONTROL, 0x2006);
        }
        MADERA_OUT1R_ENA_SHIFT => {
            snd_soc_component_write(component, MADERA_DCS_HP1R_CONTROL, 0x2006);
        }
        _ => return,
    }

    /* Only get to here for OUT1L and OUT1R */
    snd_soc_component_update_bits(component, MADERA_EDRE_HP_STEREO_CONTROL, 0x0001, 0);
}

pub unsafe extern "C" fn cs47l35_hp_ev(
    w: *mut snd_soc_dapm_widget,
    kcontrol: *mut snd_kcontrol,
    event: c_int,
) -> c_int {
    let ret: c_int;

    match event {
        SND_SOC_DAPM_PRE_PMU | SND_SOC_DAPM_PRE_PMD => madera_hp_ev(w, kcontrol, event),
        SND_SOC_DAPM_POST_PMU => {
            ret = madera_hp_ev(w, kcontrol, event);
            if ret < 0 {
                return ret;
            }

            cs47l35_hp_post_enable(w);
            0
        }
        SND_SOC_DAPM_POST_PMD => {
            ret = madera_hp_ev(w, kcontrol, event);
            cs47l35_hp_post_disable(w);
            ret
        }
        _ => -EINVAL,
    }
}

