pub unsafe extern "C" fn cs47l35_adsp_power_ev(
    w: *mut snd_soc_dapm_widget,
    kcontrol: *mut snd_kcontrol,
    event: c_int,
) -> c_int {
    let component = snd_soc_dapm_to_component((*w).dapm);
    let cs47l35 = snd_soc_component_get_drvdata(component) as *mut cs47l35;
    let priv_ = &mut (*cs47l35).core as *mut madera_priv;
    let madera = (*priv_).madera;
    let mut freq: c_uint = 0;
    let mut ret: c_int;

    ret = regmap_read((*madera).regmap, MADERA_DSP_CLOCK_1, &mut freq);
    if ret != 0 {
        dev_err((*madera).dev, b"Failed to read MADERA_DSP_CLOCK_1: %d\n\0".as_ptr() as *const c_char, ret);
        return ret;
    }

    freq &= MADERA_DSP_CLK_FREQ_LEGACY_MASK;
    freq >>= MADERA_DSP_CLK_FREQ_LEGACY_SHIFT;

    match event {
        SND_SOC_DAPM_PRE_PMU => {
            ret = madera_set_adsp_clk(&mut (*cs47l35).core, (*w).shift, freq);
            if ret != 0 {
                return ret;
            }
        }
        _ => {}
    }

    wm_adsp_early_event(w, kcontrol, event)
}

