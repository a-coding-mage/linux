// Dependency intent from C header: #include <linux/types.h>

const fn BIT(nr: u32) -> u32 {
    1u32 << nr
}

const fn GENMASK(h: u32, l: u32) -> u32 {
    u32::MAX.wrapping_shl(l) & u32::MAX.wrapping_shr(31 - h)
}

