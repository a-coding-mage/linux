pub const fn BIT(n: u32) -> u32 {
    1u32 << n
}

pub const fn GENMASK(h: u32, l: u32) -> u32 {
    u32::MAX.wrapping_shl(l) & u32::MAX.wrapping_shr(31 - h)
}

pub const TAS675X_PAGE_SIZE: u32 = 256;
pub const fn TAS675X_PAGE_REG(page: u32, reg: u32) -> u32 {
    page * TAS675X_PAGE_SIZE + reg
}

