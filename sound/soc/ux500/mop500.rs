// Probe function for device tree initialization
unsafe fn mop500_of_probe(card: *mut SndSocCard) -> i32 {
    let dev = (*card).dev as *mut Device;
    let np = (*dev).of_node;

    let mut codec_np: *mut DeviceNode;
    let mut msp_np: [*mut DeviceNode; 2] = [ptr::null_mut(); 2];

    msp_np[0] = of_parse_phandle(np, b"stericsson,cpu-dai\0".as_ptr(), 0);
    msp_np[1] = of_parse_phandle(np, b"stericsson,cpu-dai\0".as_ptr(), 1);
    codec_np = of_parse_phandle(np, b"stericsson,audio-codec\0".as_ptr(), 0);

    if msp_np[0].is_null() || msp_np[1].is_null() || codec_np.is_null() {
        dev_err(dev, b"Phandle missing or invalid\n\0".as_ptr());
        let mut i: i32 = 0;
        while i < 2 {
            of_node_put(msp_np[i as usize]);
            i += 1;
        }
        of_node_put(codec_np);
        return -22; // -EINVAL
    }

    let mut i: i32 = 0;
    while i < 2 {
        let idx = i as usize;
        let link = &mut MOP500_DAI_LINKS[idx];

        // Set device tree references and clear name references
        // This requires access to internal struct fields not available here
        // The actual assignment would be:
        // link.cpus->of_node = msp_np[i];
        // link.cpus->dai_name = NULL;
        // link.platforms->of_node = msp_np[i];
        // link.platforms->name = NULL;
        // link.codecs->of_node = codec_np;
        // link.codecs->name = NULL;

        i += 1;
    }

    snd_soc_of_parse_card_name(card, b"stericsson,card-name\0".as_ptr());

    0
}

// Main probe function called by kernel device driver
unsafe fn mop500_probe(pdev: *mut PlatformDevice) -> i32 {
    let mut ret: i32;

    dev_dbg(
        &(*pdev).dev,
        b"%s: Enter.\n\0".as_ptr(),
        b"mop500_probe\0".as_ptr(),
    );

    // Set device reference in card
    // MOP500_CARD.dev = &pdev->dev;
    // Cannot complete without kernel struct definition

    ret = mop500_of_probe(&mut MOP500_CARD);
    if ret != 0 {
        return ret;
    }

    dev_dbg(
        &(*pdev).dev,
        b"%s: Card %s: Set platform drvdata.\n\0".as_ptr(),
        b"mop500_probe\0".as_ptr(),
        MOP500_CARD_NAME.as_ptr(),
    );

    snd_soc_card_set_drvdata(&mut MOP500_CARD, ptr::null_mut());

    dev_dbg(
        &(*pdev).dev,
        b"%s: Card %s: num_links = %d\n\0".as_ptr(),
        b"mop500_probe\0".as_ptr(),
        MOP500_CARD_NAME.as_ptr(),
        // MOP500_CARD.num_links - cannot access without struct definition
    );
    dev_dbg(
        &(*pdev).dev,
        b"%s: Card %s: DAI-link 0: name = %s\n\0".as_ptr(),
        b"mop500_probe\0".as_ptr(),
        MOP500_CARD_NAME.as_ptr(),
        // MOP500_CARD.dai_link[0].name - cannot access without struct definition
    );
    dev_dbg(
        &(*pdev).dev,
        b"%s: Card %s: DAI-link 0: stream_name = %s\n\0".as_ptr(),
        b"mop500_probe\0".as_ptr(),
        MOP500_CARD_NAME.as_ptr(),
        // MOP500_CARD.dai_link[0].stream_name - cannot access without struct definition
    );

    ret = snd_soc_register_card(&mut MOP500_CARD);
    if ret != 0 {
        dev_err(
            &(*pdev).dev,
            b"Error: snd_soc_register_card failed (%d)!\n\0".as_ptr(),
            ret,
        );
    }

    ret
}

// Remove function called when driver is unloaded
unsafe fn mop500_remove(pdev: *mut PlatformDevice) {
    let card: *mut SndSocCard = platform_get_drvdata(pdev as *const PlatformDevice);

    pr_debug(b"%s: Enter.\n\0".as_ptr(), b"mop500_remove\0".as_ptr());

    snd_soc_unregister_card(card);
    mop500_ab8500_remove(card);
    mop500_of_node_put();
}

