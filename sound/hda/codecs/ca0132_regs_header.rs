pub const fn UC_RANGE(a: u32, s: u32) -> bool {
    (a >= UC_CHIP_OFFSET) && (a + (s - 1) * UC_UC_CHAN_INCR < UC_END)
}

pub const fn X_OFF(a: u32) -> u32 {
    (a - XRAM_CHIP_OFFSET) / XRAM_XRAM_CHAN_INCR
}

pub const fn AX_OFF(a: u32) -> u32 {
    (a % (AXRAM_AXRAM_CHANNEL_COUNT * AXRAM_AXRAM_CHAN_INCR)) / AXRAM_AXRAM_CHAN_INCR
}

pub const fn Y_OFF(a: u32) -> u32 {
    (a - YRAM_CHIP_OFFSET) / YRAM_YRAM_CHAN_INCR
}

pub const fn AY_OFF(a: u32) -> u32 {
    (a % (AYRAM_AYRAM_CHANNEL_COUNT * AYRAM_AYRAM_CHAN_INCR)) / AYRAM_AYRAM_CHAN_INCR
}

pub const fn UC_OFF(a: u32) -> u32 {
    (a - UC_CHIP_OFFSET) / UC_UC_CHAN_INCR
}

pub const fn X_EXT_MAIN_SIZE(a: u32) -> u32 {
    XRAM_XRAM_CHANNEL_COUNT - X_OFF(a)
}

pub const fn X_EXT_AUX_SIZE(a: u32, s: u32) -> u32 {
    s - X_EXT_MAIN_SIZE(a)
}

pub const fn Y_EXT_MAIN_SIZE(a: u32) -> u32 {
    YRAM_YRAM_CHANNEL_COUNT - Y_OFF(a)
}

pub const fn Y_EXT_AUX_SIZE(a: u32, s: u32) -> u32 {
    s - Y_EXT_MAIN_SIZE(a)
}

