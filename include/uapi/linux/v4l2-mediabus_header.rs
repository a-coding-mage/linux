pub const V4L2_MBUS_FRAMEFMT_SET_CSC: u32 = 0x0001;

/**
 * struct v4l2_mbus_framefmt - frame format on the media bus
 * @width: image width
 * @height: image height
 * @code: data format code (from enum v4l2_mbus_pixelcode)
 * @field: used interlacing type (from enum v4l2_field), zero for metadata
 *  mbus codes
 * @colorspace: colorspace of the data (from enum v4l2_colorspace), zero on
 *  metadata mbus codes
 * @ycbcr_enc: YCbCr encoding of the data (from enum v4l2_ycbcr_encoding), zero
 *  for metadata mbus codes
 * @hsv_enc: HSV encoding of the data (from enum v4l2_hsv_encoding), zero for
 *  metadata mbus codes
 * @quantization: quantization of the data (from enum v4l2_quantization), zero
 *  for metadata mbus codes
 * @xfer_func: transfer function of the data (from enum v4l2_xfer_func), zero
 *  for metadata mbus codes
 * @flags: flags (V4L2_MBUS_FRAMEFMT_*)
 * @reserved: reserved bytes that can be later used
 */
#[repr(C)]
pub struct v4l2_mbus_framefmt {
    pub width: u32,
    pub height: u32,
    pub code: u32,
    pub field: u32,
    pub colorspace: u32,
    pub encoding: v4l2_mbus_framefmt__encoding,
    pub quantization: u16,
    pub xfer_func: u16,
    pub flags: u16,
    pub reserved: [u16; 10],
}

#[repr(C)]
pub union v4l2_mbus_framefmt__encoding {
    /* enum v4l2_ycbcr_encoding */
    pub ycbcr_enc: u16,
    /* enum v4l2_hsv_encoding */
    pub hsv_enc: u16,
}

