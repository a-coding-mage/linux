// Dependencies supplied by the surrounding translation unit:
// linux/fcntl.h, linux/types.h, O_CLOEXEC, __poll_t, _IOW, and _IOR.

/* Flags for epoll_create1. */
pub const EPOLL_CLOEXEC: _ = O_CLOEXEC;

/* Valid opcodes to issue to sys_epoll_ctl() */
pub const EPOLL_CTL_ADD: i32 = 1;
pub const EPOLL_CTL_DEL: i32 = 2;
pub const EPOLL_CTL_MOD: i32 = 3;

/* Epoll event masks */
pub const EPOLLIN: __poll_t = 0x00000001 as __poll_t;
pub const EPOLLPRI: __poll_t = 0x00000002 as __poll_t;
pub const EPOLLOUT: __poll_t = 0x00000004 as __poll_t;
pub const EPOLLERR: __poll_t = 0x00000008 as __poll_t;
pub const EPOLLHUP: __poll_t = 0x00000010 as __poll_t;
pub const EPOLLNVAL: __poll_t = 0x00000020 as __poll_t;
pub const EPOLLRDNORM: __poll_t = 0x00000040 as __poll_t;
pub const EPOLLRDBAND: __poll_t = 0x00000080 as __poll_t;
pub const EPOLLWRNORM: __poll_t = 0x00000100 as __poll_t;
pub const EPOLLWRBAND: __poll_t = 0x00000200 as __poll_t;
pub const EPOLLMSG: __poll_t = 0x00000400 as __poll_t;
pub const EPOLLRDHUP: __poll_t = 0x00002000 as __poll_t;

/* Internal flag - wakeup generated by io_uring, used to detect recursion back
 * into the io_uring poll handler. */
pub const EPOLL_URING_WAKE: __poll_t = (1u32 << 27) as __poll_t;

/* Set exclusive wakeup mode for the target file descriptor */
pub const EPOLLEXCLUSIVE: __poll_t = (1u32 << 28) as __poll_t;

/* Request the handling of system wakeup events so as to prevent system
 * suspends from happening while those events are being processed.
 *
 * Assuming neither EPOLLET nor EPOLLONESHOT is set, system suspends will not
 * be re-allowed until epoll_wait is called again after consuming the wakeup
 * event(s).
 *
 * Requires CAP_BLOCK_SUSPEND */
pub const EPOLLWAKEUP: __poll_t = (1u32 << 29) as __poll_t;

/* Set the One Shot behaviour for the target file descriptor */
pub const EPOLLONESHOT: __poll_t = (1u32 << 30) as __poll_t;

/* Set the Edge Triggered behaviour for the target file descriptor */
pub const EPOLLET: __poll_t = (1u32 << 31) as __poll_t;

/* On x86-64 the 64-bit structure has the same alignment as the 32-bit
 * structure. This makes 32-bit emulation easier. */
#[cfg_attr(target_arch = "x86_64", repr(packed))]
#[repr(C)]
pub struct epoll_event {
    pub events: __poll_t,
    pub data: __u64,
}

#[repr(C)]
pub struct epoll_params {
    pub busy_poll_usecs: __u32,
    pub busy_poll_budget: __u16,
    pub prefer_busy_poll: __u8,

    /* pad the struct to a multiple of 64bits */
    pub __pad: __u8,
}

pub const EPOLL_IOC_TYPE: u8 = 0x8A;
pub const EPIOCSPARAMS: _ = _IOW(EPOLL_IOC_TYPE, 0x01, epoll_params);
pub const EPIOCGPARAMS: _ = _IOR(EPOLL_IOC_TYPE, 0x02, epoll_params);

