macro_rules! smc_enum {
    ($($name:ident),+ $(,)?) => { smc_enum!(@inner 0; $($name),+); };
    (@inner $n:expr; $head:ident, $($tail:ident),+) => {
        pub const $head: u32 = $n;
        smc_enum!(@inner $n + 1; $($tail),+);
    };
    (@inner $n:expr; $last:ident) => { pub const $last: u32 = $n; };
}

