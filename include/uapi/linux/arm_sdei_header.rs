pub const SDEI_1_0_FN_BASE: u64 = 0xC4000020;
pub const SDEI_1_0_MASK: u64 = 0xFFFFFFE0;
pub const fn SDEI_1_0_FN(n: u64) -> u64 {
    SDEI_1_0_FN_BASE + n
}

