// show_event_type(type) expands to the kernel's __print_symbolic() helper.
// The event constants are provided by linux/i2c.h.
#[allow(non_camel_case_types)]
pub type i2c_slave_event = i32;

#[allow(non_camel_case_types)]
#[repr(C)]
pub struct i2c_slave_trace_entry {
    pub adapter_nr: i32,
    pub ret: i32,
    pub addr: u16,
    pub len: u16,
    pub event: i2c_slave_event,
    pub buf: [u8; 1],
}

#[allow(non_camel_case_types)]
#[repr(C)]
pub struct i2c_client;

extern "C" {
    // These accessors stand for the fields used by the C expression
    // client->adapter->nr and client->addr; their definitions are external.
    pub fn i2c_slave_client_adapter_nr(client: *const i2c_client) -> i32;
    pub fn i2c_slave_client_addr(client: *const i2c_client) -> u16;
}

/// Source-level equivalent of the TRACE_EVENT(i2c_slave) fast assignment.
#[allow(non_snake_case)]
pub unsafe fn i2c_slave_fast_assign(
    entry: *mut i2c_slave_trace_entry,
    client: *const i2c_client,
    event: i2c_slave_event,
    val: *const u8,
    cb_ret: i32,
) {
    (*entry).adapter_nr = i2c_slave_client_adapter_nr(client);
    (*entry).addr = i2c_slave_client_addr(client);
    (*entry).event = event;
    (*entry).ret = cb_ret;

    // I2C_SLAVE_READ_REQUESTED, I2C_SLAVE_READ_PROCESSED, and
    // I2C_SLAVE_WRITE_RECEIVED are supplied by linux/i2c.h.
    if event == I2C_SLAVE_READ_REQUESTED
        || event == I2C_SLAVE_READ_PROCESSED
        || event == I2C_SLAVE_WRITE_RECEIVED
    {
        (*entry).len = 1;
        (*entry).buf[0] = core::ptr::read(val);
    } else {
        (*entry).len = 0;
    }
}

// The following constants are external C enum values from <linux/i2c.h>.
// They remain unresolved here so this header can use the supplied dependency.
extern "C" {
    pub static I2C_SLAVE_READ_REQUESTED: i2c_slave_event;
    pub static I2C_SLAVE_READ_PROCESSED: i2c_slave_event;
    pub static I2C_SLAVE_WRITE_RECEIVED: i2c_slave_event;
}

