/* unmap: (unsigned long iova, size_t size, size_t unmapped_size) */
/* TP_printk: "IOMMU: iova=0x%016llx - 0x%016llx size=%zu unmapped_size=%zu" */

/* iommu_error: (struct device *dev, unsigned long iova, int flags) */
