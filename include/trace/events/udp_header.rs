// TRACE_SYSTEM udp
// The C header guard and trace-header multi-read condition are preprocessor
// directives; Rust modules provide the corresponding inclusion protection.

use core::ffi::c_int;

/// Entry data recorded by the `udp_fail_queue_rcv_skb` trace event.
#[repr(C)]
pub struct UdpFailQueueRcvSkbEntry {
    pub rc: c_int,
    pub sport: u16,
    pub dport: u16,
    pub family: u16,
    pub saddr: [u8; core::mem::size_of::<SockaddrIn6>()],
    pub daddr: [u8; core::mem::size_of::<SockaddrIn6>()],
}

/// Opaque dependency supplied by `<linux/udp.h>`.
#[repr(C)]
pub struct Udphdr {
    pub source: u16,
    pub dest: u16,
    _rest: [u8; 4],
}

/// Opaque dependency supplied by `<linux/tracepoint.h>` and networking headers.
#[repr(C)]
pub struct Sock;

/// Opaque dependency supplied by `<linux/tracepoint.h>` and networking headers.
#[repr(C)]
pub struct SkBuff;

/// Opaque representation of `struct sockaddr_in6` from the kernel headers.
#[repr(C)]
pub struct SockaddrIn6 {
    _private: [u8; 28],
}

/// Translation of the `TP_fast_assign` portion of `udp_fail_queue_rcv_skb`.
/// External networking and trace helpers remain dependencies of this header.
pub unsafe fn udp_fail_queue_rcv_skb_fast_assign(
    entry: *mut UdpFailQueueRcvSkbEntry,
    rc: c_int,
    sk: *const Sock,
    skb: *const SkBuff,
) {
    // const struct udphdr *uh = (const struct udphdr *)udp_hdr(skb);
    let uh = udp_hdr(skb);

    (*entry).rc = rc;

    // for filtering use
    (*entry).sport = ntohs((*uh).source);
    (*entry).dport = ntohs((*uh).dest);
    (*entry).family = (*(sk as *const SockLayout)).sk_family;

    (*entry).saddr.fill(0);
    (*entry).daddr.fill(0);

    tp_store_addr_ports_skb(skb, uh, (*entry).saddr.as_mut_ptr(), (*entry).daddr.as_mut_ptr());
}

/// Dependencies supplied by the included kernel and trace headers.
extern "C" {
    pub fn udp_hdr(skb: *const SkBuff) -> *const Udphdr;
    pub fn ntohs(value: u16) -> u16;
    pub fn tp_store_addr_ports_skb(
        skb: *const SkBuff,
        uh: *const Udphdr,
        saddr: *mut u8,
        daddr: *mut u8,
    );
}

// Fields accessed through the externally supplied `struct sock`.
#[repr(C)]
struct SockLayout {
    _prefix: [u8; 0],
    sk_family: u16,
}

