//! Rust translation of the CPU hotplug tracepoint header.
//!
//! The C `TRACE_EVENT` definitions depend on the Linux tracepoint framework.
//! The entry layouts and callback interfaces are preserved here; tracepoint
//! registration and formatting remain supplied by that external framework.

use core::ffi::c_void;

#[repr(C)]
pub struct CpuhpEnterEntry {
    pub cpu: u32,
    pub target: i32,
    pub idx: i32,
    pub fun: *mut c_void,
}

pub type CpuhpEnterFun = unsafe extern "C" fn(cpu: u32) -> i32;

pub const CPUHP_ENTER_PRINTK: &str = "cpu: %04u target: %3d step: %3d (%ps)";

#[repr(C)]
pub struct CpuhpMultiEnterEntry {
    pub cpu: u32,
    pub target: i32,
    pub idx: i32,
    pub fun: *mut c_void,
}

#[repr(C)]
pub struct HlistNode {
    pub next: *mut HlistNode,
    pub pprev: *mut *mut HlistNode,
}

pub type CpuhpMultiEnterFun =
    unsafe extern "C" fn(cpu: u32, node: *mut HlistNode) -> i32;

pub const CPUHP_MULTI_ENTER_PRINTK: &str = "cpu: %04u target: %3d step: %3d (%ps)";

#[repr(C)]
pub struct CpuhpExitEntry {
    pub cpu: u32,
    pub state: i32,
    pub idx: i32,
    pub ret: i32,
}

pub const CPUHP_EXIT_PRINTK: &str = " cpu: %04u  state: %3d step: %3d ret: %d";

/// External tracepoint hooks generated by the Linux tracepoint framework.
/// Their implementations and registration are provided by another dependency.
extern "C" {
    pub fn trace_cpuhp_enter(
        cpu: u32,
        target: i32,
        idx: i32,
        fun: CpuhpEnterFun,
    );

    pub fn trace_cpuhp_multi_enter(
        cpu: u32,
        target: i32,
        idx: i32,
        fun: CpuhpMultiEnterFun,
        node: *mut HlistNode,
    );

    pub fn trace_cpuhp_exit(cpu: u32, state: i32, idx: i32, ret: i32);
}

