// TRACE_SYSTEM fsnotify
//
// The C header's tracepoint dependencies are supplied by the surrounding
// kernel translation.  TRACE_HEADER_MULTI_READ and the include guard are
// preprocessor-only controls and have no executable Rust equivalent.

use core::ffi::c_char;

pub type __u32 = u32;
pub type u32_t = u32;
pub type dev_t = u64;

#[repr(C)]
pub struct super_block {
    pub s_dev: dev_t,
}

#[repr(C)]
pub struct inode {
    pub i_ino: libc::c_ulong,
    pub i_sb: *mut super_block,
}

#[repr(C)]
pub struct qstr {
    pub name: *const c_char,
}

#[repr(C)]
pub struct FsnotifyEntry {
    pub mask: __u32,
    pub dir_ino: libc::c_ulong,
    pub ino: libc::c_ulong,
    pub s_dev: dev_t,
    pub data_type: libc::c_int,
    pub cookie: u32_t,
    // __string(file_name, ...) is a dynamically sized trace entry string.
    pub file_name: *const c_char,
}

extern "C" {
    pub fn show_fsnotify_mask(mask: __u32) -> *const c_char;
    pub fn major(dev: dev_t) -> libc::c_uint;
    pub fn minor(dev: dev_t) -> libc::c_uint;
}

/// Translation of the TRACE_EVENT(fsnotify) TP_fast_assign block.
#[inline]
pub unsafe fn fsnotify_fast_assign(
    entry: *mut FsnotifyEntry,
    mask: __u32,
    _data: *const core::ffi::c_void,
    data_type: libc::c_int,
    dir: *mut inode,
    file_name: *const qstr,
    inode_: *const inode,
    cookie: u32_t,
) {
    (*entry).mask = mask;
    (*entry).dir_ino = if !dir.is_null() { (*dir).i_ino } else { 0 };
    (*entry).ino = if !inode_.is_null() { (*inode_).i_ino } else { 0 };
    (*entry).s_dev = if !dir.is_null() {
        (*(*dir).i_sb).s_dev
    } else if !inode_.is_null() {
        (*(*inode_).i_sb).s_dev
    } else {
        0
    };
    (*entry).data_type = data_type;
    (*entry).cookie = cookie;
    (*entry).file_name = if !file_name.is_null() {
        (*file_name).name
    } else {
        c"".as_ptr()
    };
}

// TRACE_EVENT(fsnotify) emits a tracepoint whose printk format is:
// "dev=%d:%d dir=%lu ino=%lu data_type=%d cookie=0x%x mask=0x%x %s name=%s"
// with MAJOR/MINOR(s_dev), show_fsnotify_mask(mask), and file_name.
// The tracepoint registration itself is generated by the kernel trace macros.

