/* GPIOMUX bits: dout 31-24, doen 23-16, din 15-8, dout rev 7, doen rev 6, gpio nr 5-0. */
#[inline]
pub const fn GPIOMUX(n: u32, dout: u32, doen: u32, din: u32) -> u32 {
    ((dout & 0x80000000) >> (31 - 7)) | ((dout & 0xff) << 24) |
    ((doen & 0x80000000) >> (31 - 6)) | ((doen & 0xff) << 16) |
    ((din & 0xff) << 8) | (n & 0x3f)
}

