/*
 * Defines macros and constants for Renesas RZ/N1 pin controller pin
 * muxing functions.
 */

/// Equivalent to the C preprocessor macro `RZN1_PINMUX`.
pub const fn rzn1_pinmux(gpio: i32, func: i32) -> i32 {
    (func << 8) | gpio
}

