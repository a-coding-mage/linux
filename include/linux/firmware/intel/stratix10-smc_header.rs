// Shared Secure Monitor Call protocol definitions.
// The ARM_SMCCC_* names are supplied by the corresponding ARM SMCCC bindings.

macro_rules! INTEL_SIP_SMC_STD_CALL_VAL {
    ($func_num:expr) => {
        ARM_SMCCC_CALL_VAL!(ARM_SMCCC_STD_CALL, ARM_SMCCC_SMC_64,
                            ARM_SMCCC_OWNER_SIP, $func_num)
    };
}

macro_rules! INTEL_SIP_SMC_FAST_CALL_VAL {
    ($func_num:expr) => {
        ARM_SMCCC_CALL_VAL!(ARM_SMCCC_FAST_CALL, ARM_SMCCC_SMC_64,
                            ARM_SMCCC_OWNER_SIP, $func_num)
    };
}

macro_rules! INTEL_SIP_SMC_ASYNC_VAL {
    ($func_name:expr) => {
        ARM_SMCCC_CALL_VAL!(ARM_SMCCC_STD_CALL, ARM_SMCCC_SMC_64,
                            ARM_SMCCC_OWNER_SIP, $func_name)
    };
}

