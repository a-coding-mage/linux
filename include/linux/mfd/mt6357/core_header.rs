/* The C macro token-pastes the interrupt-group name; Rust requires the
 * corresponding external identifiers to be passed explicitly. */
#[macro_export]
macro_rules! MT6357_TOP_GEN {
    ($hwirq_base:expr, $num_int_regs:expr, $en_reg:expr, $sta_reg:expr, $top_offset:expr) => {
        {
            hwirq_base: $hwirq_base,
            num_int_regs: (($num_int_regs - 1) / MTK_PMIC_REG_WIDTH) + 1,
            en_reg: $en_reg,
            en_reg_shift: 0x6,
            sta_reg: $sta_reg,
            sta_reg_shift: 0x2,
            top_offset: $top_offset,
        }
    };
}

