/* Direct Rust equivalents of the C header enumerations and macros. */
macro_rules! s2mpg10_enum {
    ($($name:ident),+ $(,)?) => { s2mpg10_enum!(@n 0u32; $($name),+); };
    (@n $n:expr; $name:ident, $($rest:ident),+) => {
        pub const $name: u32 = $n;
        s2mpg10_enum!(@n $n + 1; $($rest),+);
    };
    (@n $n:expr; $name:ident) => { pub const $name: u32 = $n; };
}

