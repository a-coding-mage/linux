pub const APLIC_xMSICFGADDR_PPN_SHIFT: u32 = 12;

pub const fn APLIC_xMSICFGADDR_PPN_HART(lhxs: u32) -> u32 { (1u32 << lhxs).wrapping_sub(1) }
pub const fn APLIC_xMSICFGADDR_PPN_LHX_MASK(lhxw: u32) -> u32 { (1u32 << lhxw).wrapping_sub(1) }
pub const fn APLIC_xMSICFGADDR_PPN_LHX_SHIFT(lhxs: u32) -> u32 { lhxs }
pub const fn APLIC_xMSICFGADDR_PPN_LHX(lhxw: u32, lhxs: u32) -> u32 {
    APLIC_xMSICFGADDR_PPN_LHX_MASK(lhxw) << APLIC_xMSICFGADDR_PPN_LHX_SHIFT(lhxs)
}
pub const fn APLIC_xMSICFGADDR_PPN_HHX_MASK(hhxw: u32) -> u32 { (1u32 << hhxw).wrapping_sub(1) }
pub const fn APLIC_xMSICFGADDR_PPN_HHX_SHIFT(hhxs: u32) -> u32 { hhxs + APLIC_xMSICFGADDR_PPN_SHIFT }
pub const fn APLIC_xMSICFGADDR_PPN_HHX(hhxw: u32, hhxs: u32) -> u32 {
    APLIC_xMSICFGADDR_PPN_HHX_MASK(hhxw) << APLIC_xMSICFGADDR_PPN_HHX_SHIFT(hhxs)
}

