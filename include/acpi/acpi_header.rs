/*
 * Public include files for use by code that will interface to ACPICA.
 *
 * Information includes the ACPICA data types, names, exceptions, and
 * external interface prototypes. Also included are the definitions for
 * all ACPI tables (FADT, MADT, etc.)
 *
 * Note: The order of these include files is important.
 */

/* Environment-specific items: <acpi/platform/acenv.h> */
/* Common ACPI names and strings: <acpi/acnames.h> */
/* ACPICA data types and structures: <acpi/actypes.h> */
/* ACPICA exceptions: <acpi/acexcep.h> */
/* ACPI table definitions: <acpi/actbl.h> */
/* Resource Descriptor structs: <acpi/acrestyp.h> */
/* Extra environment-specific items: <acpi/platform/acenvex.h> */
/* Error output and Debug macros: <acpi/acoutput.h> */
/* OSL interfaces (ACPICA-to-OS): <acpi/acpiosxf.h> */
/* ACPI core subsystem external interfaces: <acpi/acpixf.h> */

