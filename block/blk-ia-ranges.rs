// Dependencies supplied by the Linux kernel and blk.h are intentionally external.

unsafe fn blk_ia_range_sector_show(
    iar: *mut blk_independent_access_range,
    buf: *mut core::ffi::c_char,
) -> isize {
    sprintf(buf, b"%llu\n\0".as_ptr() as *const core::ffi::c_char, (*iar).sector)
}

unsafe fn blk_ia_range_nr_sectors_show(
    iar: *mut blk_independent_access_range,
    buf: *mut core::ffi::c_char,
) -> isize {
    sprintf(buf, b"%llu\n\0".as_ptr() as *const core::ffi::c_char, (*iar).nr_sectors)
}

#[repr(C)]
struct blk_ia_range_sysfs_entry {
    attr: attribute,
    show: unsafe fn(*mut blk_independent_access_range, *mut core::ffi::c_char) -> isize,
}

static blk_ia_range_sector_entry: blk_ia_range_sysfs_entry = blk_ia_range_sysfs_entry {
    attr: attribute { name: b"sector\0".as_ptr() as *const core::ffi::c_char, mode: 0o444 },
    show: blk_ia_range_sector_show,
};

static blk_ia_range_nr_sectors_entry: blk_ia_range_sysfs_entry = blk_ia_range_sysfs_entry {
    attr: attribute { name: b"nr_sectors\0".as_ptr() as *const core::ffi::c_char, mode: 0o444 },
    show: blk_ia_range_nr_sectors_show,
};

static blk_ia_range_attrs: [*const attribute; 3] = [
    &blk_ia_range_sector_entry.attr,
    &blk_ia_range_nr_sectors_entry.attr,
    core::ptr::null(),
];

// Equivalent of ATTRIBUTE_GROUPS(blk_ia_range), supplied/generated by the kernel build.
extern "C" {
    static blk_ia_range_groups: *const *const attribute_group;
}

unsafe fn blk_ia_range_sysfs_show(
    kobj: *mut kobject,
    attr: *mut attribute,
    buf: *mut core::ffi::c_char,
) -> isize {
    let entry = container_of!(attr, blk_ia_range_sysfs_entry, attr);
    let iar = container_of!(kobj, blk_independent_access_range, kobj);
    ((*entry).show)(iar, buf)
}

static blk_ia_range_sysfs_ops: sysfs_ops = sysfs_ops {
    show: Some(blk_ia_range_sysfs_show),
};

/*
 * Independent access range entries are not freed individually, but alltogether
 * with struct blk_independent_access_ranges and its array of ranges. Since
 * kobject_add() takes a reference on the parent kobject contained in
 * struct blk_independent_access_ranges, the array of independent access range
 * entries cannot be freed until kobject_del() is called for all entries.
 * So we do not need to do anything here, but still need this no-op release
 * operation to avoid complaints from the kobject code.
 */
unsafe fn blk_ia_range_sysfs_nop_release(_kobj: *mut kobject) {}

static blk_ia_range_ktype: kobj_type = kobj_type {
    sysfs_ops: &blk_ia_range_sysfs_ops,
    default_groups: unsafe { &blk_ia_range_groups },
    release: Some(blk_ia_range_sysfs_nop_release),
};

/*
 * This will be executed only after all independent access range entries are
 * removed with kobject_del(), at which point, it is safe to free everything,
 * including the array of ranges.
 */
unsafe fn blk_ia_ranges_sysfs_release(kobj: *mut kobject) {
    let iars = container_of!(kobj, blk_independent_access_ranges, kobj);
    kfree(iars as *mut core::ffi::c_void);
}

static blk_ia_ranges_ktype: kobj_type = kobj_type {
    release: Some(blk_ia_ranges_sysfs_release),
};

pub unsafe fn disk_register_independent_access_ranges(disk: *mut gendisk) -> i32 {
    let mut iars = (*disk).ia_ranges;
    let q = (*disk).queue;
    let mut ret: i32;

    lockdep_assert_held(&mut (*q).sysfs_lock);
    if iars.is_null() { return 0; }

    warn_on!((*iars).sysfs_registered);
    ret = kobject_init_and_add(&mut (*iars).kobj, &blk_ia_ranges_ktype,
        &mut (*disk).queue_kobj, b"%s\0".as_ptr() as *const _, b"independent_access_ranges\0".as_ptr());
    if ret != 0 {
        (*disk).ia_ranges = core::ptr::null_mut();
        kobject_put(&mut (*iars).kobj);
        return ret;
    }
    for i in 0..(*iars).nr_ia_ranges {
        ret = kobject_init_and_add(&mut (*iars).ia_range.add(i as usize).as_mut().unwrap().kobj,
            &blk_ia_range_ktype, &mut (*iars).kobj, b"%d\0".as_ptr() as *const _, i);
        if ret != 0 {
            let mut j = i - 1;
            while j >= 0 { kobject_del(&mut (*iars).ia_range.add(j as usize).as_mut().unwrap().kobj); j -= 1; }
            kobject_del(&mut (*iars).kobj); kobject_put(&mut (*iars).kobj); return ret;
        }
    }
    (*iars).sysfs_registered = true;
    0
}

pub unsafe fn disk_unregister_independent_access_ranges(disk: *mut gendisk) {
    let q = (*disk).queue;
    let iars = (*disk).ia_ranges;
    lockdep_assert_held(&mut (*q).sysfs_lock);
    if iars.is_null() { return; }
    if (*iars).sysfs_registered {
        for i in 0..(*iars).nr_ia_ranges { kobject_del(&mut (*iars).ia_range.add(i as usize).as_mut().unwrap().kobj); }
        kobject_del(&mut (*iars).kobj); kobject_put(&mut (*iars).kobj);
    } else { kfree(iars as *mut core::ffi::c_void); }
    (*disk).ia_ranges = core::ptr::null_mut();
}

unsafe fn disk_find_ia_range(iars: *mut blk_independent_access_ranges, sector: sector_t) -> *mut blk_independent_access_range {
    for i in 0..(*iars).nr_ia_ranges {
        let iar = (*iars).ia_range.add(i as usize);
        if sector >= (*iar).sector && sector < (*iar).sector + (*iar).nr_sectors { return iar; }
    }
    core::ptr::null_mut()
}

unsafe fn disk_check_ia_ranges(disk: *mut gendisk, iars: *mut blk_independent_access_ranges) -> bool {
    if warn_on_once!((*iars).nr_ia_ranges == 0) { return false; }
    let capacity = get_capacity(disk); let mut sector: sector_t = 0;
    for i in 0..(*iars).nr_ia_ranges {
        let tmp = disk_find_ia_range(iars, sector);
        if tmp.is_null() || (*tmp).sector != sector { pr_warn!("Invalid non-contiguous independent access ranges\n"); return false; }
        let iar = (*iars).ia_range.add(i as usize);
        if tmp != iar { core::mem::swap(&mut (*iar).sector, &mut (*tmp).sector); core::mem::swap(&mut (*iar).nr_sectors, &mut (*tmp).nr_sectors); }
        sector += (*iar).nr_sectors;
    }
    if sector != capacity { pr_warn!("Independent access ranges do not match disk capacity\n"); return false; }
    true
}

unsafe fn disk_ia_ranges_changed(disk: *mut gendisk, new: *mut blk_independent_access_ranges) -> bool {
    let old = (*disk).ia_ranges;
    if old.is_null() || (*old).nr_ia_ranges != (*new).nr_ia_ranges { return true; }
    for i in 0..(*old).nr_ia_ranges {
        if (*new).ia_range.add(i as usize).read().sector != (*old).ia_range.add(i as usize).read().sector || (*new).ia_range.add(i as usize).read().nr_sectors != (*old).ia_range.add(i as usize).read().nr_sectors { return true; }
    }
    false
}

pub unsafe fn disk_alloc_independent_access_ranges(disk: *mut gendisk, nr_ia_ranges: i32) -> *mut blk_independent_access_ranges {
    let iars = kzalloc_node(struct_size!(blk_independent_access_ranges, ia_range, nr_ia_ranges), GFP_KERNEL, (*(*disk).queue).node) as *mut blk_independent_access_ranges;
    if !iars.is_null() { (*iars).nr_ia_ranges = nr_ia_ranges; }
    iars
}

pub unsafe fn disk_set_independent_access_ranges(disk: *mut gendisk, mut iars: *mut blk_independent_access_ranges) {
    let q = (*disk).queue; mutex_lock(&mut (*q).sysfs_lock);
    if !iars.is_null() && !disk_check_ia_ranges(disk, iars) { kfree(iars as *mut core::ffi::c_void); iars = core::ptr::null_mut(); }
    if !iars.is_null() && !disk_ia_ranges_changed(disk, iars) { kfree(iars as *mut core::ffi::c_void); mutex_unlock(&mut (*q).sysfs_lock); return; }
    disk_unregister_independent_access_ranges(disk); (*disk).ia_ranges = iars;
    if blk_queue_registered(q) { disk_register_independent_access_ranges(disk); }
    mutex_unlock(&mut (*q).sysfs_lock);
}

